def test_davenport_constant_and_zero_sum_subsequences():
    """
    Verify Olson's Theorem: D(F_p^m) = 1 + m(p - 1).
    Every sequence of length D contains a non-empty zero-sum subsequence.
    There exists a zero-sum free sequence of length D - 1.
    """
    test_cases = [
        (2, 2),  # D = 1 + 2(1) = 3
        (2, 3),  # D = 1 + 3(1) = 4
        (3, 1),  # D = 1 + 1(2) = 3
        (3, 2),  # D = 1 + 2(2) = 5
    ]

    for p, m in test_cases:
        D = 1 + m * (p - 1)
        all_vecs = [
            np.array(v, dtype=int)
            for v in itertools.product(range(p), repeat=m)
            if any(v)  # non-zero vectors
        ]

        # 1. Verify existence of zero-sum free sequence of length D - 1
        # Basis vector construction: repeat each standard basis vector p - 1 times
        free_seq = []
        for i in range(m):
            ei = np.zeros(m, dtype=int)
            ei[i] = 1
            for _ in range(p - 1):
                free_seq.append(ei.copy())

        assert len(free_seq) == D - 1

        # Check that no non-empty subsequence of free_seq sums to zero mod p
        has_zero_sum = False
        for r in range(1, len(free_seq) + 1):
            for combo in itertools.combinations(free_seq, r):
                if np.all(sum(combo) % p == 0):
                    has_zero_sum = True
                    break
            if has_zero_sum:
                break
        assert not has_zero_sum, f"Zero-sum free sequence of length D-1 failed for p={p}, m={m}"

        # 2. Test that adding ANY non-zero vector to free_seq creates a zero-sum subsequence
        for test_v in all_vecs[:5]:
            augmented = free_seq + [test_v]
            assert len(augmented) == D
            has_augmented_zero_sum = False
            for r in range(1, len(augmented) + 1):
                for combo in itertools.combinations(augmented, r):
                    if np.all(sum(combo) % p == 0):
                        has_augmented_zero_sum = True
                        break
                if has_augmented_zero_sum:
                    break
            assert has_augmented_zero_sum, f"Davenport bound D={D} failed to force zero-sum for p={p}, m={m}"


def test_dihedral_2group_central_intersection_failure():
    """
    Verify Theorem 2:
    In D_{2^k} = Z_{2^k} x| Z_2, every reflection H = { (0,0), (s,1) }
    satisfies H cap Z_i(D_{2^k}) = { (0,0) } for all i in {1, ..., k-1}.
    """
    for k in [3, 4, 5]:
        order_cyclic = 2**k
        # Center Z_1 is generated by (2^{k-1}, 0)
        # Z_i is generated by (2^{k-i}, 0)
        for i in range(1, k):
            step = 2 ** (k - i)
            Z_i = set((x, 0) for x in range(0, order_cyclic, step))

            # Test across multiple random shifts s
            for s in [0, 1, 3, 5, 2 ** (k - 1) - 1]:
                H = {(0, 0), (s, 1)}
                intersection = H.intersection(Z_i)
                assert intersection == {(0, 0)}, (
                    f"Violation at k={k}, level i={i}, s={s}: H cap Z_i = {intersection}"
                )


def test_trine_povm_antipodal_cancellation_and_sample_bound():
    """
    Verify Theorem 3:
    Trine POVM satisfies P(j = true_r) == 0 identically.
    Survival probability per sample is (p - 1) / p.
    Verify exact classical reconstruction of secret s from dis-equations.
    """
    np.random.seed(42)
    p = 3
    n = 3
    s_true = np.random.randint(0, p, size=n)

    # 1. Antipodal cancellation check on single qubit
    for r in range(p):
        psi_r = np.array([1, np.exp(2j * np.pi * r / p)]) / np.sqrt(2)
        # POVM state phi_j has phase 2 pi j / p + pi
        phi_r = np.array([1, np.exp(1j * (2 * np.pi * r / p + np.pi))]) / np.sqrt(2)
        overlap = np.abs(np.vdot(phi_r, psi_r)) ** 2
        assert np.isclose(overlap, 0.0), f"Antipodal overlap must be 0 for r={r}"

    # 2. Simulated measurement and secret reconstruction
    # Theoretical sample bound for epsilon = 0.01:
    epsilon = 0.01
    M_bound = int(np.ceil((n * np.log(p) + np.log(1 / epsilon)) / np.log(p / (p - 1))))

    samples = []
    for _ in range(M_bound):
        k = np.random.randint(0, p, size=n)
        if not np.any(k):
            continue
        true_r = int(np.dot(k, s_true) % p)
        # Outcome j is chosen uniformly from {x in {0, ..., p-1} : x != true_r}
        choices = [x for x in range(p) if x != true_r]
        j = np.random.choice(choices)
        samples.append((k, j))

    # Candidate filtering
    candidates = []
    for cand in itertools.product(range(p), repeat=n):
        c = np.array(cand)
        valid = True
        for k, j in samples:
            if int(np.dot(k, c) % p) == j:
                valid = False
                break
        if valid:
            candidates.append(c)

    assert len(candidates) == 1, f"Expected unique candidate, found {len(candidates)}"
    assert np.array_equal(candidates[0], s_true), "Reconstructed candidate does not match secret"


def test_carry_disruption_vs_coordinate_decoupling():
    """
    Verify Theorem 4:
    Direct product (Z_p)^n has ZERO carry leak: k1_i = k2_i = 0 => (k1 - k2)_i = 0.
    Cyclic group Z_{2^n} has carry propagation: subtraction flips higher bits with prob >= 1/2.
    """
    p = 2
    n = 6
    np.random.seed(1337)

    # 1. Direct product decoupling
    for _ in range(30):
        k1 = np.random.randint(0, p, size=n)
        k2 = np.random.randint(0, p, size=n)
        # Force coordinate 0 to be zero
        k1[0] = 0
        k2[0] = 0
        k_diff = (k1 - k2) % p
        assert k_diff[0] == 0, "Coordinate 0 must remain zero in direct product"

    # 2. Cyclic group carry propagation
    # In Z_{2^n}, if lowest b bits match, modular subtraction wraps around when k1 < k2
    m = 2**n
    b = 2
    mask = (1 << b) - 1
    carries_observed = 0
    trials = 100

    for _ in range(trials):
        k1 = np.random.randint(0, m)
        k2 = np.random.randint(0, m)
        # Force lowest b bits to match
        k2 = (k2 & ~mask) | (k1 & mask)
        assert (k1 & mask) == (k2 & mask)

        diff = (k1 - k2) % m
        assert (diff & mask) == 0  # lowest b bits are zeroed

        # Check if subtraction wrapped around (k1 < k2) inducing higher bit borrowing
        if k1 < k2:
            carries_observed += 1

    # Probability of wrap-around is approximately 1/2
    wrap_ratio = carries_observed / trials
    assert 0.35 <= wrap_ratio <= 0.65, f"Wrap-around ratio {wrap_ratio} outside expected binomial range"


def test_hadamard_linear_system_p2():
    """
    Verify polynomial quantum BQP algorithm for G = (Z_2)^n x| Z_2:
    Measuring in Hadamard basis gives <k, s> mod 2 deterministically.
    Gaussian elimination solves for s in O(n^3) time.
    """
    np.random.seed(99)
    n = 8
    s_true = np.random.randint(0, 2, size=n)

    # Collect n linearly independent vectors k_i
    K_rows = []
    b_outcomes = []

    while len(K_rows) < n:
        k = np.random.randint(0, 2, size=n)
        if not np.any(k):
            continue
        # Test independence
        test_mat = np.vstack([K_rows, [k]]) if len(K_rows) > 0 else np.array([k])
        # Rank mod 2
        import scipy.linalg
        # Simple RREF rank check
        if len(K_rows) > 0:
            current_mat = np.array(K_rows)
            # Check independence via numpy / rank
            # Over F_2:
            aug = np.vstack([current_mat, k])
            # Check rank
            # Manual GF(2) rank
            def gf2_rank(A):
                mat = A.copy() % 2
                r = 0
                for c in range(mat.shape[1]):
                    piv = -1
                    for i in range(r, len(mat)):
                        if mat[i, c] == 1:
                            piv = i
                            break
                    if piv == -1:
                        continue
                    mat[[r, piv]] = mat[[piv, r]]
                    for i in range(len(mat)):
                        if i != r and mat[i, c] == 1:
                            mat[i] = (mat[i] + mat[r]) % 2
                    r += 1
                return r

            if gf2_rank(aug) != len(K_rows) + 1:
                continue

        K_rows.append(k)
        # Hadamard measurement on (|0> + (-1)^{<k, s>} |1>)/sqrt(2) gives <k, s> mod 2 deterministically
        outcome = int(np.dot(k, s_true) % 2)
        b_outcomes.append(outcome)

    K = np.array(K_rows, dtype=int)
    b = np.array(b_outcomes, dtype=int)

    # Solve K s = b mod 2 by Gaussian elimination
    aug = np.column_stack([K, b])
    r = 0
    for c in range(n):
        piv = -1
        for i in range(r, n):
            if aug[i, c] == 1:
                piv = i
                break
        if piv == -1:
            continue
        aug[[r, piv]] = aug[[piv, r]]
        for i in range(n):
            if i != r and aug[i, c] == 1:
                aug[i] = (aug[i] + aug[r]) % 2
        r += 1

    s_recon = aug[:, -1] % 2
    assert np.array_equal(s_recon, s_true), "Reconstructed secret does not match true secret over F_2"


def test_tripartite_tractability_classification():
    """Verify classification categories and parameter bounds."""
    cases = [
        {"group": "(Z_2)^n x| Z_2", "c": 2, "p": 2, "cyclic_exp": False, "sector": "Sector I (BQP)"},
        {"group": "(Z_3)^n x| Z_2", "c": 2, "p": 3, "cyclic_exp": False, "sector": "Sector I (BQP)"},
        {"group": "D_{2^k}", "c": "k-1", "p": 2, "cyclic_exp": True, "sector": "Sector II (Sieve)"},
        {"group": "D_N", "c": "inf", "p": "var", "cyclic_exp": True, "sector": "Sector II (Sieve)"},
    ]
    for case in cases:
        if not case["cyclic_exp"] and isinstance(case["p"], int) and case["p"] <= 3:
            assert case["sector"] == "Sector I (BQP)"
        else:
            assert case["sector"] == "Sector II (Sieve)"
