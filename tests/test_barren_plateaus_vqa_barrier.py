def test_parameter_shift_rule_exactness():
    """
    Theorem 1: For any parameterized unitary gate generated by a Pauli operator
    U(theta) = exp(-i * theta * P / 2), the analytical gradient of an expectation
    value C(theta) = <0| U^dagger O U |0> is given exactly by the parameter-shift rule:
        dC / dtheta = ( C(theta + pi/2) - C(theta - pi/2) ) / 2.
    """
    # Single-qubit state |0>, rotation around Y: U(theta) = exp(-i theta Y / 2)
    # Observable O = Z
    # Analytic expectation: <0| exp(i theta Y / 2) Z exp(-i theta Y / 2) |0> = cos(theta)
    # Analytic gradient: -sin(theta)
    for theta in [0.2, 0.75, 1.45, 2.3]:
        c_plus = math.cos(theta + math.pi / 2.0)
        c_minus = math.cos(theta - math.pi / 2.0)
        grad_param_shift = (c_plus - c_minus) / 2.0
        grad_exact = -math.sin(theta)
        assert np.isclose(grad_param_shift, grad_exact, atol=1e-12)


def test_haar_measure_gradient_variance_exponential_decay():
    """
    Theorem 2 (McClean et al. 2018):
    For an n-qubit parameterized quantum circuit forming an approximate 2-design,
    the gradient of a global cost function C_global = |<0^n| U(theta) |0^n>|^2
    has zero mean E[dC/dtheta] = 0, and variance decaying exponentially as:
        Var(dC / dtheta) = Theta(1 / 4^n).
    We test the variance scaling across n = 2, 3, 4 qubits.
    """
    variances = []
    qubit_range = [2, 3, 4]

    for n in qubit_range:
        D = 2**n
        # Over Haar random unitaries, for global projector O = |0><0|,
        # the variance of dC/dtheta is given by:
        # Var = 1 / ( (D - 1) * (D + 1)^2 ) approx 1 / D^3 or 1 / (2 * (D+1)^2)
        # Using exact Weingarten integration formula:
        var_val = 2.0 / ((D + 1) * (D + 2) * (D + 3))
        variances.append(var_val)

    # Check that variance decays by at least a factor of 4 to 8 per additional qubit
    ratio_2_to_3 = variances[0] / variances[1]
    ratio_3_to_4 = variances[1] / variances[2]

    # As D doubles (D -> 2D), Var ~ 1/D^3 drops by factor of 4.7x to 5.9x (approaching 8x)
    assert ratio_2_to_3 > 4.0
    assert ratio_3_to_4 > 5.0
    # For n = 4 (D = 16), variance is under 0.0004
    assert variances[2] < 4e-4


def test_local_vs_global_cost_function_variance_contrast():
    """
    Theorem 3 (Cerezo et al. 2021):
    For local observables O_local = Z_1, at shallow depth L <= O(log n), the gradient
    variance scales polynomially Var_local = Theta(1 / poly(n)), avoiding barren plateaus.
    In contrast, global observables O_global = |0^n><0^n| exhibit exponential barren
    plateaus Var_global = O(1 / 2^{2n}) at ALL depths L >= 1.
    """
    n = 6  # 6 qubits -> D = 64
    D = 2**n

    # Global observable variance ~ 1 / D^2 = 1 / 4096 approx 2.4e-4
    var_global = 1.0 / (D**2)
    # Local observable variance at shallow depth ~ 1 / n = 1 / 6 approx 0.1667
    var_local = 1.0 / float(n)

    # Local variance is orders of magnitude larger than global variance at shallow depth
    ratio = var_local / var_global
    assert ratio > 500.0, f"Local to global ratio {ratio} should exceed 500"


def test_dynamical_lie_algebra_dimension_dilemma():
    """
    Theorem 4 (Larocca et al. 2022, Fontana et al. 2023):
    The gradient variance scales inversely with the dimension of the Dynamical
    Lie Algebra (DLA) g = Lie(i H_1, ..., i H_L):
        Var(dC / dtheta) = Theta(1 / dim(g)).
    For universal expressive ansätze:
        g = su(2^n) ==> dim(g) = 4^n - 1 (Exponential Barren Plateau).
    For classically simulable matchgate / non-interacting fermion ansätze:
        g = so(2n)  ==> dim(g) = binom(2n, 2) = n * (2n - 1) = O(n^2) (Poly dimension, in P).
    """
    for n in [3, 4, 5, 6]:
        dim_su = 4**n - 1
        dim_so = n * (2 * n - 1)

        # Full universal algebra is exponential
        assert dim_su >= 63
        # Matchgate algebra is strictly quadratic polynomial
        assert dim_so <= 66

    # For n = 6 qubits:
    # dim(su(64)) = 4^6 - 1 = 4095
    # dim(so(12)) = 6 * 11 = 66
    n = 6
    assert 4**n - 1 == 4095
    assert n * (2 * n - 1) == 66
    assert (4**n - 1) / (n * (2 * n - 1)) > 60.0


def test_noise_induced_barren_plateau_depth_decay():
    """
    Theorem 5 (Wang et al. 2021):
    In physical NISQ circuits with local depolarizing noise rate epsilon > 0,
    the gradient variance decays exponentially with circuit depth d:
        Var(dC / dtheta) <= O((1 - epsilon)^{2d}) = O(e^{-2 * epsilon * d}).
    For epsilon = 0.02 and depth d = 100, the gradient signal is suppressed by
    over 98% (decay factor < 0.02), rendering deep circuits untrainable regardless
    of ansatz locality or classical initialization.
    """
    epsilon = 0.02
    d = 100
    decay_factor = (1.0 - epsilon)**(2 * d)

    # (1 - 0.02)^200 = 0.98^200 approx 0.01758
    assert np.isclose(decay_factor, 0.98**200, atol=1e-6)
    assert decay_factor < 0.02  # > 98% signal suppression

    # For depth d = 250:
    decay_250 = (1.0 - epsilon)**(2 * 250)
    assert decay_250 < 0.0001  # > 99.99% signal extinction


