def sl2_inverse(g):
    """Compute exact 2x2 inverse for det=1 matrix."""
    return np.array([[g[1, 1], -g[0, 1]], [-g[1, 0], g[0, 0]]], dtype=float)


def sl2_conjugate(g, gamma):
    """Conjugate gamma by g in SL(2, R): g gamma g^-1."""
    return g @ gamma @ sl2_inverse(g)


def random_sl2(scale=2.0, seed=None):
    """Generate a random SL(2, R) matrix with determinant exactly 1."""
    rng = np.random.default_rng(seed)
    while True:
        m = rng.normal(0, scale, (2, 2))
        det = np.linalg.det(m)
        if abs(det) > 1e-3:
            if det < 0:
                m[0, 0] = -m[0, 0]
                m[0, 1] = -m[0, 1]
                det = np.linalg.det(m)
            return m / np.sqrt(det)


def mobius_action(g, z):
    """Action of SL(2, R) on upper half plane H^2 by Mobius transformation."""
    a, b = g[0, 0], g[0, 1]
    c, d = g[1, 0], g[1, 1]
    return (a * z + b) / (c * z + d)


def hyperbolic_distance(z1, z2):
    """Hyperbolic distance on upper half plane H^2."""
    x1, y1 = z1.real, z1.imag
    x2, y2 = z2.real, z2.imag
    delta = abs(z1 - z2) ** 2 / (2.0 * y1 * y2)
    return float(np.arccosh(1.0 + delta))


def harish_chandra_character(gamma, r):
    """Spherical principal series character for hyperbolic element in SL(2, R).

    For hyperbolic elements (|Tr| > 2), the character distribution evaluates to:
        Theta_{ir}(gamma) = cos(r * ell / 2) / sinh(ell / 2),
    where ell = 2 * arccosh(|Tr(gamma)| / 2) is the hyperbolic translation length.
    """
    tr = float(np.trace(gamma))
    abs_tr = abs(tr)
    if abs_tr > 2.0 + 1e-12:
        ell = 2.0 * float(np.arccosh(abs_tr / 2.0))
        denom = float(np.sinh(ell / 2.0))
        if denom < 1e-12:
            return 0.0
        return float(np.cos(r * ell / 2.0) / denom)
    elif abs_tr < 2.0 - 1e-12:
        # Principal series characters vanish on elliptic regular elements
        return 0.0
    else:
        # Parabolic elements form a measure-zero set with singular character distribution
        return 0.0


def plancherel_density(r):
    """Plancherel measure density for spherical principal series of SL(2, R):

    dmu(r) = (1 / (4 pi)) * r * tanh(pi * r / 2).
    """
    if r < 1e-12:
        return 0.0
    return (1.0 / (4.0 * np.pi)) * r * float(np.tanh(np.pi * r / 2.0))


def test_harish_chandra_character_conjugacy_invariance():
    """Verify that Harish-Chandra characters are class functions invariant under conjugation."""
    # Hyperbolic elements
    gamma1 = np.array([[2.0, 1.0], [3.0, 2.0]])  # Tr = 4, det = 1
    gamma2 = np.array([[3.0, 2.0], [4.0, 3.0]])  # Tr = 6, det = 1
    gamma3 = np.array([[1.5, 0.5], [1.0, 1.0]])  # Tr = 2.5, det = 1

    r_values = [0.1, 0.5, 1.0, 2.5, 5.0, 10.0]

    for seed, gamma in enumerate([gamma1, gamma2, gamma3], start=42):
        g = random_sl2(scale=2.0, seed=seed)
        gamma_conj = sl2_conjugate(g, gamma)

        # Determinant and trace preservation
        assert np.isclose(np.linalg.det(gamma_conj), 1.0, atol=1e-12)
        assert np.isclose(np.trace(gamma), np.trace(gamma_conj), atol=1e-12)

        # Translation length preservation
        ell_orig = 2.0 * np.arccosh(abs(np.trace(gamma)) / 2.0)
        ell_conj = 2.0 * np.arccosh(abs(np.trace(gamma_conj)) / 2.0)
        assert np.isclose(ell_orig, ell_conj, atol=1e-12)

        # Character evaluation invariance across continuous spectrum
        for r in r_values:
            c_orig = harish_chandra_character(gamma, r)
            c_conj = harish_chandra_character(gamma_conj, r)
            assert np.isclose(c_orig, c_conj, atol=1e-12), f"Character mismatch at r={r}: {c_orig} vs {c_conj}"


def test_weak_fourier_conjugacy_blindness():
    """Verify that weak Fourier sampling distribution is identically orientation-blind across Fuchsian conjugates."""
    # Free Fuchsian subgroup generated by two hyperbolic elements
    A = np.array([[2.0, 1.0], [1.0, 1.0]])  # Tr = 3
    B = np.array([[3.0, 2.0], [1.0, 1.0]])  # Tr = 4

    # Generate subgroup elements up to word length 3
    generators = [A, sl2_inverse(A), B, sl2_inverse(B)]
    subgroup_elements = [np.eye(2)] + generators
    for g1 in generators:
        for g2 in generators:
            subgroup_elements.append(g1 @ g2)

    # Orientation 1: canonical Gamma
    # Orientation 2: conjugate by g_rot
    g_rot = np.array([[np.cos(0.7), np.sin(0.7)], [-np.sin(0.7), np.cos(0.7)]])
    # Orientation 3: conjugate by hyperbolic shear
    g_shear = np.array([[2.0, 0.5], [1.0, 0.5]])
    g_shear /= np.sqrt(np.linalg.det(g_shear))

    subgroup_conj1 = [sl2_conjugate(g_rot, el) for el in subgroup_elements]
    subgroup_conj2 = [sl2_conjugate(g_shear, el) for el in subgroup_elements]

    # Sample Fourier density over continuous spectrum r in [0.1, 5.0]
    r_grid = np.linspace(0.1, 5.0, 50)

    def fourier_density(elements, r):
        char_sum = sum(harish_chandra_character(el, r) for el in elements)
        return plancherel_density(r) * (char_sum ** 2)

    densities_base = np.array([fourier_density(subgroup_elements, r) for r in r_grid])
    densities_conj1 = np.array([fourier_density(subgroup_conj1, r) for r in r_grid])
    densities_conj2 = np.array([fourier_density(subgroup_conj2, r) for r in r_grid])

    # Normalize to probability distributions
    p_base = densities_base / np.sum(densities_base)
    p_conj1 = densities_conj1 / np.sum(densities_conj1)
    p_conj2 = densities_conj2 / np.sum(densities_conj2)

    # TV distances
    tv1 = 0.5 * np.sum(np.abs(p_base - p_conj1))
    tv2 = 0.5 * np.sum(np.abs(p_base - p_conj2))

    assert tv1 < 1e-12, f"Weak Fourier TV distance non-zero: {tv1}"
    assert tv2 < 1e-12, f"Weak Fourier TV distance non-zero: {tv2}"

    # Mutual information is identically 0.000 bits
    mi = np.sum(np.where(p_base > 1e-15, p_base * np.log2(np.clip(p_base / p_conj1, 1e-15, None)), 0.0))
    assert abs(mi) < 1e-12


def test_plancherel_continuous_measure_properties():
    """Verify continuous Plancherel measure dmu(r) scaling and absence of discrete isolated modes."""
    # Quadratic suppression near 0: tanh(pi r / 2) ~ pi r / 2 => dmu(r) ~ (1/8) r^2
    r_small = 1e-3
    density_small = plancherel_density(r_small)
    expected_small = (1.0 / (4.0 * np.pi)) * r_small * (np.pi * r_small / 2.0)
    assert np.isclose(density_small, expected_small, rtol=1e-4)

    # Linear growth at infinity: tanh(pi r / 2) -> 1 => dmu(r) ~ (1 / 4pi) r
    r_large = 100.0
    density_large = plancherel_density(r_large)
    expected_large = (1.0 / (4.0 * np.pi)) * r_large
    assert np.isclose(density_large, expected_large, rtol=1e-4)

    # Plancherel integral diverges to infinity (non-compact group)
    r_vals = np.linspace(0.1, 100.0, 1000)
    dr = r_vals[1] - r_vals[0]
    integral_approx = np.sum([plancherel_density(r) * dr for r in r_vals])
    assert integral_approx > 300.0, f"Plancherel volume unexpectedly bounded: {integral_approx}"


def test_hyperbolic_geodesic_flow_anosov_chaos():
    """Verify exponential geodesic divergence and Lyapunov exponent lambda = 1.000 in H^2."""
    theta_0 = 0.01  # small initial angle divergence between tangent vectors at z = i
    times = np.linspace(1.0, 6.0, 6)

    # Geodesic 1: gamma_1(t) = i * exp(t) (vertical)
    # Geodesic 2: hyperbolic law of cosines from origin z = i
    # cosh(d(t)) = cosh^2(t) - sinh^2(t) * cos(theta_0)
    for t in times:
        cosh_d = np.cosh(t) ** 2 - np.sinh(t) ** 2 * np.cos(theta_0)
        d_t = np.arccosh(cosh_d)

        # For small theta_0 and moderate t, the Jacobi field approximation J(t) = theta_0 * sinh(t) holds
        jacobi = theta_0 * np.sinh(t)
        assert np.isclose(d_t, jacobi, rtol=0.15)

    # Asymptotic Lyapunov exponent lambda = lim (1/Delta t) ln(J(t2)/J(t1)) = 1.000
    t1, t2 = 25.0, 40.0
    cosh_d1 = np.cosh(t1) ** 2 - np.sinh(t1) ** 2 * np.cos(theta_0)
    cosh_d2 = np.cosh(t2) ** 2 - np.sinh(t2) ** 2 * np.cos(theta_0)
    d1 = np.arccosh(cosh_d1)
    d2 = np.arccosh(cosh_d2)

    # Difference quotient cancels initial condition log(sin(theta_0/2))
    lyapunov_rate = (d2 - d1) / (2.0 * (t2 - t1))
    assert np.isclose(lyapunov_rate, 1.0, rtol=1e-4)

    # Direct Jacobi field growth rate
    j1 = theta_0 * np.sinh(t1)
    j2 = theta_0 * np.sinh(t2)
    jacobi_lyapunov = (np.log(j2) - np.log(j1)) / (t2 - t1)
    assert np.isclose(jacobi_lyapunov, 1.0, rtol=1e-4)


def test_classical_three_point_cross_ratio_reconstruction():
    """Verify that 3 point queries in H^2 reconstruct g in PSL(2, R) in O(1) operations with machine precision."""
    # Target transformation
    g_target = np.array([[2.5, 1.2], [1.0, 0.88]])
    g_target /= np.sqrt(np.linalg.det(g_target))

    # Three base points in H^2
    z_pts = [1j, 2j, 1.0 + 1j]
    w_pts = [mobius_action(g_target, z) for z in z_pts]

    # Linear system for matrix entries [a, b, c, d]:
    # a * z + b - c * z * w - d * w = 0
    A_rows = []
    for z, w in zip(z_pts, w_pts):
        row = np.array([z, 1.0, -z * w, -w], dtype=complex)
        A_rows.append(row.real)
        A_rows.append(row.imag)

    A_mat = np.array(A_rows, dtype=float)
    _, _, vh = np.linalg.svd(A_mat)
    null_vec = vh[-1]

    a, b, c, d = null_vec
    det = a * d - b * c
    assert abs(det) > 1e-12

    scale = 1.0 / np.sqrt(abs(det))
    g_reconstructed = np.array([[a, b], [c, d]]) * scale

    # Reconstructed up to projective sign in PSL(2, R)
    err_plus = np.linalg.norm(g_reconstructed - g_target)
    err_minus = np.linalg.norm(g_reconstructed + g_target)
    min_err = min(err_plus, err_minus)

    assert min_err < 1e-12, f"PSL(2, R) reconstruction error exceeded machine tolerance: {min_err}"


