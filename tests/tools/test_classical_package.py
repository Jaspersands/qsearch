from __future__ import annotations

import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
PACKAGE = REPO / "packages" / "qsearch_classical"


def _sync():
    spec = importlib.util.spec_from_file_location("qsearch_classical_sync", PACKAGE / "sync.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


SAMPLE = '''"""Doc mentioning theorems/ stays."""
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from theorems.bpqm_gibbs_frontier import integer
from theorems.prime_character_opi import instance, ring

REPORT = ROOT/"research/classical_baselines/x.json"
a = hashlib.sha256((ROOT/"theorems/bpqm_gibbs_frontier.py").read_bytes())
b = hashlib.sha256((ROOT / "theorems/prime_character_opi.py").read_bytes())
c = {name: hashlib.sha256((ROOT/"theorems"/name).read_bytes()) for name in helpers}
'''


def test_transform_rewrites_imports_dependency_paths_and_root() -> None:
    out = _sync().transform(SAMPLE, "x")
    assert "from qsearch_classical._validators import integer" in out
    assert "from qsearch_classical.prime_character_opi import instance, ring" in out
    assert 'PACKAGE/"_validators.py"' in out and 'PACKAGE / "prime_character_opi.py"' in out
    assert 'PACKAGE/_vendored(name)' in out
    assert "sys.path.insert" not in out and 'os.environ.get("QSEARCH_CLASSICAL_ROOT"' in out
    assert 'REPORT = ROOT/"research/classical_baselines/x.json"' in out
    assert "Generated by packages/qsearch_classical/sync.py from theorems/x.py" in out.splitlines()[0]


def test_transform_rejects_an_unvendored_theorem_import() -> None:
    with pytest.raises(ValueError, match="parity_block"):
        _sync().transform("from theorems.parity_block_usd_prange import affine_system\n", "x")


def test_validators_are_extracted_verbatim() -> None:
    source = (REPO / "theorems" / "bpqm_gibbs_frontier.py").read_text()
    out = _sync().validators(source)
    namespace: dict = {}
    exec(out, namespace)
    assert namespace["integer"](3, "n", 1, 5) == 3
    with pytest.raises(ValueError):
        namespace["rational"](0.5)


def test_package_matches_upstream_sources() -> None:
    assert _sync().check(REPO) == []


REPRODUCE = r'''
import importlib, json, sys
module = importlib.import_module("qsearch_classical." + sys.argv[1])
strip = lambda d: {k: v for k, v in d.items() if "sha256" not in k and k not in ("python_flint_version", "numpy_version")}
fresh = json.loads(json.dumps(strip(module.run_controls())))
committed = strip(json.loads(module.REPORT.read_text()))
diff = sorted(k for k in set(fresh) | set(committed) if fresh.get(k) != committed.get(k))
print(json.dumps(diff))
'''


@pytest.mark.parametrize("module", [
    "prime_character_opi", "prime_character_norm_attack", "prime_character_capacity_source",
    "prime_character_finite_readout", "polar_conditional_sampler", "polar_source_design",
])
def test_package_reproduces_the_committed_report(module: str) -> None:
    pytest.importorskip("flint")
    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"} | {
        "PYTHONPATH": str(PACKAGE / "src"), "QSEARCH_CLASSICAL_ROOT": str(REPO)}
    result = subprocess.run([sys.executable, "-c", REPRODUCE, module], cwd=PACKAGE / "src", env=env,
                            capture_output=True, text=True, timeout=300)
    assert result.returncode == 0, result.stderr[-2000:]
    assert json.loads(result.stdout.strip().splitlines()[-1]) == []


def test_package_imports_without_the_repository() -> None:
    pytest.importorskip("flint")
    code = ("import sys, qsearch_classical.prime_character_finite_readout, qsearch_classical.polar_source_design, "
            "qsearch_classical.jacobi_known_norm_reduction; "
            "assert not [m for m in sys.modules if m.split('.')[0] in ('theorems', 'core')], 'repository module imported'")
    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"} | {"PYTHONPATH": str(PACKAGE / "src")}
    result = subprocess.run([sys.executable, "-c", code], cwd=PACKAGE / "src", env=env, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr[-2000:]
