"""Natural-source mass of the trivial-color wreath fusion sector.

The generic hyperoctahedral Clebsch--Gordan transform contains the ordinary
``S_m`` Kronecker transform on trivial-color irreps.  This module tests whether
that embedded sector is actually important for the hidden-involution source.

Let ``G=S_(2m)``, let ``h`` be the canonical perfect matching, let
``K=C_2 wr S_m``, and let ``N=(C_2)^m`` be the normal subgroup generated by
the individual matching swaps.  The one-copy source fiber

    R = ran((I+R_h)/2)

has the explicit ``K``-permutation basis ``C[G/<h>]`` under conjugation.  The
sum of all trivial-color ``K`` isotypic sectors is exactly ``R^N``.  If
``a in N`` flips ``t`` matching pairs, then

    chi_R(a) = |C_G(a)|/2 * (1 + 1[t=m-t]),             (1)
    |C_G(a)| = 2^t t! (2m-2t)!.

For ``k`` tensor copies, Burnside projection gives the exact source fraction

    w_(m,k) = 2^-m sum_(t=0)^m binom(m,t)
      [2^t t!(2m-2t)!/(2m)! * (1+1[2t=m])]^k.          (2)

For every ``m>=2`` the nonidentity normalized character is at most ``1/3``.
At the orbit-flatness width ``k>=m``, therefore

    w_(m,k) <= 2^-m + (1-2^-m)3^-k <= 2^(1-m).         (3)

Let ``x`` be the unnormalized orbit-synthesis Gram eigenvalue under the
uniform source law.  The exact moment theorem gives
``E[x^2]=1+(M-1)/2^k``.  Cauchy--Schwarz bounds the alternative contribution
of any source subspace of fraction ``w`` by

    Tr(rho_alt from that subspace) <= sqrt((1+eta)w).   (4)

At ``k=ceil(log2(64M))``, ``eta<=1/64``, so the entire trivial-color sector
has exponentially vanishing alternative contribution.  Thus the embedded
ordinary Kronecker transform is not a natural-source bottleneck at this copy
width.  This does not show that source-heavy colored wreath sectors are easy,
nor does it construct their fusion transform or the full matrix-Hecke polar.
"""

