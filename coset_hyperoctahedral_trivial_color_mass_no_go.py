def canonical_matching_involution(half_degree: int) -> Permutation:
    if half_degree < 1:
        raise ValueError("half_degree must be positive")
    return tuple(
        value
        for pair in range(half_degree)
        for value in (2 * pair + 1, 2 * pair)
    )


def base_subgroup_element(
    half_degree: int,
    mask: int,
) -> Permutation:
    if half_degree < 1 or not 0 <= mask < 2**half_degree:
        raise ValueError("invalid half_degree or mask")
    output = list(range(2 * half_degree))
    for pair in range(half_degree):
        if (mask >> pair) & 1:
            output[2 * pair], output[2 * pair + 1] = (
                output[2 * pair + 1],
                output[2 * pair],
            )
    return tuple(output)


def normalized_fiber_character(
    half_degree: int,
    flipped_pairs: int,
) -> Fraction:
    if half_degree < 1 or not 0 <= flipped_pairs <= half_degree:
        raise ValueError("invalid half_degree or flipped_pairs")
    degree = 2 * half_degree
    centralizer = (
        (2**flipped_pairs)
        * math.factorial(flipped_pairs)
        * math.factorial(degree - 2 * flipped_pairs)
    )
    conjugate_after_hidden = int(2 * flipped_pairs == half_degree)
    return Fraction(
        centralizer * (1 + conjugate_after_hidden),
        math.factorial(degree),
    )


def exact_trivial_color_source_fraction(
    half_degree: int,
    copy_count: int,
) -> Fraction:
    if half_degree < 1 or copy_count < 1:
        raise ValueError("half_degree and copy_count must be positive")
    return sum(
        Fraction(math.comb(half_degree, flipped_pairs), 2**half_degree)
        * normalized_fiber_character(half_degree, flipped_pairs) ** copy_count
        for flipped_pairs in range(half_degree + 1)
    )


def _conjugate(
    element: Permutation,
    value: Permutation,
) -> Permutation:
    return compose_permutations(
        compose_permutations(element, value), inverse_permutation(element)
    )


def _direct_fiber_character(
    half_degree: int,
    element: Permutation,
) -> int:
    group = symmetric_group(2 * half_degree)
    hidden = canonical_matching_involution(half_degree)
    unseen = set(group)
    representatives = []
    while unseen:
        representative = min(unseen)
        representatives.append(representative)
        unseen.discard(representative)
        unseen.discard(compose_permutations(representative, hidden))
    return sum(
        min(
            _conjugate(element, representative),
            compose_permutations(
                _conjugate(element, representative), hidden
            ),
        )
        == representative
        for representative in representatives
    )


def audit_trivial_color_mass(
    half_degree: int,
    copy_count: int,
) -> TrivialColorMassFiniteControl:
    if half_degree < 1 or half_degree > 3:
        raise ValueError("finite control supports half_degree in [1,3]")
    if copy_count < 1:
        raise ValueError("copy_count must be positive")
    group_order = math.factorial(2 * half_degree)
    fiber_dimension = group_order // 2
    mismatch = 0
    direct_characters = []
    for mask in range(2**half_degree):
        element = base_subgroup_element(half_degree, mask)
        direct = _direct_fiber_character(half_degree, element)
        flipped = mask.bit_count()
        predicted = (
            normalized_fiber_character(half_degree, flipped)
            * fiber_dimension
        )
        if predicted.denominator != 1 or direct != predicted.numerator:
            mismatch += 1
        direct_characters.append(direct)
    invariant_dimension = sum(
        character**copy_count for character in direct_characters
    ) // (2**half_degree)
    tensor_dimension = fiber_dimension**copy_count
    direct_fraction = Fraction(invariant_dimension, tensor_dimension)
    formula_fraction = exact_trivial_color_source_fraction(
        half_degree, copy_count
    )
    residual = abs(float(direct_fraction - formula_fraction))
    verified = bool(
        mismatch == 0 and direct_fraction == formula_fraction and residual == 0.0
    )
    return TrivialColorMassFiniteControl(
        half_degree=half_degree,
        degree=2 * half_degree,
        copy_count=copy_count,
        group_order=group_order,
        base_subgroup_order=2**half_degree,
        one_copy_fiber_dimension=fiber_dimension,
        direct_character_mismatch_count=mismatch,
        exact_invariant_dimension_decimal=str(invariant_dimension),
        exact_tensor_fiber_dimension_decimal=str(tensor_dimension),
        exact_source_fraction=float(direct_fraction),
        character_formula_source_fraction=float(formula_fraction),
        source_fraction_residual=residual,
        exact_burnside_formula_verified=verified,
        status=(
            "exact-trivial-color-source-mass-verified"
            if verified
            else "trivial-color-mass-control-failure"
        ),
    )


def _logsumexp(values: list[float]) -> float:
    maximum = max(values)
    return maximum + math.log(sum(math.exp(value - maximum) for value in values))


def _source_fraction_log(half_degree: int, copy_count: int) -> float:
    degree = 2 * half_degree
    terms = []
    for flipped in range(half_degree + 1):
        log_combination = (
            math.lgamma(half_degree + 1)
            - math.lgamma(flipped + 1)
            - math.lgamma(half_degree - flipped + 1)
        )
        log_character = (
            flipped * math.log(2.0)
            + math.lgamma(flipped + 1)
            + math.lgamma(degree - 2 * flipped + 1)
            - math.lgamma(degree + 1)
        )
        if 2 * flipped == half_degree:
            log_character += math.log(2.0)
        terms.append(log_combination + copy_count * log_character)
    return _logsumexp(terms) - half_degree * math.log(2.0)


def trivial_color_mass_scaling_record(
    half_degree: int,
) -> TrivialColorMassScalingRecord:
    if half_degree < 2:
        raise ValueError("half_degree must be at least two")
    matchings = perfect_matching_count(half_degree)
    copies = flatness_copy_count(matchings)
    log_source = _source_fraction_log(half_degree, copies)
    source_fraction = math.exp(log_source)
    elementary_bound = 2.0 ** (-half_degree) + (
        1.0 - 2.0 ** (-half_degree)
    ) * 3.0 ** (-copies)
    eta = (matchings - 1) / (2**copies)
    alternative_bound = math.sqrt((1.0 + eta) * source_fraction)
    return TrivialColorMassScalingRecord(
        half_degree=half_degree,
        degree=2 * half_degree,
        perfect_matching_count_decimal=str(matchings),
        copy_count=copies,
        exact_source_fraction=source_fraction,
        exact_source_fraction_log2=log_source / math.log(2.0),
        elementary_source_fraction_upper_bound=elementary_bound,
        alternative_contribution_upper_bound=alternative_bound,
        alternative_contribution_log2_upper_bound=math.log2(
            alternative_bound
        ),
        embedded_kronecker_sector_has_constant_alternative_mass=False,
        generic_wreath_cg_is_natural_source_bottleneck=False,
        colored_source_fusion_compiled=False,
        status="trivial-color-sector-negligible-colored-fusion-open",
    )


