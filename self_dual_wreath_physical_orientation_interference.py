def _kron_all(matrices: tuple[np.ndarray, ...]) -> np.ndarray:
    output = matrices[0]
    for matrix in matrices[1:]:
        output = np.kron(output, matrix)
    return output


def _independent_binary_basis(
    copy_count: int,
    generators: tuple[int, ...],
) -> tuple[int, ...]:
    if copy_count < 1:
        raise ValueError("copy_count must be positive")
    if not generators:
        raise ValueError("at least one orientation generator is required")
    limit = 1 << copy_count
    if any(generator <= 0 or generator >= limit for generator in generators):
        raise ValueError("orientation generator out of range")

    pivots: dict[int, int] = {}

    def add(vector: int) -> bool:
        reduced = vector
        while reduced:
            pivot = reduced.bit_length() - 1
            if pivot in pivots:
                reduced ^= pivots[pivot]
            else:
                pivots[pivot] = reduced
                return True
        return False

    basis: list[int] = []
    for generator in generators:
        if not add(generator):
            raise ValueError("orientation generators must be independent")
        basis.append(generator)
    for index in range(copy_count):
        candidate = 1 << index
        if add(candidate):
            basis.append(candidate)
    if len(basis) != copy_count:
        raise ArithmeticError("failed to extend orientation basis")
    return tuple(basis)


def orientation_subspace_transform(
    copy_count: int,
    generators: tuple[int, ...],
) -> tuple[np.ndarray, np.ndarray, tuple[int, ...]]:
    """Return branch transform, accepted-character diagonal, and basis."""

    basis = _independent_binary_basis(copy_count, generators)
    subspace_dimension = len(generators)
    count = 1 << copy_count
    coordinate_to_mask = []
    for coordinate in range(count):
        mask = 0
        for index, vector in enumerate(basis):
            if coordinate & (1 << index):
                mask ^= vector
        coordinate_to_mask.append(mask)
    mask_to_coordinate = {
        mask: coordinate for coordinate, mask in enumerate(coordinate_to_mask)
    }
    transform = np.zeros((count, count))
    normalization = 2 ** (-subspace_dimension / 2)
    low_mask = (1 << subspace_dimension) - 1
    for orientation in range(count):
        coordinate = mask_to_coordinate[orientation]
        source_h = coordinate & low_mask
        quotient = coordinate >> subspace_dimension
        for character in range(1 << subspace_dimension):
            output_coordinate = character | (quotient << subspace_dimension)
            sign = -1 if (character & source_h).bit_count() % 2 else 1
            transform[output_coordinate, orientation] = sign * normalization
    accepted = np.asarray(
        [1.0 if coordinate & low_mask else 0.0 for coordinate in range(count)]
    )
    return transform, accepted, basis


def _branch_major_reordering(
    carrier_dimensions: tuple[int, ...],
) -> np.ndarray:
    copy_count = len(carrier_dimensions)
    branch_count = 1 << copy_count
    carrier_dimension = math.prod(carrier_dimensions)
    factor_dimensions = tuple(2 * dimension for dimension in carrier_dimensions)
    total = branch_count * carrier_dimension
    reordering = np.zeros((total, total))
    for physical_index in range(total):
        remainder = physical_index
        local_indices = [0] * copy_count
        for index in range(copy_count - 1, -1, -1):
            local_indices[index] = remainder % factor_dimensions[index]
            remainder //= factor_dimensions[index]
        orientation = 0
        carrier_index = 0
        for index, (local, dimension) in enumerate(
            zip(local_indices, carrier_dimensions)
        ):
            branch = local // dimension
            carrier = local % dimension
            orientation |= branch << index
            carrier_index = carrier_index * dimension + carrier
        branch_major = orientation * carrier_dimension + carrier_index
        reordering[physical_index, branch_major] = 1.0
    return reordering


def _physical_orientation_operators(
    labels: tuple[Label, ...],
    generators: tuple[int, ...],
) -> tuple[np.ndarray, np.ndarray]:
    carrier_dimensions = tuple(
        hook_length_dimension(left) * hook_length_dimension(right)
        for left, right in labels
    )
    alignments = []
    for (left, right), dimension in zip(labels, carrier_dimensions):
        left_dimension = hook_length_dimension(left)
        right_dimension = hook_length_dimension(right)
        flip = rectangular_tensor_flip(left_dimension, right_dimension)
        zero = np.zeros((dimension, dimension))
        alignments.append(
            np.block([[np.eye(dimension), zero], [zero, flip]])
        )
    alignment = _kron_all(tuple(alignments))
    reordering = _branch_major_reordering(carrier_dimensions)
    branch_transform, accepted, _ = orientation_subspace_transform(
        len(labels), generators
    )
    carrier_dimension = math.prod(carrier_dimensions)
    aligned_transform = (
        reordering
        @ np.kron(branch_transform, np.eye(carrier_dimension))
        @ reordering.T
    )
    aligned_accept = (
        reordering
        @ np.kron(np.diag(accepted), np.eye(carrier_dimension))
        @ reordering.T
    )
    return (
        alignment @ aligned_transform @ alignment.T,
        alignment @ aligned_accept @ alignment.T,
    )


def _orientation_cosets(
    copy_count: int,
    generators: tuple[int, ...],
) -> tuple[tuple[int, ...], ...]:
    basis = _independent_binary_basis(copy_count, generators)
    r = len(generators)
    cosets = []
    for quotient in range(1 << (copy_count - r)):
        base = 0
        for index in range(copy_count - r):
            if quotient & (1 << index):
                base ^= basis[r + index]
        masks = []
        for coordinate in range(1 << r):
            mask = base
            for index in range(r):
                if coordinate & (1 << index):
                    mask ^= basis[index]
            masks.append(mask)
        cosets.append(tuple(masks))
    return tuple(cosets)


def audit_physical_orientation_filter(
    n: int,
    labels: tuple[Label, ...],
    generators: tuple[int, ...],
    *,
    control_id: str,
    tolerance: float = 1e-9,
) -> PhysicalOrientationFilterControl:
    copy_count = len(labels)
    transform, accepted = _physical_orientation_operators(labels, generators)
    frame = _direct_frame(labels)
    subgroup_rows = tuple_left_subgroup_matrices(labels)
    sector_projectors = []
    kraus = []
    trace_residual = 0.0
    cosets = _orientation_cosets(copy_count, generators)
    weight = len(cosets[0]) / (1 << copy_count)
    for target in integer_partitions(n):
        projector = _isotypic_projector(n, target, subgroup_rows)
        if float(np.trace(projector).real) <= tolerance:
            continue
        sector_projectors.append(projector)
        operator = accepted @ transform @ projector
        kraus.append(operator)
        physical_trace = float(
            np.trace(operator @ frame @ operator.T.conj()).real
        )
        dual_trace = 0.0
        for coset in cosets:
            projectors = tuple(
                orientation_invariant_projector(target, labels, mask)
                for mask in coset
            )
            coset_frame = sum(projectors) / len(projectors)
            dual_trace += float(
                np.trace(coset_frame - coset_frame @ coset_frame).real
            )
        expected_trace = (
            hook_length_dimension(target) * weight * dual_trace
        )
        trace_residual = max(
            trace_residual,
            abs(physical_trace - expected_trace),
        )

    resolution = sum(
        sector_projectors,
        np.zeros_like(frame),
    )
    resolution_residual = float(
        np.linalg.norm(resolution - np.eye(frame.shape[0]), ord=2)
    )
    filter_effect = sum(
        (operator.T.conj() @ operator for operator in kraus),
        np.zeros_like(frame),
    )
    effect_eigenvalues = np.linalg.eigvalsh(
        (filter_effect + filter_effect.T.conj()) / 2
    )
    filtered_frame = sum(
        (operator @ frame @ operator.T.conj() for operator in kraus),
        np.zeros_like(frame),
    )
    retained = float(np.trace(filtered_frame).real / np.trace(frame).real)

    subgroup = tuple(matrix for _, matrix in subgroup_rows)
    covariant_effect = sum(
        matrix @ filter_effect @ matrix.T.conj() for matrix in subgroup
    ) / len(subgroup)
    hidden_projectors = []
    for bridge_tuple in _bridge_tables(labels):
        hidden_projectors.append(
            _kron_all(
                tuple(
                    (np.eye(bridge.shape[0]) + bridge) / 2
                    for bridge in bridge_tuple
                )
            )
        )
    hidden_rank = round(float(np.trace(hidden_projectors[0]).real))
    acceptances = [
        float(np.trace(covariant_effect @ projector).real / hidden_rank)
        for projector in hidden_projectors
    ]
    frame_top = float(np.linalg.eigvalsh(frame)[-1])
    filtered_top = float(np.linalg.eigvalsh(filtered_frame)[-1])
    spread = max(acceptances) - min(acceptances)
    verified = (
        trace_residual <= 100 * tolerance
        and resolution_residual <= 100 * tolerance
        and float(effect_eigenvalues[0]) >= -100 * tolerance
        and float(effect_eigenvalues[-1]) <= 1 + 100 * tolerance
        and spread <= 100 * tolerance
        and abs(sum(acceptances) / len(acceptances) - retained)
        <= 100 * tolerance
    )
    return PhysicalOrientationFilterControl(
        control_id=control_id,
        n=n,
        labels=labels,
        orientation_generators=generators,
        copy_count=copy_count,
        orientation_subspace_dimension=len(generators),
        orientation_subspace_size=1 << len(generators),
        orientation_quotient_size=1 << (copy_count - len(generators)),
        physical_dimension=frame.shape[0],
        hidden_label_count=len(hidden_projectors),
        hidden_projector_rank=hidden_rank,
        active_isotypic_sector_count=len(sector_projectors),
        retained_average_trace_fraction=retained,
        covariantized_minimum_hidden_acceptance=min(acceptances),
        covariantized_maximum_hidden_acceptance=max(acceptances),
        covariantized_acceptance_spread=spread,
        frame_top_eigenvalue_before=frame_top,
        filtered_frame_top_eigenvalue_after=filtered_top,
        filtered_top_to_original_ratio=filtered_top / frame_top,
        maximum_filter_effect_eigenvalue=float(effect_eigenvalues[-1]),
        minimum_filter_effect_eigenvalue=float(effect_eigenvalues[0]),
        maximum_sector_trace_transfer_residual=trace_residual,
        maximum_isotypic_projector_resolution_residual=resolution_residual,
        exact_physical_trace_transfer_verified=verified,
        status=(
            "exact-direct-physical-orientation-interference"
            if verified
            else "physical-orientation-interference-validation-failure"
        ),
    )


def physical_filter_scaling_record(
    n: int,
    illustrative_sellke_block_size: int = 8,
) -> PhysicalOrientationFilterScalingRecord:
    if n < 3:
        raise ValueError("n must be at least three")
    copies = math.ceil(math.lgamma(n + 1) / math.log(2))
    subspace_dimension = copies // illustrative_sellke_block_size
    return PhysicalOrientationFilterScalingRecord(
        n=n,
        information_threshold_copy_count=copies,
        illustrative_sellke_block_size=illustrative_sellke_block_size,
        orientation_subspace_dimension=subspace_dimension,
        quotient_qubit_count=copies - subspace_dimension,
        binary_transform_gate_upper_bound=copies * copies,
        symmetric_group_isotypic_measurement_polynomial=True,
        direct_physical_carrier_operation=True,
        synthesis_adjoint_used=False,
        factorial_amplitude_amplification_required=False,
        all_n_retained_information_proved=True,
        postfilter_polynomial_frame_norm_proved=False,
        status="polynomial-physical-filter-schema-asymptotic-analysis-open",
    )


