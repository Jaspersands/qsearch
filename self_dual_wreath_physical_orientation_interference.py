"""Direct physical orientation-subspace interference filter.

An unequal wreath irrep has an explicit two-branch induced carrier.  After a
known rectangular-flip alignment, a k-copy collision-free carrier is

    C[F_2^k] tensor C,

the base bridge projector is ``|+><+|^(tensor k) tensor I``, and the diagonal
``S_n`` action is block diagonal in the orientation string.

Let ``H <= F_2^k`` be generated by selected orientation directions.  The
following operation acts directly on the physical hidden-state carrier:

1. coherently measure the diagonal ``S_n`` isotypic label ``nu``;
2. change orientation coordinates to ``H`` plus a quotient complement;
3. Hadamard-transform the ``H`` coordinates;
4. accept a nontrivial ``H`` character.

For each target ``nu`` and orientation coset ``q+H``, put

    F_(nu,q+H) = |H|^-1 sum_(h in H) E_(nu,q+h).

The accepted physical trace obeys the exact transfer identity

    Tr(K_(nu,H) B K_(nu,H)^*)
      = d_nu |H|/2^k sum_q Tr(F_(nu,q+H)-F_(nu,q+H)^2).

Thus every exact common range within a selected coset is rejected at unit
scale, without entering the orbit-Gram domain through the factorially weak
synthesis adjoint.  Uniform random conjugation covariantizes the filter and
equalizes its acceptance across hidden labels.

All operations have polynomial circuit schemas: branch flips, a binary
linear transform, Hadamards, the symmetric-group isotypic measurement, and
reversible random conjugation.  The companion Plancherel retention theorem
proves near-unit acceptance and constant retained identification information
on typical natural tuples.  A postfilter frame-norm theorem and polynomial
decoder remain open.
"""

