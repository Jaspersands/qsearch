"""The connected orientation group has an easy class-two parity quotient.

After syndrome canonicalization the orientation incidence lives in

    L=<B,D>=N semidirect B,

where ``N`` contains an independent ``A_n`` on every one of the ``2K+1``
target/source coordinates.  Let

    A = A_n^(2K+1).

The quotient ``P_K=L/A`` is generated by

* ``a``: the zero-orientation sign vector;
* ``b_i``: swap of source pair ``i``;
* ``c_i``: simultaneous odd parity in both entries of pair ``i``.

Its defining relations are

    a^2=b_i^2=c_i^2=1,
    [a,b_i]=c_i,
    all c_i central,
    [b_i,b_j]=1.                                        (1)

Thus ``|P_K|=2^(2K+1)``, its center and derived subgroup are both
``<c_1,...,c_K>`` of order ``2^K``, and its abelianization has order
``2^(K+1)``.  It is a multi-center Heisenberg/dihedral-type class-two group.

The complete irrep dimensions follow from the commutator form.  There are

    2^(K+1) one-dimensional irreps,
    (2^K-1) 2^(K-1) two-dimensional irreps,              (2)

and no larger irreps.  Indeed, a nonzero central character ``theta`` gives a
rank-two alternating commutator form

    omega_theta((a,b),(a',b'))=a theta.b' + a' theta.b,

whose radical has dimension ``K-1``.  Its radical characters index the
``2^(K-1)`` two-dimensional irreps over that ``theta``.  Equation (2) obeys
the exact sum-of-squares identity ``|P_K|``.

Consequently every sign/branch quotient degree can be Fourier transformed by
binary linear algebra and one-qubit Pauli/Hadamard blocks.  The quotient is
not the missing high-rank transform.  The homogeneous native-rank theorem
places almost all regular-master frame mass in occupied CS blocks of rank at
least ``|S_n|^(K/4)``, while every quotient irrep has dimension at most two.
The unresolved multiplicity must therefore remain in the
``A_n^(2K+1)`` orbit/stabilizer and many-way subduction spaces.

This does not prove that the residual alternating-group recoupling is hard.
For non-self-conjugate partitions, restriction from ``S_n`` to ``A_n`` is
irreducible and odd conjugation only changes the extension gauge; for
self-conjugate partitions it swaps the two split constituents.  A uniform
Clifford-theory/QFT construction for the full semidirect product ``L`` may be
possible.  But merely finishing the easy quotient QFT cannot implement the
matrix CS polar or alter its principal-angle normalization.

No complete ``L`` QFT, fixed-space polar, decoder, classical separation, or
speedup is claimed.
"""

