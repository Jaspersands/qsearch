def parity_quotient_elements(copy_count: int) -> tuple[ParityElement, ...]:
    if copy_count < 1:
        raise ValueError("copy count must be positive")
    return tuple(
        (a, central, branch)
        for a in (0, 1)
        for central in range(1 << copy_count)
        for branch in range(1 << copy_count)
    )


def parity_quotient_multiply(
    left: ParityElement,
    right: ParityElement,
) -> ParityElement:
    left_a, left_central, left_branch = left
    right_a, right_central, right_branch = right
    return (
        left_a ^ right_a,
        left_central ^ right_central ^ (left_branch if right_a else 0),
        left_branch ^ right_branch,
    )


def parity_quotient_inverse(element: ParityElement) -> ParityElement:
    a, central, branch = element
    return a, central ^ (branch if a else 0), branch


def parity_quotient_commutator(
    left: ParityElement,
    right: ParityElement,
) -> ParityElement:
    return parity_quotient_multiply(
        parity_quotient_multiply(
            parity_quotient_multiply(
                parity_quotient_inverse(left),
                parity_quotient_inverse(right),
            ),
            left,
        ),
        right,
    )


def _conjugacy_classes(
    elements: tuple[ParityElement, ...],
) -> tuple[frozenset[ParityElement], ...]:
    remaining = set(elements)
    classes: list[frozenset[ParityElement]] = []
    while remaining:
        element = next(iter(remaining))
        conjugates = frozenset(
            parity_quotient_multiply(
                parity_quotient_multiply(group_element, element),
                parity_quotient_inverse(group_element),
            )
            for group_element in elements
        )
        classes.append(conjugates)
        remaining.difference_update(conjugates)
    return tuple(classes)


def audit_parity_quotient(copy_count: int) -> ParityQuotientControl:
    elements = parity_quotient_elements(copy_count)
    identity = (0, 0, 0)
    center = tuple(
        element
        for element in elements
        if all(
            parity_quotient_multiply(element, other)
            == parity_quotient_multiply(other, element)
            for other in elements
        )
    )
    commutators = {
        parity_quotient_commutator(left, right)
        for left in elements
        for right in elements
    }
    # Every commutator is central and commutators [a,b_i] generate all c_i.
    derived = {identity}
    changed = True
    while changed:
        changed = False
        for left in tuple(derived):
            for right in commutators:
                product = parity_quotient_multiply(left, right)
                if product not in derived:
                    derived.add(product)
                    changed = True
    classes = _conjugacy_classes(elements)
    one_dimensional = 1 << (copy_count + 1)
    two_dimensional = ((1 << copy_count) - 1) * (1 << (copy_count - 1))
    predicted_irreps = one_dimensional + two_dimensional
    square_sum = one_dimensional + 4 * two_dimensional
    class_two = all(commutator in center for commutator in commutators)
    verified = bool(
        len(elements) == 1 << (2 * copy_count + 1)
        and len(center) == 1 << copy_count
        and len(derived) == 1 << copy_count
        and class_two
        and len(classes) == predicted_irreps
        and square_sum == len(elements)
    )
    return ParityQuotientControl(
        copy_count=copy_count,
        group_order=len(elements),
        predicted_group_order=1 << (2 * copy_count + 1),
        center_order=len(center),
        predicted_center_order=1 << copy_count,
        derived_subgroup_order=len(derived),
        predicted_derived_subgroup_order=1 << copy_count,
        nilpotency_class_at_most_two=class_two,
        conjugacy_class_count=len(classes),
        predicted_irrep_count=predicted_irreps,
        one_dimensional_irrep_count=one_dimensional,
        two_dimensional_irrep_count=two_dimensional,
        maximum_irrep_dimension=2,
        irrep_dimension_square_sum=square_sum,
        exact_parity_quotient_classification_verified=verified,
        status=(
            "exact-class-two-parity-quotient-irrep-classification"
            if verified
            else "parity-quotient-control-failure"
        ),
    )


def connected_quotient_scaling_record(n: int) -> ConnectedQuotientScalingRecord:
    occupied = native_occupied_rank_scaling_record(n)
    copy_count = occupied.copy_count
    two_dimensional = ((1 << copy_count) - 1) * (1 << (copy_count - 1))
    return ConnectedQuotientScalingRecord(
        n=n,
        copy_count=copy_count,
        parity_quotient_order_log2=2 * copy_count + 1,
        parity_quotient_center_order_log2=copy_count,
        one_dimensional_irrep_count_log2=copy_count + 1,
        two_dimensional_irrep_count_log2=math.log2(two_dimensional),
        maximum_parity_quotient_irrep_dimension=2,
        native_occupied_cs_rank_threshold_log2=occupied.occupied_rank_threshold_log2,
        quotient_irrep_to_occupied_rank_log2_ratio=(
            1.0 - occupied.occupied_rank_threshold_log2
        ),
        parity_quotient_qft_polynomial=True,
        alternating_product_qft_polynomial=True,
        full_connected_group_clifford_transform_compiled=False,
        matrix_cs_polar_compiled=False,
        status="easy-parity-quotient-residual-alternating-recoupling-open",
    )


