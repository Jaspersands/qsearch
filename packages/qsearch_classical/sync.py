"""Regenerate the vendored solver modules from theorems/, or check that they still match.

    python packages/qsearch_classical/sync.py           # rewrite src/qsearch_classical/*.py
    python packages/qsearch_classical/sync.py --check   # exit 1 and list files that drifted

Reads theorems/*.py as text and never imports them. Each module is copied with four
mechanical rewrites:

1. `from theorems.X import` becomes `from qsearch_classical.X import`;
2. the two validators imported from theorems/bpqm_gibbs_frontier.py come from a generated
   `_validators.py`, so the package does not pull in the BPQM frontier and its imports;
3. the `sys.path` block goes; ROOT, under which reports are read and written
   (`research/classical_baselines/...`), comes from $QSEARCH_CLASSICAL_ROOT and defaults
   to the current directory;
4. dependency hashes read the vendored copies (`PACKAGE/"x.py"`) instead of theorems/.

A theorems/ import outside MODULES is an error, so a new upstream dependency surfaces as
a failing parity test instead of a broken install.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE / "src" / "qsearch_classical"
MODULES = (
    "prime_character_opi",
    "prime_character_norm_attack",
    "prime_character_morse_attack",
    "prime_character_exterior_bound",
    "prime_character_capacity_source",
    "prime_character_finite_readout",
    "polar_conditional_sampler",
    "polar_source_design",
    "jacobi_surface_reconstruction",
    "jacobi_known_norm_reduction",
)
VALIDATOR_SOURCE = "bpqm_gibbs_frontier"
VALIDATORS = ("rational", "integer")

_PATH_BLOCK = re.compile(
    r"ROOT = Path\(__file__\)\.resolve\(\)\.parents\[1\]\n"
    r"if str\(ROOT\) not in sys\.path:\n"
    r"    sys\.path\.insert\(0, str\(ROOT\)\)\n"
)
_NEW_ROOT = (
    "import os\n"
    "PACKAGE = Path(__file__).resolve().parent\n"
    'ROOT = Path(os.environ.get("QSEARCH_CLASSICAL_ROOT", ".")).resolve()\n'
    "\n\n"
    "def _vendored(name):\n"
    f'    return "_validators.py" if name == "{VALIDATOR_SOURCE}.py" else name\n'
)


def _header(name: str) -> str:
    return f"# Generated by packages/qsearch_classical/sync.py from theorems/{name}.py. Do not edit; run sync.py.\n"


def transform(text: str, name: str) -> str:
    out, count = _PATH_BLOCK.subn(_NEW_ROOT, text)
    if count > 1:
        raise ValueError(f"{name}: more than one sys.path block")

    def rewrite_import(match: re.Match) -> str:
        module = match.group(1)
        if module == VALIDATOR_SOURCE:
            return "from qsearch_classical._validators import"
        if module not in MODULES:
            raise ValueError(f"{name}: imports theorems.{module}, which the package does not vendor")
        return f"from qsearch_classical.{module} import"

    out = re.sub(r"from theorems\.(\w+) import", rewrite_import, out)
    bad = re.findall(r"^\s*import theorems\b.*$", out, flags=re.M)
    if bad:
        raise ValueError(f"{name}: unsupported import form {bad[0]!r}")

    def rewrite_path(match: re.Match) -> str:
        module, spacing = match.group(2), match.group(1)
        if module == VALIDATOR_SOURCE:
            return f'PACKAGE{spacing}"_validators.py"'
        if module not in MODULES:
            raise ValueError(f"{name}: hashes theorems/{module}.py, which the package does not vendor")
        return f'PACKAGE{spacing}"{module}.py"'

    out = re.sub(r'ROOT(\s*/\s*)"theorems/(\w+)\.py"', rewrite_path, out)
    out = re.sub(r'ROOT\s*/\s*"theorems"\s*/\s*(\w+)', r"PACKAGE/_vendored(\1)", out)
    if re.search(r'ROOT\s*/\s*"theorems', out):
        raise ValueError(f"{name}: unhandled theorems/ path")
    return _header(name) + out


def validators(source: str) -> str:
    tree = ast.parse(source)
    parts = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in VALIDATORS:
            parts.append(ast.get_source_segment(source, node))
    if len(parts) != len(VALIDATORS):
        raise ValueError(f"expected {VALIDATORS} in theorems/{VALIDATOR_SOURCE}.py")
    return (_header(VALIDATOR_SOURCE) + '"""Exact-input validators copied from the BPQM frontier module."""\n\n'
            "from fractions import Fraction\n\n\n" + "\n\n\n".join(parts) + "\n")


def generate(repo: Path) -> dict[str, str]:
    files = {f"{name}.py": transform((repo / "theorems" / f"{name}.py").read_text(encoding="utf-8"), name) for name in MODULES}
    files["_validators.py"] = validators((repo / "theorems" / f"{VALIDATOR_SOURCE}.py").read_text(encoding="utf-8"))
    return files


def check(repo: Path, target: Path = TARGET) -> list[str]:
    drift = []
    for filename, text in generate(repo).items():
        path = target / filename
        if not path.exists():
            drift.append(f"missing {filename}")
        elif path.read_text(encoding="utf-8") != text:
            drift.append(f"differs {filename}")
    return drift


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=HERE.parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        drift = check(args.repo)
        for line in drift:
            print(line)
        return 1 if drift else 0
    TARGET.mkdir(parents=True, exist_ok=True)
    for filename, text in generate(args.repo).items():
        (TARGET / filename).write_text(text, encoding="utf-8")
    print(f"wrote {len(MODULES) + 1} modules to {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
