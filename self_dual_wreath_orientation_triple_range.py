"""Triple and fixed-family common ranges for orientation projectors.

For ``m`` orientations, group every selected representation factor by its
nonempty membership pattern ``S subseteq {1,...,m}``: the orientations in
``S`` are exactly those whose diagonal action reaches that factor.  The target
irrep belongs to the full membership pattern.  Factors selected by no
orientation are pure companion multiplicities.

For ``n>=5``, the alternating group ``A_n`` is nonabelian simple.  The subgroup
generated by the orientation diagonals contains an independent ``A_n`` on
every distinct nonempty membership pattern.  A common invariant therefore
requires each pattern tensor ``R_S`` to land in a trivial or sign sector.  If
``x_S`` records that choice, the residual parity action is trivial exactly
when

    sum_{S containing j} x_S = 0 mod 2

for every orientation ``j``.  Hence

    dim(intersection_j Ran E_j)
      = d_companion * sum_{x in ker(M)} product_S m_S(sign^x_S).

This is an exact fixed-family formula.  Exact counting over all orientation
triples is a separate problem: the naive Kronecker-support dynamic program has
seven coupled support states and grows rapidly.  This module records that
complexity boundary and uses deterministic uniform sampling, with Wilson
confidence intervals, only to test whether triple intersections appear rare
on threshold portfolios.  Sampling is never promoted to an all-triples
theorem or an operator-norm bound.
"""

