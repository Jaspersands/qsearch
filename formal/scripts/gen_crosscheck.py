"""Regenerate Formal/CrossCheck.lean from the Python mirror.

The function `exterior_characters` is taken from
theorems/prime_character_exterior_bound.py by parsing that file with `ast`
and executing only that one function definition. The module itself is not
imported, so its FLINT and solver dependencies are not needed.

Usage (from the repository root):

    python formal/scripts/gen_crosscheck.py            # rewrite the Lean file
    python formal/scripts/gen_crosscheck.py --check    # fail if it is stale
"""

from __future__ import annotations

import argparse
import ast
import hashlib
from pathlib import Path
import sys

FORMAL = Path(__file__).resolve().parents[1]
ROOT = FORMAL.parent
SOURCE = ROOT / "theorems" / "prime_character_exterior_bound.py"
TARGET = FORMAL / "Formal" / "CrossCheck.lean"
MAX_N = 7


def load_exterior_characters():
    text = SOURCE.read_text()
    tree = ast.parse(text)
    nodes = [node for node in tree.body
             if isinstance(node, ast.FunctionDef) and node.name == "exterior_characters"]
    if len(nodes) != 1:
        raise SystemExit("exterior_characters not found exactly once")
    module = ast.Module(body=nodes, type_ignores=[])
    namespace: dict = {}
    exec(compile(module, str(SOURCE), "exec"), namespace)
    return namespace["exterior_characters"], hashlib.sha256(text.encode()).hexdigest(), nodes[0].lineno


def partitions(n, largest=None):
    """Partitions of n as non-increasing lists of positive integers."""
    if largest is None:
        largest = n
    if n == 0:
        yield []
        return
    for first in range(min(n, largest), 0, -1):
        for rest in partitions(n - first, first):
            yield [first] + rest


def lean_list(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def render(exterior_characters, digest, lineno):
    rows = []
    for n in range(1, MAX_N + 1):
        for lengths in partitions(n):
            chars = exterior_characters(lengths)
            alternating = sum((-1) ** j * c for j, c in enumerate(chars))
            if alternating != n * int(len(lengths) == 1):
                raise SystemExit(f"Python indicator fails for {lengths}")
            rows.append((lengths, chars))
    out = []
    out.append("/-")
    out.append("GENERATED by formal/scripts/gen_crosscheck.py; do not edit by hand.")
    out.append("")
    out.append("Values of `exterior_characters` from theorems/prime_character_exterior_bound.py")
    out.append(f"(function at line {lineno}; file SHA-256 {digest}),")
    out.append(f"for every cycle type of every n from 1 to {MAX_N} ({len(rows)} cycle types).")
    out.append("-/")
    out.append("import Formal.CoeffList")
    out.append("")
    out.append("namespace QSearch.CrossCheck")
    out.append("")
    out.append("open Polynomial")
    out.append("")
    out.append("/-- `(cycle lengths, exterior_characters(cycle lengths))`, as returned by Python. -/")
    out.append("def pythonValues : List (List ℕ × List ℤ) := [")
    for i, (lengths, chars) in enumerate(rows):
        sep = "," if i + 1 < len(rows) else ""
        out.append(f"  ({lean_list(lengths)}, {lean_list(chars)}){sep}")
    out.append("]")
    out.append("")
    out.append(f"theorem pythonValues_length : pythonValues.length = {len(rows)} := by decide")
    out.append("")
    out.append("/-- Kernel check: the computable Lean mirror `extCharsList` reproduces every")
    out.append("Python row exactly (same length, same integers). -/")
    out.append("theorem extCharsList_eq_python :")
    out.append("    pythonValues.all (fun e => extCharsList e.1 == e.2) = true := by decide")
    out.append("")
    out.append("/-- Kernel check: on every Python row the alternating sum is `n` for one cycle")
    out.append("and `0` otherwise. -/")
    out.append("theorem python_cycle_indicator :")
    out.append("    pythonValues.all (fun e => altSum e.2 == if e.1.length = 1 then (e.1.sum : ℤ) else 0)")
    out.append("      = true := by decide")
    out.append("")
    out.append("/-- Every Python row is the coefficient list of the polynomial `stdDet L`, the")
    out.append("quotient `∏ (1 - (-z)^ℓᵢ) / (1 + z)` that `Formal.CycleIndicator` is about. -/")
    out.append("theorem stdDet_eq_python : ∀ e ∈ pythonValues, stdDet e.1 = ofCoeffList e.2 := by")
    out.append("  intro e he")
    out.append("  have h := List.all_eq_true.mp extCharsList_eq_python e he")
    out.append("  rw [beq_iff_eq] at h")
    out.append("  rw [← h, ofCoeffList_extCharsList]")
    out.append("")
    out.append("/-- Coefficient form: Python's `chars[j]` is the `j`-th coefficient of `stdDet L`. -/")
    out.append("theorem stdDet_coeff_eq_python :")
    out.append("    ∀ e ∈ pythonValues, ∀ j : ℕ, (stdDet e.1).coeff j = e.2.getD j 0 := by")
    out.append("  intro e he j")
    out.append("  rw [stdDet_eq_python e he, coeff_ofCoeffList]")
    out.append("")
    out.append("-- Compiled (not kernel) re-check, printed during the build: `true`.")
    out.append("#eval pythonValues.all (fun e => extCharsList e.1 == e.2)")
    out.append("")
    out.append("end QSearch.CrossCheck")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(*load_exterior_characters())
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            sys.exit("Formal/CrossCheck.lean is stale; rerun formal/scripts/gen_crosscheck.py")
        print("Formal/CrossCheck.lean is up to date")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
