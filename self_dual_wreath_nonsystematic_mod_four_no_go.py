def mod_four_code(width: int) -> tuple[Assignment, ...]:
    if width < 6 or width % 4 != 2:
        raise ValueError("mod-four family requires n>=6 and n=2 mod 4")
    return tuple(
        row
        for row in itertools.product((0, 1), repeat=width)
        if sum(row) % 4 == 0
    )


def _minimum_distance(code: tuple[Assignment, ...]) -> int:
    return min(
        sum(a != b for a, b in zip(left, right))
        for left, right in itertools.combinations(code, 2)
    )


def _distance_two_witnesses(
    width: int,
) -> tuple[tuple[tuple[int, int], Assignment, Assignment], ...]:
    witnesses = []
    coordinates = set(range(width))
    for first, second in itertools.combinations(range(width), 2):
        common = tuple(sorted(coordinates - {first, second})[:3])
        left_support = {*common, first}
        right_support = {*common, second}
        left = tuple(int(index in left_support) for index in range(width))
        right = tuple(int(index in right_support) for index in range(width))
        witnesses.append(((first, second), left, right))
    return tuple(witnesses)


def _spanning_distance_two_star_exists(
    code: tuple[Assignment, ...],
) -> bool:
    width = len(code[0])
    rows = set(code)
    for row in code:
        for pivot in range(width):
            if all(
                tuple(
                    bit ^ int(index in (pivot, coordinate))
                    for index, bit in enumerate(row)
                )
                in rows
                for coordinate in range(width)
                if coordinate != pivot
            ):
                return True
    return False


def _codeword_relations(code: tuple[Assignment, ...]) -> tuple[SignedWord, ...]:
    return tuple(
        tuple(index + 1 for index, bit in enumerate(row) if bit)
        for row in code
        if any(row)
    )


@lru_cache(maxsize=None)
def audit_mod_four_structure(width: int) -> ModFourStructuralControl:
    code = mod_four_code(width)
    witnesses = _distance_two_witnesses(width)
    rows = set(code)
    witness_exact = all(
        left in rows
        and right in rows
        and tuple(
            index for index, (a, b) in enumerate(zip(left, right)) if a != b
        )
        == pair
        for pair, left, right in witnesses
    )
    even_parity = all(sum(row) % 2 == 0 for row in code)
    minimum_distance = 2 if even_parity and witness_exact else _minimum_distance(code)
    star = _spanning_distance_two_star_exists(code)
    reduction = tietze_reduce_presentation(width, _codeword_relations(code))
    surviving = reduction.remaining_generators
    pure_powers = tuple(
        relation
        for relation in reduction.residual_relations
        if len(set(map(abs, relation))) == 1
    )
    fourth_power = any(len(relation) == 4 for relation in pure_powers)
    all_degrees_divisible_by_four = all(
        len(relation) % 4 == 0 for relation in pure_powers
    )
    exact_cyclic = (
        len(surviving) == 1
        and fourth_power
        and all_degrees_divisible_by_four
    )
    exact = (
        len(code) == 1 << (width - 2)
        and minimum_distance == 2
        and witness_exact
        and not any(sum(row) == 2 for row in code)
        and not star
        and exact_cyclic
    )
    return ModFourStructuralControl(
        code_width=width,
        code_size=len(code),
        expected_quarter_cube_size=1 << (width - 2),
        roots_of_unity_filter_exact=len(code) == 1 << (width - 2),
        minimum_distance=minimum_distance,
        all_coordinate_pairs_have_explicit_distance_two_witnesses=witness_exact,
        minimum_separating_coordinate_count=width - 1,
        has_dimension_sized_information_set=False,
        contains_weight_two_row=any(sum(row) == 2 for row in code),
        spanning_distance_two_star_exists=star,
        incidence_lattice_formula="{z in Z^n: sum(z)=0 mod 4}",
        incidence_lattice_index=4,
        smith_invariants=(1,) * (width - 1) + (4,),
        codeword_presentation_remaining_generator_count=len(surviving),
        codeword_presentation_residual_relations=reduction.residual_relations,
        exact_cyclic_order_four_presentation_verified=exact_cyclic,
        exact_control_verified=exact,
        status=(
            "mod-four-nonsystematic-cyclic-presentation-verified"
            if exact
            else "mod-four-structural-certificate-failure"
        ),
    )


def mod_four_marked_supports(
    width: int,
) -> tuple[str, tuple[Assignment, ...], tuple[Assignment, ...]]:
    code = mod_four_code(width)
    same = tuple((1, 0, 1, 0, *row) for row in code if any(row))
    different = tuple((0, 0, 0, 0, *row) for row in code)
    pattern = "E" + "BABA" + "A" * width + "FEF"
    return pattern, same, different


@lru_cache(maxsize=None)
def audit_mod_four_marked_presentation(
    width: int,
) -> ModFourMarkedPresentationControl:
    pattern, same, different = mod_four_marked_supports(width)
    appended = tuple(range(5, 5 + width))
    peeling = audit_support_difference_peeling_lift(
        f"MOD-FOUR-{width}",
        pattern,
        appended,
        same,
        different,
    )
    reduction = tietze_reduce_presentation(
        len(pattern),
        marked_support_presentation(pattern, same, different),
    )
    exponent, source = presentation_solution_exponent_upper_bound(reduction)
    appended_generators = set(range(6, 6 + width))
    surviving_appended = appended_generators.intersection(
        reduction.remaining_generators
    )
    fourth_power = any(
        len(relation) == 4
        and len(set(map(abs, relation))) == 1
        and abs(relation[0]) in surviving_appended
        for relation in reduction.residual_relations
    )
    entropy = 0.5 * math.log2(len(same)) + 0.5 * math.log2(
        len(different)
    )
    margin = width + 5 - (exponent + entropy)
    target = _transport_target_product_word(len(pattern), reduction)
    exact = (
        peeling.uncovered_appended_coordinates_one_based == appended
        and peeling.residual_core_is_stopping_set
        and len(reduction.remaining_generators) == 6
        and len(surviving_appended) == 1
        and fourth_power
        and exponent <= 5.0
        and margin > 2.0
        and bool(target)
    )
    return ModFourMarkedPresentationControl(
        code_width=width,
        support_difference_peeling_stalls_on_full_core=(
            peeling.uncovered_appended_coordinates_one_based == appended
        ),
        remaining_generator_count=len(reduction.remaining_generators),
        residual_relations=reduction.residual_relations,
        fourth_power_relation_present=fourth_power,
        solution_exponent_upper_bound=exponent,
        solution_exponent_certificate_source=source,
        support_entropy_bits=entropy,
        true_pressure_margin_lower_bound=margin,
        residual_target_word=target,
        exact_control_verified=exact,
        status=(
            "mod-four-marked-presentation-uniformly-subleading"
            if exact
            else "mod-four-marked-presentation-certificate-failure"
        ),
    )


def mod_four_all_depth_certificate() -> ModFourAllDepthCertificate:
    surface_normal_form = (-6, -5, 6, -4, -2, -3, 2, 3, 4, 5)
    surface_exact = orientable_quadratic_genus(surface_normal_form) == 2
    return ModFourAllDepthCertificate(
        admissible_widths="n>=6 and n=2 mod 4",
        cardinality_proof=(
            "The fourth-root filter is (2^n+2*2^(n/2)*cos(n*pi/4))/4; "
            "the cosine vanishes for n=2 mod 4."
        ),
        no_information_set_proof=(
            "Two weight-four rows sharing three coordinates realize every "
            "coordinate pair as their exact difference support."
        ),
        no_spanning_star_proof=(
            "For a fixed pivot, preserving weight mod four across every swap "
            "would require all other bits to be the complement of the pivot, "
            "which has forbidden weight when n=2 mod 4."
        ),
        incidence_lattice_proof=(
            "Weight-four row differences generate every e_i-e_j, and one "
            "weight-four row supplies total sum four."
        ),
        ordered_presentation_reduction=(
            "Anchor relations on {0,1,2,j} identify j>=3; relations on "
            "{0,1,3,4}, {0,2,3,4}, and {1,2,3,4} identify the remaining "
            "generators and impose x^4=1."
        ),
        marked_surface_relation=(
            "h^-1 e^-1 h x^a c^-1 [p,q] c x^-a e"
        ),
        marked_surface_nielsen_reduction=(
            "Cyclic rotation and c -> c x^-a give a genus-two quadratic word; "
            f"the normalized genus check is {orientable_quadratic_genus(surface_normal_form)}."
        ),
        symmetric_group_solution_exponent_upper_bound=5.0,
        pressure_margin_formula=(
            "n-0.5*log2(2^(n-2)*(2^(n-2)-1)) > 2"
        ),
        uniform_pressure_margin_lower_bound=2.0,
        arbitrary_admissible_width=True,
        universal_mod_four_family_no_go_verified=surface_exact,
        status=(
            "all-depth-nonsystematic-mod-four-pressure-no-go"
            if surface_exact
            else "mod-four-surface-normal-form-failure"
        ),
    )


