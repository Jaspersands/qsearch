"""No-go theorem for a non-systematic index-four incidence family.

For every ``n = 2 (mod 4)``, ``n>=6``, let

    Q_n = {x in F_2^n : |x| = 0 (mod 4)}.

A roots-of-unity filter gives ``|Q_n|=2^(n-2)``.  The code is independent in
the hypercube, and every coordinate pair is the difference support of two
weight-four rows, so no projection to ``n-2`` coordinates is injective.  It
also contains no weight-two row and no spanning distance-two star around any
codeword.  This is therefore a stricter non-systematic test than the twisted
star family.

The integer lattice generated by the rows is

    {z in Z^n : sum_i z_i = 0 (mod 4)},

with Smith invariants ``(1,...,1,4)``.  The ordered codeword presentation is
exactly cyclic of order four: weight-four relators identify all coordinate
generators with one generator ``x`` and impose ``x^4=1``; every remaining
codeword relator then follows.

This bounded torsion still does not preserve marked pressure.  The fixed
``BABA`` split and complement relations leave six generators and a word

    h^-1 e^-1 h x^a c^-1 [p,q] c x^-a e.

The Nielsen move ``c -> c x^-a`` and cyclic rotation expose an orientable
genus-two word, uniformly in ``a``.  Dropping all other relations bounds the
symmetric-group solution exponent by five and gives crossing margin greater
than two.  Thus a bounded nontrivial Smith invariant is not enough; any
remaining non-systematic escape must force growing torsion or a genuinely
different noncommutative residual law.  No quantum speedup is claimed.
"""

