def _compose(left: Permutation, right: Permutation) -> Permutation:
    return tuple(left[right[index]] for index in range(4))


def _inverse(permutation: Permutation) -> Permutation:
    output = [0] * 4
    for index, image in enumerate(permutation):
        output[image] = index
    return tuple(output)


def _cycles(permutation: Permutation) -> tuple[tuple[int, ...], ...]:
    seen: set[int] = set()
    cycles = []
    for start in range(4):
        if start in seen:
            continue
        cycle = []
        current = start
        while current not in seen:
            seen.add(current)
            cycle.append(current)
            current = permutation[current]
        cycles.append(tuple(cycle))
    return tuple(cycles)


def _cycle_type(permutation: Permutation) -> tuple[int, ...]:
    return tuple(sorted((len(cycle) for cycle in _cycles(permutation)), reverse=True))


def _content_polynomial(partition: tuple[int, ...], dimension: int) -> int:
    output = 1
    for row_index, row_size in enumerate(partition, start=1):
        for column_index in range(1, row_size + 1):
            output *= dimension + column_index - row_index
    return output


def unitary_weingarten_s4(
    permutation: Permutation,
    dimension: int,
) -> Fraction:
    if dimension < 4:
        raise ValueError("the S4 character formula requires dimension at least four")
    cycle_type = _cycle_type(permutation)
    return sum(
        Fraction(
            S4_IRREP_DIMENSIONS[partition]
            * characters[cycle_type],
            24 * _content_polynomial(partition, dimension),
        )
        for partition, characters in S4_CHARACTER_TABLE.items()
    )


def _fixed_distinct_pair_word_moment(
    ambient_dimension: int,
    fiber_dimension: int,
    block_dimension: int,
    labels: tuple[int, int, int, int],
) -> Fraction:
    """Enumerate the p=4 Weingarten contraction for one block-label word."""

    gamma = (1, 2, 3, 0)
    output = Fraction()
    for sigma in S4:
        index_cycles = _cycles(_compose(gamma, sigma))
        if any(len({labels[index] for index in cycle}) > 1 for cycle in index_cycles):
            continue
        index_assignments = block_dimension ** len(index_cycles)
        sigma_inverse = _inverse(sigma)
        for tau in S4:
            output += (
                index_assignments
                * fiber_dimension ** len(_cycles(tau))
                * unitary_weingarten_s4(
                    _compose(sigma_inverse, tau),
                    ambient_dimension,
                )
            )
    return output


def haar_ordered_pair_moment_gap(
    ambient_dimension: int,
    fiber_dimension: int,
    block_dimension: int,
) -> Fraction:
    _validate_dimensions(ambient_dimension, fiber_dimension, block_dimension)
    numerator = (
        block_dimension**2
        * fiber_dimension
        * (ambient_dimension - 2 * block_dimension)
        * (ambient_dimension - fiber_dimension)
        * (fiber_dimension**2 - 1)
    )
    denominator = (
        ambient_dimension**2
        * (ambient_dimension - 2)
        * (ambient_dimension - 1)
        * (ambient_dimension + 1)
        * (ambient_dimension + 2)
    )
    return Fraction(numerator, denominator)


def haar_normalized_commutator_trace(
    ambient_dimension: int,
    fiber_dimension: int,
    block_dimension: int,
) -> Fraction:
    _validate_dimensions(ambient_dimension, fiber_dimension, block_dimension)
    numerator = (
        (ambient_dimension - block_dimension)
        * (ambient_dimension - 2 * block_dimension)
        * (ambient_dimension - fiber_dimension)
        * (fiber_dimension**2 - 1)
    )
    denominator = (
        ambient_dimension
        * (ambient_dimension - 2)
        * (ambient_dimension - 1)
        * (ambient_dimension + 1)
        * (ambient_dimension + 2)
    )
    return Fraction(numerator, denominator)


def _validate_dimensions(
    ambient_dimension: int,
    fiber_dimension: int,
    block_dimension: int,
) -> None:
    if ambient_dimension < 4 or not 1 <= fiber_dimension <= ambient_dimension:
        raise ValueError("invalid ambient or fiber dimension")
    if block_dimension < 1 or ambient_dimension % block_dimension:
        raise ValueError("block dimension must divide the ambient dimension")
    if ambient_dimension // block_dimension < 2:
        raise ValueError("at least two outcomes are required")


def audit_haar_commutator_formula(
    control_id: str,
    ambient_dimension: int,
    fiber_dimension: int,
    block_dimension: int,
) -> HaarCommutatorExactControl:
    _validate_dimensions(ambient_dimension, fiber_dimension, block_dimension)
    outcome_count = ambient_dimension // block_dimension
    aabb = _fixed_distinct_pair_word_moment(
        ambient_dimension,
        fiber_dimension,
        block_dimension,
        (0, 0, 1, 1),
    )
    abab = _fixed_distinct_pair_word_moment(
        ambient_dimension,
        fiber_dimension,
        block_dimension,
        (0, 1, 0, 1),
    )
    enumerated = (
        outcome_count
        * (outcome_count - 1)
        * (aabb - abab)
        / fiber_dimension
    )
    formula = haar_normalized_commutator_trace(
        ambient_dimension,
        fiber_dimension,
        block_dimension,
    )
    pair_formula = haar_ordered_pair_moment_gap(
        ambient_dimension,
        fiber_dimension,
        block_dimension,
    )
    residual = enumerated - formula
    exact = residual == 0 and aabb - abab == pair_formula
    return HaarCommutatorExactControl(
        control_id=control_id,
        ambient_dimension=ambient_dimension,
        fiber_dimension=fiber_dimension,
        block_dimension=block_dimension,
        outcome_count=outcome_count,
        exact_ordered_pair_moment_gap=str(pair_formula),
        exact_normalized_commutator_trace_formula=str(formula),
        enumerated_normalized_commutator_trace=str(enumerated),
        formula_residual=str(residual),
        normalized_commutator_trace_float=float(formula),
        one_dimensional_boundary=fiber_dimension == 1 and formula == 0,
        two_outcome_boundary=outcome_count == 2 and formula == 0,
        exact_weingarten_formula_verified=exact,
        status=(
            "exact-complex-haar-component-commutator-formula-verified"
            if exact
            else "haar-component-commutator-formula-failure"
        ),
    )


def haar_commutator_asymptotic_record(
    fiber_aspect: float,
    block_aspect: float,
) -> HaarCommutatorAsymptoticRecord:
    if not 0 < fiber_aspect < 1 or not 0 <= block_aspect <= 0.5:
        raise ValueError("aspects must satisfy 0<alpha<1 and 0<=beta<=1/2")
    value = (
        fiber_aspect**2
        * (1 - fiber_aspect)
        * (1 - block_aspect)
        * (1 - 2 * block_aspect)
    )
    sparse = fiber_aspect**2 * (1 - fiber_aspect)
    return HaarCommutatorAsymptoticRecord(
        fiber_aspect=fiber_aspect,
        block_aspect=block_aspect,
        asymptotic_normalized_commutator_trace=value,
        sparse_block_limit=sparse,
        positive_surrogate_signal=value > 0,
        natural_frame_transfer_proved=False,
        status="positive-haar-surrogate-commutator-gap-natural-transfer-open",
    )


