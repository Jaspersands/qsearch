"""Exact Haar benchmark for the component commutator fourth-moment gap.

The natural trace-mass bridge reduces noncommutative component support to

    M_4 = Tr(D_com)/r

for one normalized child POVM.  This module evaluates that quantity exactly
for the standard complex-Haar block-isometry surrogate.

Let ``W:C^r -> C^N`` be the first ``r`` columns of a Haar unitary.  Split
``C^N`` into ``q=N/b`` equal coordinate blocks with projections ``P_e`` and
put

    H_e = W^* P_e W,            sum_e H_e=I_r.             (1)

For distinct ``e,f``, the fourth-order unitary Weingarten expansion of the
two block words gives

    E[Tr(H_e^2 H_f^2)-Tr(H_e H_f H_e H_f)]
      = b^2 r (N-2b)(N-r)(r^2-1)
        / [N^2(N-2)(N-1)(N+1)(N+2)].                     (2)

There are ``q(q-1)`` ordered distinct pairs in the exact trace identity.
Therefore

    E Tr(D_com)/r
      = (N-b)(N-2b)(N-r)(r^2-1)
        / [N(N-2)(N-1)(N+1)(N+2)].                       (3)

The factors have meaningful boundary checks: ``r=1`` and ``q=2`` both make
(3) vanish, as every one-dimensional or two-outcome POVM commutes.  For
``r/N -> alpha`` and ``b/N -> beta``, (3) converges to

    alpha^2(1-alpha)(1-beta)(1-2beta).                    (4)

In the natural sparse-block aspect ``beta=1/q -> 0``, this becomes
``alpha^2(1-alpha)``.  Thus a Haar/Jacobi component model predicts a constant
commutator moment even though every block has vanishing relative rank and the
outcome count grows superpolynomially.

At the proved natural lower aspect ``alpha=19/520``, the sparse-Haar value is
``180861/140608000 ~= 1.286e-3``.  Combining this only as a benchmark with the
proved source event ``1/9`` and common physical rank ``19/128`` would suggest
total regular-master moment mass about ``2.12e-5`` and support mass about
``1.06e-5``.  These are constants, but they are not natural theorems.

The calculation is deliberately a surrogate.  Natural orientation effects
share representation-theoretic dependencies, the common span is generated by
the sibling frame, and no Haar/freeness transfer has been proved after
pseudoinverse normalization.  Equation (3) supplies a quantitative falsifier:
the natural calculation should either recover a positive scale or identify an
exact recoupling mechanism that collapses the crossing gap.
"""

