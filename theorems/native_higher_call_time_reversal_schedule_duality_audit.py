def canonical_sha256(payload: dict[str, Any]) -> str:
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def load_contract(path: Path = DEFAULT_CONTRACT_PATH) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def time_reversed_schedule(
    epsilon: tuple[int, ...],
    sigma: tuple[int, ...],
) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """Return (epsilon^rev, sigma^rev) where epsilon^rev = (eps_k, ..., eps_1) and sigma^rev = (sig_{k-1}, ..., sig_1, sig_k)."""
    eps_rev = tuple(reversed(epsilon))
    if len(sigma) == 1:
        sig_rev = sigma
    else:
        sig_rev = tuple(reversed(sigma[:-1])) + (sigma[-1],)
    return eps_rev, sig_rev


def klein_four_orbit(
    epsilon: tuple[int, ...],
    sigma: tuple[int, ...],
) -> list[tuple[tuple[int, ...], tuple[int, ...]]]:
    """Return the 4 schedules in the Klein four-group orbit generated by (-eps, -sig) and sig_k -> -sig_k."""
    neg_eps = tuple(-e for e in epsilon)
    neg_sig = tuple(-s for s in sigma)
    flip_sig = sigma[:-1] + (-sigma[-1],)
    neg_flip_sig = neg_sig[:-1] + (-neg_sig[-1],)
    return [
        (epsilon, sigma),
        (neg_eps, neg_sig),
        (epsilon, flip_sig),
        (neg_eps, neg_flip_sig),
    ]


def evaluate_schedule_duality_case(
    *,
    case_id: str,
    D: int,
    q: int,
    n: int,
    k_calls: int,
    freq_table: list[tuple[int, ...]],
    error_table: list[int],
    tolerance: float = 1e-12,
) -> dict[str, Any]:
    """Exhaustively evaluate all 4^k schedules (epsilon, sigma) in {-1, +1}^k x {-1, +1}^k and verify Theorems 1, 2, 3."""
    all_sign_tuples = list(itertools.product((-1, 1), repeat=k_calls))
    all_schedules = list(itertools.product(all_sign_tuples, all_sign_tuples))
    total_schedules = len(all_schedules)  # 4^k

    secrets = list(itertools.product(range(q), repeat=n))
    y_by_secret = [
        [
            (sum(freq_table[w][j] * s[j] for j in range(n)) + error_table[w]) % q
            for w in range(D)
        ]
        for s in secrets
    ]

    # Precompute statevectors across all 4^k schedules and all q^n secrets, plus ensemble metrics
    psi_table: dict[tuple[tuple[int, ...], tuple[int, ...]], list[np.ndarray]] = {}
    metrics_table: dict[tuple[tuple[int, ...], tuple[int, ...]], dict[str, Any]] = {}

    for eps, sig in all_schedules:
        psi_list = [k_call_statevector(D, q, y_s, eps, sig) for y_s in y_by_secret]
        psi_table[(eps, sig)] = psi_list
        metrics_table[(eps, sig)] = compute_ensemble_metrics(
            D, q, n, freq_table, error_table, eps, sig
        )

    max_conj_state_residual = 0.0
    max_conj_born_residual = 0.0
    max_reflection_born_residual = 0.0
    max_orbit_l2_energy_spread = 0.0
    max_orbit_v_hs_spread = 0.0
    max_time_reversal_amp0_residual = 0.0
    max_time_reversal_prob0_residual = 0.0

    visited_in_orbits: set[tuple[tuple[int, ...], tuple[int, ...]]] = set()
    distinct_orbit_count = 0

    for eps, sig in all_schedules:
        orbit = klein_four_orbit(eps, sig)
        orbit_set = set(orbit)
        if (eps, sig) not in visited_in_orbits:
            if len(orbit_set) == 4:
                distinct_orbit_count += 1
            visited_in_orbits.update(orbit_set)

        neg_eps, neg_sig = orbit[1]
        _, flip_sig = orbit[2]
        eps_rev, sig_rev = time_reversed_schedule(eps, sig)

        # Check Orbit constancy of L2 signal energy and V_HS
        orbit_l2 = [metrics_table[sch]["l2_energy"] for sch in orbit]
        orbit_vhs = [metrics_table[sch]["v_hs"] for sch in orbit]
        max_orbit_l2_energy_spread = max(
            max_orbit_l2_energy_spread, max(orbit_l2) - min(orbit_l2)
        )
        max_orbit_v_hs_spread = max(
            max_orbit_v_hs_spread, max(orbit_vhs) - min(orbit_vhs)
        )

        # Check pointwise across all secrets s in Z_q^n
        for s_idx in range(len(secrets)):
            psi_orig = psi_table[(eps, sig)][s_idx]
            psi_neg = psi_table[(neg_eps, neg_sig)][s_idx]
            psi_flip = psi_table[(eps, flip_sig)][s_idx]
            psi_rev = psi_table[(eps_rev, sig_rev)][s_idx]

            # Theorem 1: |Psi_{-eps, -sig}(y)> == conj(|Psi_{eps, sig}(y)>)
            conj_res = float(np.max(np.abs(psi_neg - psi_orig.conj())))
            born_orig = np.abs(psi_orig) ** 2
            born_neg = np.abs(psi_neg) ** 2
            born_res = float(np.max(np.abs(born_neg - born_orig)))
            max_conj_state_residual = max(max_conj_state_residual, conj_res)
            max_conj_born_residual = max(max_conj_born_residual, born_res)

            # Theorem 2: P_{eps, flip_sig}(x | y) == P_{eps, sig}((-x) mod D | y)
            born_flip = np.abs(psi_flip) ** 2
            born_mod_neg = np.array([born_orig[(-x) % D] for x in range(D)])
            refl_res = float(np.max(np.abs(born_flip - born_mod_neg)))
            max_reflection_born_residual = max(max_reflection_born_residual, refl_res)

            # Theorem 3: <0_D | Psi_{eps, sig}(y)> == <0_D | Psi_{eps^rev, sig^rev}(y)>
            amp0_res = float(abs(psi_orig[0] - psi_rev[0]))
            prob0_res = float(abs(born_orig[0] - (abs(psi_rev[0]) ** 2)))
            max_time_reversal_amp0_residual = max(
                max_time_reversal_amp0_residual, amp0_res
            )
            max_time_reversal_prob0_residual = max(
                max_time_reversal_prob0_residual, prob0_res
            )

    expected_orbit_count = 4 ** (k_calls - 1)
    theorem1_verified = bool(
        max_conj_state_residual <= tolerance and max_conj_born_residual <= tolerance
    )
    theorem2_verified = bool(
        distinct_orbit_count == expected_orbit_count
        and max_reflection_born_residual <= tolerance
        and max_orbit_l2_energy_spread <= tolerance
        and max_orbit_v_hs_spread <= tolerance
    )
    theorem3_verified = bool(
        max_time_reversal_amp0_residual <= tolerance
        and max_time_reversal_prob0_residual <= tolerance
    )

    return {
        "case_id": case_id,
        "D": D,
        "q": q,
        "n": n,
        "k_calls": k_calls,
        "total_schedules_4_pow_k": total_schedules,
        "klein_four_orbit_count_4_pow_k_minus_1": distinct_orbit_count,
        "expected_orbit_count": expected_orbit_count,
        "max_conj_state_residual": max_conj_state_residual,
        "max_conj_born_residual": max_conj_born_residual,
        "max_reflection_born_residual": max_reflection_born_residual,
        "max_orbit_l2_energy_spread": max_orbit_l2_energy_spread,
        "max_orbit_v_hs_spread": max_orbit_v_hs_spread,
        "max_time_reversal_amp0_residual": max_time_reversal_amp0_residual,
        "max_time_reversal_prob0_residual": max_time_reversal_prob0_residual,
        "theorem1_verified": theorem1_verified,
        "theorem2_verified": theorem2_verified,
        "theorem3_verified": theorem3_verified,
        "all_theorems_verified": bool(
            theorem1_verified and theorem2_verified and theorem3_verified
        ),
    }


