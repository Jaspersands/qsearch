Assignment = tuple[int, ...]


@dataclass(frozen=True)
class SupportAffineRankControl:
    control_id: str
    frame_position_count: int
    crossing: bool
    frame_types: tuple[str, ...]
    same_support: tuple[Assignment, ...]
