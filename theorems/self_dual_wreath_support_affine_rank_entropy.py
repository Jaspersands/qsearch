"""Affine-rank payment of marked support entropy.

For nonempty supports ``S,D subset {0,1}^u``, form the exponent-sum matrix of
the split relation, all same-coordinate partition relations, all
different-coordinate partition relations, and the all-ones row generated by
each color/complement pair.  Its rational rank ``R`` obeys

    R >= 2 + 0.5 log2|S| + 0.5 log2|D|.                 (1)

Indeed, a cube subset of size ``k`` has real affine dimension at least
``log2(k)``.  The span of same-support vectors contains its affine direction
space; differences of different-support vectors contain the other direction
space.  Their maximum dimension dominates the average support entropy.  The
different E/F leaf offset supplies one further direction, and the all-ones
row is independent of every partition vector.

For a crossing pressure target, (1) pays every support-entropy exponent except
at most one.  What remains is nonabelian: prove that rational relation rank
lifts to the corresponding leading ``S_n`` solution loss, with a surface or
power-word certificate supplying the final crossing exponent.  Abelian rank
alone does not prove that lift.
"""

