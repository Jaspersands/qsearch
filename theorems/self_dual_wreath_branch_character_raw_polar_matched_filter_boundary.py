"""Operational raw/polar mismatch for the native branch-character ensemble.

The physical joint-character state is generated by the raw isometric field

    K_h=[M_+(h);M_-(h)],

whereas the proposed near-isometric candidate convolution uses the locally
polar-completed field

    J_h=[V_+(h);V_-(h)](P_+(h)+P_-(h))^-1/2.

The predecessor separation theorem proved that the two global fields have
vanishing natural normalized Hilbert--Schmidt overlap.  This module turns that
geometric fact into an operational decoder boundary.

For every ``h``, the cross map is a positive contraction:

    T_h=J_h^*K_h
       =F_h^-1/2 (|M_+(h)|+|M_-(h)|),                  (1)
    0 <= T_h <= I.

For ``k`` source pairs this tensor-factorizes.  Let ``C_J`` and ``C_K`` be the
relative convolutions built from ``J_h`` and ``K_h``, and put

    A=|G|^-1 sum_h J_h^*K_h.                            (2)

Every correct-label diagonal block of ``C_J^*C_K`` is exactly ``A``.  Hence
the correct probability of the unwhitened polar matched filter on the native
raw ensemble is

    P_match=Tr(A^2)/D <= Tr(A)/D
           =Tr(C_J^*C_K)/(|G|D).                        (3)

The right side is precisely the overlap already proved to vanish for natural
globally distinct source portfolios.  Thus direct use of ``C_J^*`` as the
native decoder is asymptotically rejected.

Could global polar whitening rescue it?  Let ``Q=polar(C_J)``,
``E=Q-C_J``,

    R=||C_J^*C_J-I||_F^2/(|G|D),
    kappa=||C_K||^2.

Singular-value calculus gives ``||E||_F^2/(|G|D)<=R``.  Extracting only the
correct candidate blocks is a contraction, so Minkowski and submultiplicity
give the exact portfolio bound

    sqrt(P_Q) <= sqrt(P_match)+sqrt(kappa R),
    P_Q <= (sqrt(overlap)+sqrt(kappa R))^2.              (4)

At ``k=ceil(3log_2|G|)+2``, the quadrant theorem gives
``E R=O(|G|^-0.245...)``.  Therefore any uniform polynomial-in-``n`` bound on
the raw physical concentration ``kappa`` would force the whitened decoder to
fail as well.  Constant success can only come from raw-state concentration on
the Frobenius-small bad singular sector (or from a different decoder).

This reverses the old interpretation of the physical-input gate.  Flat or
polynomial domination does not validate the branch-polar route; together
with raw/polar separation it kills it.  The live question is whether the
native raw frame has sufficiently large, structured concentration and whether
whitening exploits that concentration coherently.  This module neither proves
such concentration nor rules out the actual physical PGM or another decoder.
"""

