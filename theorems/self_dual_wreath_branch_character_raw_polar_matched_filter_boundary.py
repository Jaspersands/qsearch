def _kron_all(matrices: tuple[np.ndarray, ...]) -> np.ndarray:
    output = np.asarray([[1.0]], dtype=complex)
    for matrix in matrices:
        output = np.kron(output, matrix)
    return output


def raw_candidate_relative_convolution(
    labels: tuple[Label, ...],
) -> tuple[np.ndarray, tuple[Permutation, ...], dict[Permutation, np.ndarray]]:
    if not labels:
        raise ValueError("at least one source pair is required")
    group = tuple(_source_representation_rows(labels[0][0]))
    fields = {
        permutation: _kron_all(
            tuple(
                raw_branch_isometry(left, right, permutation)
                for left, right in labels
            )
        )
        for permutation in group
    }
    output_dimension, input_dimension = next(iter(fields.values())).shape
    convolution = np.zeros(
        (
            len(group) * output_dimension,
            len(group) * input_dimension,
        ),
        dtype=complex,
    )
    for output_index, output_group in enumerate(group):
        output_block = slice(
            output_index * output_dimension,
            (output_index + 1) * output_dimension,
        )
        for input_index, input_group in enumerate(group):
            input_block = slice(
                input_index * input_dimension,
                (input_index + 1) * input_dimension,
            )
            relative = compose_permutations(
                _inverse_permutation(input_group),
                output_group,
            )
            convolution[output_block, input_block] = (
                fields[relative] / math.sqrt(len(group))
            )
    return convolution, group, fields


def _canonical_partial_polar(matrix: np.ndarray, tolerance: float) -> np.ndarray:
    left, singular_values, right_star = np.linalg.svd(matrix, full_matrices=False)
    active = singular_values > tolerance
    return left[:, active] @ right_star[active, :]


def _diagonal_block_success(
    decoder_product: np.ndarray,
    group_order: int,
    carrier_dimension: int,
) -> float:
    total = 0.0
    for label in range(group_order):
        block = decoder_product[
            label * carrier_dimension : (label + 1) * carrier_dimension,
            label * carrier_dimension : (label + 1) * carrier_dimension,
        ]
        total += float(np.linalg.norm(block, ord="fro") ** 2)
    return total / (group_order * carrier_dimension)


def audit_raw_polar_matched_filter(
    control_id: str,
    labels: tuple[Label, ...],
    *,
    tolerance: float = 1e-9,
) -> RawPolarMatchedFilterControl:
    polar, group, polar_fields = candidate_relative_convolution(labels)
    raw, raw_group, raw_fields = raw_candidate_relative_convolution(labels)
    if group != raw_group:
        raise ArithmeticError("raw and polar fields enumerate different groups")
    order = len(group)
    carrier = next(iter(polar_fields.values())).shape[1]
    local_cross = {
        element: polar_fields[element].conj().T @ raw_fields[element]
        for element in group
    }
    hermiticity = max(
        float(np.linalg.norm(matrix - matrix.conj().T, ord=2))
        for matrix in local_cross.values()
    )
    local_eigenvalues = np.concatenate(
        [
            np.linalg.eigvalsh((matrix + matrix.conj().T) / 2.0)
            for matrix in local_cross.values()
        ]
    )
    matched = sum(
        local_cross.values(),
        np.zeros((carrier, carrier), dtype=complex),
    ) / order
    matched_hermiticity = float(
        np.linalg.norm(matched - matched.conj().T, ord=2)
    )
    matched_eigenvalues = np.linalg.eigvalsh(
        (matched + matched.conj().T) / 2.0
    )

    product = polar.conj().T @ raw
    block_residual = 0.0
    for label in range(order):
        block = product[
            label * carrier : (label + 1) * carrier,
            label * carrier : (label + 1) * carrier,
        ]
        block_residual = max(
            block_residual,
            float(np.linalg.norm(block - matched, ord=2)),
        )
    overlap = float(np.trace(polar.conj().T @ raw).real / (order * carrier))
    matched_overlap = float(np.trace(matched).real / carrier)
    overlap_residual = abs(overlap - matched_overlap)
    matched_success = float(np.trace(matched.conj().T @ matched).real / carrier)
    matched_bound_residual = max(0.0, matched_success - overlap)

    identity = np.eye(order * carrier, dtype=complex)
    gram_residual = float(
        np.linalg.norm(polar.conj().T @ polar - identity, ord="fro") ** 2
        / (order * carrier)
    )
    polar_isometry = _canonical_partial_polar(polar, tolerance)
    polar_distance = float(
        np.linalg.norm(polar_isometry - polar, ord="fro") ** 2
        / (order * carrier)
    )
    raw_singular_maximum = float(np.linalg.svd(raw, compute_uv=False)[0])
    concentration = raw_singular_maximum**2
    whitened_product = polar_isometry.conj().T @ raw
    whitened_success = _diagonal_block_success(
        whitened_product,
        order,
        carrier,
    )
    upper = (
        math.sqrt(max(0.0, matched_success))
        + math.sqrt(max(0.0, concentration * gram_residual))
    ) ** 2
    upper_verified = whitened_success <= upper + 1000 * tolerance
    distance_verified = polar_distance <= gram_residual + 1000 * tolerance
    verified = bool(
        hermiticity <= 1000 * tolerance
        and local_eigenvalues[0] >= -1000 * tolerance
        and local_eigenvalues[-1] <= 1.0 + 1000 * tolerance
        and matched_hermiticity <= 1000 * tolerance
        and matched_eigenvalues[0] >= -1000 * tolerance
        and matched_eigenvalues[-1] <= 1.0 + 1000 * tolerance
        and block_residual <= 1000 * tolerance
        and overlap_residual <= 1000 * tolerance
        and matched_bound_residual <= 1000 * tolerance
        and distance_verified
        and upper_verified
    )
    return RawPolarMatchedFilterControl(
        control_id=control_id,
        n=sum(labels[0][0]),
        source_pair_count=len(labels),
        group_order=order,
        carrier_dimension=carrier,
        maximum_local_cross_hermiticity_residual=hermiticity,
        minimum_local_cross_eigenvalue=float(local_eigenvalues[0]),
        maximum_local_cross_eigenvalue=float(local_eigenvalues[-1]),
        matched_cross_hermiticity_residual=matched_hermiticity,
        matched_cross_minimum_eigenvalue=float(matched_eigenvalues[0]),
        matched_cross_maximum_eigenvalue=float(matched_eigenvalues[-1]),
        correct_block_identity_residual=block_residual,
        global_overlap_identity_residual=overlap_residual,
        normalized_raw_polar_overlap=overlap,
        unwhitened_matched_filter_success=matched_success,
        matched_success_upper_bound_residual=matched_bound_residual,
        polar_convolution_gram_residual=gram_residual,
        polar_to_convolution_distance=polar_distance,
        polar_distance_below_gram_residual=distance_verified,
        raw_convolution_concentration=concentration,
        whitened_correct_success=whitened_success,
        whitened_success_upper_bound=upper,
        whitened_success_bound_verified=upper_verified,
        exact_raw_polar_matched_filter_boundary_verified=verified,
        status=(
            "raw-polar-matched-filter-and-whitening-dichotomy-verified"
            if verified
            else "raw-polar-matched-filter-control-failure"
        ),
    )


def raw_polar_matched_filter_scaling(
    n: int,
    *,
    polynomial_concentration_degree: int = 20,
) -> RawPolarMatchedFilterScaling:
    if n < 2 or polynomial_concentration_degree < 0:
        raise ValueError("invalid scaling parameters")
    log_order = math.log2(math.factorial(n))
    copies = math.ceil(3.0 * log_order) + 2
    low_order_log = math.log2(n + 1) - n / 4.0
    gamma_log = copies * math.log2(GAMMA)
    low_order = 2.0**low_order_log if low_order_log > -1074 else 0.0
    gamma_term = 2.0**gamma_log if gamma_log > -1074 else 0.0
    overlap = min(1.0, low_order + gamma_term)
    inverse_order = 2.0**(-log_order) if log_order < 1074 else 0.0
    log_order_minus_one = log_order + math.log2(1.0 - inverse_order)
    gram_log = log_order_minus_one + copies * math.log2(3.0 / 4.0)
    concentration_log = polynomial_concentration_degree * math.log2(n)
    product_log = concentration_log + gram_log
    product = 2.0**product_log if product_log > -1074 else 0.0
    upper = (math.sqrt(overlap) + math.sqrt(product)) ** 2
    visible = upper < 0.1
    return RawPolarMatchedFilterScaling(
        n=n,
        log2_group_order=log_order,
        copy_count=copies,
        polynomial_concentration_degree=polynomial_concentration_degree,
        log2_polynomial_raw_concentration_bound=concentration_log,
        raw_polar_overlap_upper_bound=overlap,
        log2_polar_gram_residual_upper_bound=gram_log,
        log2_concentration_times_gram_upper_bound=product_log,
        whitened_success_upper_bound=upper,
        three_quarter_power_exponent=THREE_QUARTER_EXPONENT,
        polynomial_domination_forces_decoder_failure_asymptotically=True,
        finite_polynomial_domination_failure_visible=visible,
        status=(
            "polynomially-dominated-raw-state-forces-polar-decoder-failure"
            if visible
            else "asymptotic-raw-domination-separation-not-yet-visible"
        ),
    )


