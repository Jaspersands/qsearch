def _mat_vec_mod(mat: Sequence[Sequence[int]], vec: Sequence[int], p_mod: int) -> List[int]:
    n = len(mat)
    return [
        sum(int(mat[i][j]) * int(vec[j]) for j in range(n)) % p_mod
        for i in range(n)
    ]


def _solve_linear_system_fp(mat: Sequence[Sequence[int]], rhs: Sequence[int], p_prime: int) -> List[int]:
    n = len(mat)
    aug = [
        [int(mat[i][j]) % p_prime for j in range(n)] + [int(rhs[i]) % p_prime]
        for i in range(n)
    ]
    for col in range(n):
        pivot = next((r for r in range(col, n) if aug[r][col] != 0), None)
        if pivot is None:
            raise ValueError("Hankel matrix is singular over F_p")
        aug[col], aug[pivot] = aug[pivot], aug[col]
        inv_piv = pow(aug[col][col], -1, p_prime)
        for c in range(col, n + 1):
            aug[col][c] = (aug[col][c] * inv_piv) % p_prime
        for r in range(n):
            if r != col and aug[r][col] != 0:
                fac = aug[r][col]
                for c in range(col, n + 1):
                    aug[r][c] = (aug[r][c] - fac * aug[col][c]) % p_prime
    return [aug[i][n] for i in range(n)]


def evaluate_cayley_hamilton_hankel_recurrence_extrapolation(
    p_prime: int,
    m_matrix: Sequence[Sequence[int]],
    u_proj: Sequence[int],
    secret_s: Sequence[int],
    total_horizon_k: int = 20,
) -> Dict[str, Any]:
    """Recover the order-n recurrence from the first 2n terms and verify 100% exact prediction of terms 2n .. total_horizon_k - 1."""
    n = len(m_matrix)
    if total_horizon_k <= 2 * n:
        raise ValueError("total_horizon_k must exceed 2 * n")

    # 1. Generate true sequence z_k = <u, M^k s> mod p for k = 0 .. total_horizon_k - 1:
    z_true: List[int] = []
    v_curr = [int(x) % p_prime for x in secret_s]
    for _ in range(total_horizon_k):
        zk = sum(int(u_proj[i]) * v_curr[i] for i in range(n)) % p_prime
        z_true.append(zk)
        v_curr = _mat_vec_mod(m_matrix, v_curr, p_prime)

    # 2. Construct n x n Hankel matrix H_{i, j} = z_{i + j} from ONLY the first 2n terms z_0 .. z_{2n-1}:
    hankel = [
        [z_true[i + j] for j in range(n)]
        for i in range(n)
    ]
    rhs = [(-z_true[n + i]) % p_prime for i in range(n)]
    # Solve H * [c_n, c_{n-1}, ..., c_1]^T = -[z_n, ..., z_{2n-1}]^T mod p:
    c_rev = _solve_linear_system_fp(hankel, rhs, p_prime)
    # So z_{k + n} == -sum_{j=0}^{n-1} c_rev[j] * z_{k + j} (mod p)!

    # 3. Extrapolate from the first n terms all the way to total_horizon_k - 1:
    z_pred = list(z_true[:n])
    for k in range(n, total_horizon_k):
        nxt = (-sum(c_rev[j] * z_pred[k - n + j] for j in range(n))) % p_prime
        z_pred.append(nxt)

    out_of_sample_true = z_true[2 * n:]
    out_of_sample_pred = z_pred[2 * n:]

    return {
        "n_dim": n,
        "p_prime": p_prime,
        "training_samples_2n": 2 * n,
        "out_of_sample_predictions_tested": total_horizon_k - 2 * n,
        "recovered_recurrence_coeffs_c_n_to_c_1": c_rev,
        "true_sequence": z_true,
        "predicted_sequence": z_pred,
        "out_of_sample_exact_matches": sum(1 for a, b in zip(out_of_sample_true, out_of_sample_pred) if a == b),
        "exact_extrapolation_verified": (z_pred == z_true),
    }


