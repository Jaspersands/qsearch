def hierarchical_endpoint_scaling_record(
    n: int,
    *,
    fixed_jump_log2_arity: int = 12,
    target_error: float = 0.01,
) -> HierarchicalEndpointScalingRecord:
    if n < 3 or fixed_jump_log2_arity < 0 or not 0 < target_error < 1:
        raise ValueError("invalid hierarchical scaling parameters")
    order = math.factorial(n)
    selected = (order - 1).bit_length() + 2
    leaf_count = 1 << selected
    early_log2 = max(0, selected - fixed_jump_log2_arity)
    early_width = 1 << early_log2
    lower = 0.1
    upper = 10.0
    depth = selected
    return HierarchicalEndpointScalingRecord(
        n=n,
        group_order_decimal=str(order),
        selected_copy_count=selected,
        orientation_leaf_count_decimal=str(leaf_count),
        binary_tree_depth=depth,
        early_child_leaf_width_decimal=str(early_width),
        early_child_leaf_width_log2=early_log2,
        canonical_uniform_frame_normalization_log2=early_log2,
        fixed_level_short_metric_lower=lower,
        fixed_level_short_metric_upper=upper,
        conditional_endpoint_signal_normalization=math.sqrt(upper / lower),
        per_level_operator_error_budget=target_error / depth,
        required_per_level_native_mass_loss=f"o(1/{depth})",
        compact_aggregate_metric_oracle_proved=False,
        all_depth_parent_trim_recurrence_proved=False,
        conditional_binary_compiler_polynomial_given_metric_oracles=True,
        direct_schur_racah_naimark_ruled_out=False,
        status="binary-endpoint-compiler-conditional-aggregate-metric-access-open",
    )


