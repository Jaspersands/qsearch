"""Binary endpoint compilation needs aggregate metrics, not a small algebra.

At one hierarchical merge, quotient the internal child relations and retain
the common crossing coefficient space.  In internal/crossing coordinates let
the two positive child kernels be

    G_s = [D_s  B_s; B_s^*  C_s],       s in {L,R}.

The exact child short metrics are the Schur shorts

    E_s = C_s - B_s^* D_s^+ B_s,                         (1)

and the binary relative isometry and effects are

    M   = E_L+E_R,
    T_s = E_s^(1/2) M^(-1/2),
    K_s = T_s^*T_s = M^(-1/2)E_sM^(-1/2).                (2)

Equation (1) is the explicit operator-valued Schur/Racah normal form.  With
coordinate projections ``P_I,P_C``, its embedded version is

    P_C G_s P_C
      - P_C G_s P_I (P_I G_s P_I)^+ P_I G_s P_C.         (3)

Thus ``E_s`` lies in the finite-dimensional rational C*-closure generated by
the local physical/Racah kernel and the coordinate projections.  This is an
exact structural reduction, but it does not imply that the generated algebra
has polynomial dimension.

There is nevertheless a complete conditional binary compiler.  Suppose one
has coherent block encodings of ``E_L,E_R`` with normalization at most
``beta``, on one parent-propagated retained fiber satisfying

    a I <= E_s <= b I.                                    (4)

QSVT gives the contractions

    R_s = E_s^(1/2)/sqrt(b),
    Q   = sqrt(2a) M^(-1/2).

One address qubit prepares ``Y=2^(-1/2)[R_L;R_R]``.  Then exactly

    YQ = sqrt(a/b) T,       T=[T_L;T_R],                  (5)

so the endpoint signal normalization is ``sqrt(b/a)``, independent of the
leaf count.  Moreover

    K_s >= a/(2b) I,        I-K_s >= a/(2b) I.            (6)

For ``beta/a=poly(n)`` and inverse-polynomial requested error, standard
block-encoding functional calculus and robust oblivious amplification give a
polynomial coherent two-outcome dilation.  Per-level errors and discarded
native mass add.  At tree depth ``L``, one therefore needs local error
``O(epsilon/L)`` and conditional native loss ``o(1/L)`` per level.

The small-algebra shortcut is false even under stronger promises.  Let

    A=diag(a_1,...,a_D),       B=I+eta |v><v|,

where the ``a_i`` are distinct in ``[1,3/2]`` and every entry of ``v`` is
``1/sqrt(D)``.  If ``P_i`` are the spectral projections of ``A``, then

    P_i(B-I)P_j = (eta/D) |i><j|.                         (7)

Hence two positive generators with condition numbers at most ``3/2``
generate all of ``M_D(C)``, of dimension ``D^2``.  Their binary endpoint is
also uniformly separated from zero and one.  Fixed arity, conditioning, and
a constant endpoint gap therefore do not force a poly-dimensional Racah
algebra.  This is not a circuit lower bound: succinct block encodings of two
full-algebra generators can still make (5) efficient.

The present GPE/addressed-cross-map stack does not meet the positive premise.
It supplies leaf projectors or individual cross blocks.  Uniformly assembling
an aggregate child frame from ``q_s`` leaves exposes ``F_s/q_s``; obtaining
``E_s=X^*F_s^+X`` through that canonical route retains the leaf-width scale.
Finite physical vertex-kernel extraction proves (1) algebraically but does
not provide a reversible all-``n`` node labeler or a polynomial-normalized
aggregate block encoding.  Weak final-root/eight-way spectral laws supply
fixed-window native mass for those fixed levels, not the all-depth
``o(1/L)`` recurrence.

Consequently the next gate is exact and narrow: construct a uniform coherent
aggregate short-metric oracle (or implement (5) directly) for every retained
node.  A direct representation-specific Schur/Racah Naimark transform remains
possible.  No arbitrary-query lower bound, physical PGM, decoder, classical
separation, or speedup is proved.
"""

