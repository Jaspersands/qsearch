"""Sector-coherence lower bound for covariant hidden-label measurements.

Let a finite group ``G`` act as

    U_g = direct_sum_nu rho_nu(g) tensor I_(M_nu)

and let ``rho_g=U_g rho U_g^*`` be a freely labelled uniform covariant
ensemble.  A covariant POVM is generated by one positive seed ``E`` with

    sum_g U_g E U_g^* = I.

Schur averaging fixes every diagonal seed block:

    Tr_(V_nu)(E_nunu) = d_nu/|G| I_(M_nu).

For the graph Gamma whose vertices are irrep sectors and whose edges are the
nonzero off-diagonal blocks of ``E``, put ``A_Gamma`` for its adjacency matrix
and ``p_* = max_nu d_nu^2/|G|``.  Positivity of ``E`` and ``rho`` gives the
block trace Cauchy--Schwarz inequality

    |Tr(E_numu rho_munu)|
      <= sqrt(Tr(E_nunu rho_nunu) Tr(E_mumu rho_mumu)).

The partial-trace domination inequality then yields

    p_success = Tr(E rho)
      <= lambda_max(I+A_Gamma) p_*
      <= (Delta(Gamma)+1) p_* .                          (1)

More generally, for any declared graph, (1) holds plus the absolute trace
mass of omitted block pairs.  Thus tiny unregistered coherences cannot be
silently discarded.

For ``S_n``, ``p_*`` is the largest Plancherel atom.  The known maximal-irrep
asymptotic makes it ``exp(-Theta(sqrt(n)))``.  Constant-success covariant
decoding therefore requires ``exp(Omega(sqrt(n)))`` sector-coherence degree,
unless comparable success mass is carried by blocks omitted from the graph.
This kills polynomial-sector catalogs and exactly sparse local ansatzes as
final decoders.  It does not kill an implicitly dense structured transform.

If a seed is obtained from a sector-diagonal effect by ``L`` layers whose
block row and column degrees are at most ``b``, its coherence degree is at
most ``b^(2L)-1``.  Consequently constant success requires

    L >= log(target_success/p_*) / (2 log b).             (2)

The depth bound excludes shallow sector-local recoupling, not general
polynomial-depth or dense coherent circuits.  No speedup is claimed.
"""

