def _sector_slices(
    irrep_dimensions: tuple[int, ...],
    multiplicity_dimensions: tuple[int, ...],
) -> tuple[slice, ...]:
    if not irrep_dimensions or len(irrep_dimensions) != len(
        multiplicity_dimensions
    ):
        raise ValueError("matching nonempty sector dimensions are required")
    if any(value < 1 for value in (*irrep_dimensions, *multiplicity_dimensions)):
        raise ValueError("all sector dimensions must be positive")
    output: list[slice] = []
    offset = 0
    for irrep, multiplicity in zip(
        irrep_dimensions,
        multiplicity_dimensions,
    ):
        width = irrep * multiplicity
        output.append(slice(offset, offset + width))
        offset += width
    return tuple(output)


def _partial_trace_irrep(
    block: np.ndarray,
    irrep_dimension: int,
    multiplicity_dimension: int,
) -> np.ndarray:
    expected = irrep_dimension * multiplicity_dimension
    if block.shape != (expected, expected):
        raise ValueError("sector block has the wrong dimension")
    tensor = block.reshape(
        irrep_dimension,
        multiplicity_dimension,
        irrep_dimension,
        multiplicity_dimension,
    )
    return np.trace(tensor, axis1=0, axis2=2)


def _coherence_adjacency(
    seed: np.ndarray,
    slices: tuple[slice, ...],
    tolerance: float,
) -> np.ndarray:
    adjacency = np.zeros((len(slices), len(slices)), dtype=float)
    for left in range(len(slices)):
        for right in range(left + 1, len(slices)):
            block = seed[slices[left], slices[right]]
            if np.linalg.norm(block, ord="fro") > tolerance:
                adjacency[left, right] = 1.0
                adjacency[right, left] = 1.0
    return adjacency


def _omitted_trace_mass(
    seed: np.ndarray,
    state: np.ndarray,
    slices: tuple[slice, ...],
    declared_adjacency: np.ndarray,
) -> float:
    total = 0.0
    for left in range(len(slices)):
        for right in range(left + 1, len(slices)):
            if declared_adjacency[left, right]:
                continue
            term = np.trace(
                seed[slices[left], slices[right]]
                @ state[slices[right], slices[left]]
            )
            total += 2.0 * abs(complex(term))
    return total


def audit_sector_coherence_bound(
    control_id: str,
    group_order: int,
    irrep_dimensions: tuple[int, ...],
    multiplicity_dimensions: tuple[int, ...],
    seed: np.ndarray,
    state: np.ndarray,
    *,
    declared_adjacency: np.ndarray | None = None,
    tolerance: float = 1e-10,
) -> SectorCoherenceControl:
    """Audit the exact graph and robust omitted-coherence bounds."""

    if group_order < 1:
        raise ValueError("group order must be positive")
    slices = _sector_slices(irrep_dimensions, multiplicity_dimensions)
    total_dimension = slices[-1].stop
    if seed.shape != (total_dimension, total_dimension):
        raise ValueError("seed has the wrong dimension")
    if state.shape != seed.shape:
        raise ValueError("state and seed must have the same dimension")
    hermitian_seed = (seed + seed.conj().T) / 2.0
    hermitian_state = (state + state.conj().T) / 2.0
    if np.linalg.eigvalsh(hermitian_seed)[0] < -100 * tolerance:
        raise ValueError("seed must be positive semidefinite")
    if np.linalg.eigvalsh(hermitian_state)[0] < -100 * tolerance:
        raise ValueError("state must be positive semidefinite")
    if abs(float(np.trace(hermitian_state).real) - 1.0) > 100 * tolerance:
        raise ValueError("state must have trace one")

    partial_trace_residual = 0.0
    diagonal_pairings: list[float] = []
    sector_state_masses: list[float] = []
    for sector, (index, irrep, multiplicity) in enumerate(
        zip(slices, irrep_dimensions, multiplicity_dimensions)
    ):
        seed_block = hermitian_seed[index, index]
        state_block = hermitian_state[index, index]
        expected = (irrep / group_order) * np.eye(multiplicity)
        observed = _partial_trace_irrep(seed_block, irrep, multiplicity)
        partial_trace_residual = max(
            partial_trace_residual,
            float(np.linalg.norm(observed - expected, ord=2)),
        )
        diagonal_pairings.append(
            float(np.trace(seed_block @ state_block).real)
        )
        sector_state_masses.append(float(np.trace(state_block).real))
    if partial_trace_residual > 100 * tolerance:
        raise ValueError("seed does not satisfy covariant completeness")

    exact_adjacency = _coherence_adjacency(
        hermitian_seed,
        slices,
        tolerance,
    )
    if declared_adjacency is None:
        graph = exact_adjacency
    else:
        graph = np.asarray(declared_adjacency, dtype=float)
        if graph.shape != exact_adjacency.shape:
            raise ValueError("declared adjacency has the wrong shape")
        if np.linalg.norm(graph - graph.T, ord=2) > tolerance:
            raise ValueError("declared adjacency must be symmetric")
        if np.max(np.abs(np.diag(graph))) > tolerance:
            raise ValueError("declared adjacency must have zero diagonal")
        graph = (np.abs(graph) > tolerance).astype(float)

    maximum_cauchy_residual = 0.0
    for left in range(len(slices)):
        for right in range(left + 1, len(slices)):
            term = np.trace(
                hermitian_seed[slices[left], slices[right]]
                @ hermitian_state[slices[right], slices[left]]
            )
            squared = abs(complex(term)) ** 2
            product = diagonal_pairings[left] * diagonal_pairings[right]
            maximum_cauchy_residual = max(
                maximum_cauchy_residual,
                squared - product,
            )

    degrees = graph.sum(axis=1)
    maximum_degree = int(round(float(max(degrees, default=0.0))))
    spectral_factor = float(
        np.linalg.eigvalsh(np.eye(len(slices)) + graph)[-1]
    )
    maximum_atom = max(
        irrep * irrep / group_order for irrep in irrep_dimensions
    )
    success = float(np.trace(hermitian_seed @ hermitian_state).real)
    spectral_bound = spectral_factor * maximum_atom
    degree_bound = (maximum_degree + 1) * maximum_atom
    omitted = _omitted_trace_mass(
        hermitian_seed,
        hermitian_state,
        slices,
        graph,
    )
    robust_bound = spectral_bound + omitted
    spectral_residual = max(0.0, success - spectral_bound)
    degree_residual = max(0.0, success - degree_bound)
    robust_residual = max(0.0, success - robust_bound)
    exact_graph = bool(np.array_equal(graph, exact_adjacency))
    verified = bool(
        partial_trace_residual <= 100 * tolerance
        and maximum_cauchy_residual <= 100 * tolerance
        and (not exact_graph or spectral_residual <= 100 * tolerance)
        and (not exact_graph or degree_residual <= 100 * tolerance)
        and robust_residual <= 100 * tolerance
    )
    return SectorCoherenceControl(
        control_id=control_id,
        group_order=group_order,
        sector_count=len(slices),
        total_dimension=total_dimension,
        irrep_dimensions=irrep_dimensions,
        multiplicity_dimensions=multiplicity_dimensions,
        coherence_edge_count=int(round(float(graph.sum() / 2))),
        maximum_coherence_degree=maximum_degree,
        coherence_graph_spectral_factor=spectral_factor,
        maximum_plancherel_atom=maximum_atom,
        exact_success_probability=success,
        graph_spectral_success_upper_bound=spectral_bound,
        maximum_degree_success_upper_bound=degree_bound,
        omitted_block_trace_mass=omitted,
        robust_graph_success_upper_bound=robust_bound,
        maximum_seed_partial_trace_residual=partial_trace_residual,
        maximum_block_trace_cauchy_residual=max(0.0, maximum_cauchy_residual),
        spectral_bound_residual=spectral_residual,
        degree_bound_residual=degree_residual,
        robust_bound_residual=robust_residual,
        graph_bound_saturated=abs(success - spectral_bound) <= 100 * tolerance,
        exact_sector_coherence_bound_verified=verified,
        status=(
            "sector-coherence-bound-saturated"
            if verified and abs(success - spectral_bound) <= 100 * tolerance
            else "sector-coherence-bound-verified"
            if verified
            else "sector-coherence-bound-control-failure"
        ),
    )


def cyclic_clique_control(
    group_order: int,
    component_sizes: tuple[int, ...],
    selected_component: int,
    *,
    declared_empty_graph: bool = False,
) -> SectorCoherenceControl:
    """Build an abelian covariant seed with clique-block coherence.

    The cyclic representation has ``|G|`` distinct one-dimensional sectors.
    Diagonal seed entries are ``1/|G|`` and character orthogonality makes its
    orbit a complete covariant POVM.  A state uniform on one clique saturates
    the graph-spectral theorem by its clique size.
    """

    if group_order < 2 or sum(component_sizes) != group_order:
        raise ValueError("component sizes must partition the group order")
    if any(size < 1 for size in component_sizes):
        raise ValueError("component sizes must be positive")
    if not 0 <= selected_component < len(component_sizes):
        raise ValueError("selected component is out of range")
    seed = np.zeros((group_order, group_order), dtype=complex)
    ranges: list[range] = []
    offset = 0
    for size in component_sizes:
        component = range(offset, offset + size)
        ranges.append(component)
        indices = np.asarray(tuple(component), dtype=int)
        seed[np.ix_(indices, indices)] = 1.0 / group_order
        offset += size
    chosen = tuple(ranges[selected_component])
    vector = np.zeros(group_order, dtype=complex)
    vector[list(chosen)] = 1.0 / math.sqrt(len(chosen))
    state = np.outer(vector, vector.conj())
    declared = (
        np.zeros((group_order, group_order), dtype=float)
        if declared_empty_graph
        else None
    )
    return audit_sector_coherence_bound(
        (
            f"CYCLIC-C{group_order}-COMPONENT-"
            f"{component_sizes[selected_component]}"
            + ("-OMITTED" if declared_empty_graph else "")
        ),
        group_order,
        (1,) * group_order,
        (1,) * group_order,
        seed,
        state,
        declared_adjacency=declared,
    )


def minimum_sector_local_depth(
    maximum_plancherel_atom: float,
    target_success_probability: float,
    local_layer_block_degree: int,
) -> int:
    """Return the exact integer consequence of ``b^(2L) p_* >= eta``."""

    if not 0 < maximum_plancherel_atom <= 1:
        raise ValueError("Plancherel atom must lie in (0,1]")
    if not 0 < target_success_probability <= 1:
        raise ValueError("target success must lie in (0,1]")
    if local_layer_block_degree < 2:
        raise ValueError("local block degree must be at least two")
    ratio = target_success_probability / maximum_plancherel_atom
    if ratio <= 1:
        return 0
    return math.ceil(
        math.log(ratio) / (2.0 * math.log(local_layer_block_degree))
        - 1e-12
    )


def symmetric_group_coherence_scaling_record(
    n: int,
    *,
    target_success_probability: float = 2 / 3,
) -> SymmetricGroupCoherenceScalingRecord:
    if n < 2:
        raise ValueError("n must be at least two")
    dimensions = tuple(
        (partition, hook_length_dimension(partition))
        for partition in integer_partitions(n)
    )
    maximum_partition, maximum_dimension = max(
        dimensions,
        key=lambda row: (row[1], row[0]),
    )
    order = math.factorial(n)
    atom = maximum_dimension * maximum_dimension / order
    required_factor = target_success_probability / atom
    required_degree = max(0, math.ceil(required_factor - 1 - 1e-12))
    log_degree = math.log2(max(1.0, required_factor - 1.0))
    local_degree = max(2, n * n)
    depth = minimum_sector_local_depth(
        atom,
        target_success_probability,
        local_degree,
    )
    return SymmetricGroupCoherenceScalingRecord(
        n=n,
        partition_count=len(dimensions),
        group_order_decimal=str(order),
        maximum_irrep_partition=maximum_partition,
        maximum_irrep_dimension_decimal=str(maximum_dimension),
        maximum_plancherel_atom=atom,
        target_success_probability=target_success_probability,
        minimum_required_maximum_degree=required_degree,
        log2_minimum_required_maximum_degree=log_degree,
        local_layer_block_degree=local_degree,
        minimum_sector_local_layer_depth=depth,
        polynomial_degree_decoder_ruled_out_at_scale=(
            required_degree > n**4
        ),
        polylog_depth_local_decoder_ruled_out_asymptotically=True,
        status="exact-sector-coherence-degree-lower-bound",
    )


