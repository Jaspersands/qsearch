def permutation_parity(permutation: tuple[int, ...]) -> int:
    inversions = sum(
        permutation[left] > permutation[right]
        for left in range(len(permutation))
        for right in range(left + 1, len(permutation))
    )
    return inversions & 1


def component_syndrome(gamma: GammaElement) -> int:
    if len(gamma) % 2 != 1:
        raise ValueError("Gamma must have one target and source pairs")
    copy_count = (len(gamma) - 1) // 2
    target = permutation_parity(gamma[0])
    syndrome = 0
    for pair_index in range(copy_count):
        bit = (
            target
            ^ permutation_parity(gamma[1 + 2 * pair_index])
            ^ permutation_parity(gamma[2 + 2 * pair_index])
        )
        syndrome |= bit << pair_index
    return syndrome


def omega_syndrome(element: OmegaElement) -> int:
    return component_syndrome(element[0])


def syndrome_representative(
    n: int,
    copy_count: int,
    syndrome: int,
) -> OmegaElement:
    if n < 2 or not 0 <= syndrome < 1 << copy_count:
        raise ValueError("invalid degree, copy count, or syndrome")
    identity = _identity(n)
    odd = list(range(n))
    odd[0], odd[1] = odd[1], odd[0]
    gamma = [identity for _ in range(2 * copy_count + 1)]
    for pair_index in range(copy_count):
        if syndrome & (1 << pair_index):
            gamma[1 + 2 * pair_index] = tuple(odd)
    return tuple(gamma), 0


def _generated_subgroup(
    generators: tuple[OmegaElement, ...],
) -> frozenset[OmegaElement]:
    if not generators:
        raise ValueError("at least one generator is required")
    identity_gamma = tuple(
        _identity(len(generators[0][0][0])) for _ in generators[0][0]
    )
    identity: OmegaElement = (identity_gamma, 0)
    found = {identity}
    queue: deque[OmegaElement] = deque((identity,))
    while queue:
        current = queue.popleft()
        for generator in generators:
            image = omega_multiply(current, generator)
            if image not in found:
                found.add(image)
                queue.append(image)
    return frozenset(found)


def _source_column_syndromes(
    n: int,
    copy_count: int,
    labels: tuple[tuple[int, int], ...],
    gamma: tuple[GammaElement, ...],
) -> tuple[int, ...]:
    del n, copy_count
    return tuple(component_syndrome(gamma[label]) for _orientation, label in labels)


def audit_syndrome_component_reduction(
    n: int,
    copy_count: int,
    *,
    tolerance: float = 1e-9,
) -> SyndromeComponentControl:
    group, gamma, omega, branch_subgroup, diagonal_subgroup = _group_data(
        n,
        copy_count,
    )
    generated = _generated_subgroup(branch_subgroup + diagonal_subgroup)
    kernel = frozenset(element for element in omega if omega_syndrome(element) == 0)
    synthesis, labels, direct_gamma = direct_orientation_synthesis(n, copy_count)
    row_syndromes = tuple(component_syndrome(point) for point in direct_gamma)
    column_syndromes = _source_column_syndromes(
        n,
        copy_count,
        labels,
        direct_gamma,
    )
    orientation_count = 1 << copy_count
    blocks: list[np.ndarray] = []
    off_syndrome = 0.0
    for row in range(synthesis.shape[0]):
        for column in np.flatnonzero(np.abs(synthesis[row]) > tolerance):
            if row_syndromes[row] != column_syndromes[column]:
                off_syndrome = max(off_syndrome, abs(float(synthesis[row, column])))
    for syndrome in range(orientation_count):
        rows = [index for index, value in enumerate(row_syndromes) if value == syndrome]
        columns = [
            index for index, value in enumerate(column_syndromes) if value == syndrome
        ]
        blocks.append(synthesis[np.ix_(rows, columns)])
    reference = np.linalg.svd(blocks[0], compute_uv=False)
    spectrum_residual = max(
        float(np.max(np.abs(np.linalg.svd(block, compute_uv=False) - reference)))
        for block in blocks
    )
    normalized_positive = reference[reference > tolerance] / math.sqrt(orientation_count)
    unitary_distance = max(
        abs(1.0 - float(value)) for value in normalized_positive
    )

    canonicalization_failures = 0
    for element in omega:
        syndrome = omega_syndrome(element)
        representative = syndrome_representative(n, copy_count, syndrome)
        if omega_syndrome(omega_multiply(representative, element)) != 0:
            canonicalization_failures += 1

    expected_component_count = orientation_count
    physical_component_dimension = len(gamma) // orientation_count
    source_component_dimension = synthesis.shape[1] // orientation_count
    verified = bool(
        generated == kernel
        and len(kernel) * orientation_count == len(omega)
        and off_syndrome <= tolerance
        and spectrum_residual <= tolerance
        and canonicalization_failures == 0
        and all(block.shape == blocks[0].shape for block in blocks)
    )
    return SyndromeComponentControl(
        n=n,
        copy_count=copy_count,
        orientation_count=orientation_count,
        omega_order=len(omega),
        generated_subgroup_order=len(generated),
        syndrome_kernel_order=len(kernel),
        generated_subgroup_equals_syndrome_kernel=generated == kernel,
        component_count=len(blocks),
        predicted_component_count=expected_component_count,
        physical_component_dimension=physical_component_dimension,
        source_component_dimension=source_component_dimension,
        maximum_off_syndrome_incidence=off_syndrome,
        maximum_component_singular_spectrum_residual=spectrum_residual,
        maximum_syndrome_canonicalization_failure_count=canonicalization_failures,
        minimum_normalized_component_positive_singular_value=float(
            np.min(normalized_positive)
        ),
        maximum_normalized_component_positive_singular_value=float(
            np.max(normalized_positive)
        ),
        minimum_unitary_only_distance_to_component_polar=unitary_distance,
        exact_syndrome_component_reduction_verified=verified,
        status=(
            "exact-syndrome-components-reduced-to-one-connected-incidence"
            if verified
            else "syndrome-component-control-failure"
        ),
    )


def syndrome_component_scaling_record(
    n: int,
    *,
    extra_copies: int = 2,
) -> SyndromeComponentScalingRecord:
    if n < 5 or extra_copies < 0:
        raise ValueError("n>=5 and nonnegative copy offset are required")
    group_order = math.factorial(n)
    group_log2 = math.log2(group_order)
    copy_count = (group_order - 1).bit_length() + extra_copies
    orientation_count = 1 << copy_count
    ratio = orientation_count / group_order
    gamma = 1.0 + (orientation_count - 1) / group_order
    return SyndromeComponentScalingRecord(
        n=n,
        group_order_log2=group_log2,
        copy_count=copy_count,
        component_count_log2=copy_count,
        connected_group_order_log2=(2 * copy_count + 1) * group_log2,
        source_component_dimension_log2=2 * copy_count * group_log2,
        physical_component_dimension_log2=(
            (2 * copy_count + 1) * group_log2 - copy_count
        ),
        source_to_physical_component_dimension_ratio=ratio,
        frame_first_moment_per_physical_dimension=ratio,
        frame_second_to_first_moment_ratio=gamma,
        total_support_rank_fraction_lower_bound=ratio / gamma,
        flat_benchmark_normalized_singular_amplitude_log2=-0.5 * group_log2,
        syndrome_computation_polynomial=True,
        zero_component_canonicalization_polynomial=True,
        syndrome_only_polar_compiler_proved=False,
        status="one-connected-component-canonicalized-matrix-cs-polar-open",
    )


