"""Parity-component reduction of the homogeneous orientation incidence.

Use the homogeneous model

    Omega = Gamma semidirect B,
    Gamma = S_n^(2K+1),  B=C_2^K,

with zero-orientation diagonal subgroup ``D``.  For
``gamma=(t,x_1,y_1,...,x_K,y_K)``, define the syndrome

    z_i(gamma) = sgn(t) + sgn(x_i) + sgn(y_i) mod 2.       (1)

Pair swaps preserve (1), so it extends to a homomorphism
``z:Omega->F_2^K``.  Both ``B`` and ``D`` lie in its kernel.

For ``n>=5``, the affine generated-subgroup theorem identifies the subgroup
generated by all orientation diagonals as the preimage of the incidence sign
code, with an independent ``A_n`` on every target/source coordinate.  Since
``B`` conjugates ``D`` through all orientations,

    L=<B,D>=ker(z),
    |L|=|S_n|^(2K+1),
    [Omega:L]=2^K.                                         (2)

The bipartite incidence between ``Omega/D`` and ``Omega/B`` has connected
components equal to right ``L`` cosets.  Hence the complete synthesis and its
polar split as

    T  is unitarily equivalent to I_(2^K) tensor T_0,
    polar(T) is unitarily equivalent to I_(2^K) tensor polar(T_0),  (3)

where ``T_0`` is the connected incidence ``L/D -> L/B``.  Its source and
physical dimensions are respectively

    |L:D|=|S_n|^(2K),   |L:B|=|S_n|^(2K+1)/2^K.             (4)

The syndrome is efficiently computable from permutation parities.  A fixed
odd permutation in the first coordinate of pair ``i`` supplies a representative
for syndrome bit ``i``; controlled multiplication canonicalizes every component
to zero syndrome.  Thus future compiler work only needs one connected block.

This is a structural reduction, not the polar.  Branch-controlled translations,
syndrome Fourier transforms, and other unitaries acting before or after the
normalized incidence ``T_0/sqrt(2^K)`` preserve all singular values.  They
cannot turn it into its polar unless its nonzero singular values were already
one.  The finite controls have a constant distance from that condition, while
the natural flat benchmark has singular amplitude ``Theta(|S_n|^-1/2)``.
Syndrome relocation therefore removes component replication but not the
inverse-width normalization or the high-rank matrix-CS recoupling.

The syndrome is a conserved gauge charge, not a hidden-label statistic.  No
orientation-polar circuit, decoder, classical separation, or speedup is
claimed.
"""

