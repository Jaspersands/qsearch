def _flatten_mat(mat: Any, d: int) -> tuple[int, ...]:
    return tuple(int(mat[i, j]) for i in range(d) for j in range(d))


def _unflatten_mat(vec: Sequence[int], d: int, p: int) -> Any:
    rows = [[int(vec[i * d + j]) % p for j in range(d)] for i in range(d)]
    return _matrix(rows, p)


def _rref_row_basis(vectors: Sequence[Sequence[int]], width: int, p: int) -> tuple[tuple[int, ...], ...]:
    if not vectors:
        return ()
    nonempty = [row for row in vectors if any(int(x) % p for x in row)]
    if not nonempty:
        return ()
    reduced, rank = _fmpz_rref(nonempty, p)
    return tuple(tuple(int(x) % p for x in row) for row in reduced[:rank] if any(row))


def _right_nullspace_basis(rows: Sequence[Sequence[int]], d: int, p: int) -> tuple[tuple[int, ...], ...]:
    """Return a tuple of column vectors (as length-d tuples) spanning {v in F_p^d : rows * v = 0}."""
    if not rows:
        return tuple(tuple(int(i == j) for j in range(d)) for i in range(d))
    return tuple(_fmpz_nullspace_basis(rows, d, p))


@dataclass(frozen=True)
class CommonAlgebraGuardResult:
    status: str
    prime: int
    dimension: int
    generator_count: int
    algebra_dimension: int
    nilpotency_index: int | None
    guard_passed: bool
    all_generators_order_dividing_p: bool
    generators_commute: bool
    basis_matrices: tuple[tuple[tuple[int, ...], ...], ...]


def compute_common_nonunital_algebra(
    prime: int,
    dimension: int,
    generators: Sequence[Sequence[Sequence[int]]],
    *,
    max_nilpotency_index: int | None = None,
) -> CommonAlgebraGuardResult:
    """Compute the common nonunital associative algebra J = Alg_{F_p}(g_i - I) and check J^nu = 0 with nu <= p."""
    if type(prime) is not int or prime < 3:
        raise ValueError("odd prime >= 3 required")
    if type(dimension) is not int or dimension < 1:
        raise ValueError("positive integer dimension required")
    if not generators:
        raise ValueError("nonempty sequence of ambient matrix generators required")

    id_mat = _matrix(_identity(dimension), prime)
    zero_mat = id_mat - id_mat
    x_mats: list[Any] = []
    g_mats: list[Any] = []
    for g in generators:
        if len(g) != dimension:
            raise ValueError("square matrix of matching dimension required")
        for row in g:
            _canonical(row, dimension, prime)
        g_mat = _matrix(g, prime)
        if _rank(g, prime) != dimension:
            raise ValueError("invertible ambient matrix generator required")
        g_mats.append(g_mat)
        x_mats.append(g_mat - id_mat)

    all_order_p = all(matrix_power(prime, g_mat, prime) == id_mat for g_mat in g_mats)
    commute = all(
        g_mats[i] * g_mats[j] == g_mats[j] * g_mats[i]
        for i in range(len(g_mats))
        for j in range(i + 1, len(g_mats))
    )

    flat_width = dimension * dimension
    basis_vecs = _rref_row_basis([_flatten_mat(x, dimension) for x in x_mats], flat_width, prime)

    # Close under left and right multiplication by each X_i = g_i - I, capped at dimension^2
    while basis_vecs:
        current_rank = len(basis_vecs)
        if current_rank > flat_width:
            raise RuntimeError("algebra dimension exceeded D^2 cap")
        basis_mats = [_unflatten_mat(v, dimension, prime) for v in basis_vecs]
        candidates = list(basis_vecs)
        for b_mat in basis_mats:
            for x_mat in x_mats:
                prod_left = x_mat * b_mat
                if prod_left != zero_mat:
                    candidates.append(_flatten_mat(prod_left, dimension))
                prod_right = b_mat * x_mat
                if prod_right != zero_mat:
                    candidates.append(_flatten_mat(prod_right, dimension))
        new_basis = _rref_row_basis(candidates, flat_width, prime)
        if len(new_basis) == current_rank:
            basis_vecs = new_basis
            break
        basis_vecs = new_basis

    j_basis_mats = [_unflatten_mat(v, dimension, prime) for v in basis_vecs]
    basis_tuples = tuple(
        tuple(tuple(int(mat[i, j]) for j in range(dimension)) for i in range(dimension))
        for mat in j_basis_mats
    )

    if not j_basis_mats:
        return CommonAlgebraGuardResult(
            status="COMMON_ALGEBRA_NILPOTENT_OK",
            prime=prime,
            dimension=dimension,
            generator_count=len(generators),
            algebra_dimension=0,
            nilpotency_index=1,
            guard_passed=True,
            all_generators_order_dividing_p=all_order_p,
            generators_commute=commute,
            basis_matrices=(),
        )

    index_cap = max_nilpotency_index if max_nilpotency_index is not None else max(prime, len(j_basis_mats) + 1)
    power_vecs = basis_vecs
    nu: int | None = None
    for exponent in range(2, index_cap + 2):
        power_mats = [_unflatten_mat(v, dimension, prime) for v in power_vecs]
        next_candidates: list[tuple[int, ...]] = []
        for x_mat in x_mats:
            for p_mat in power_mats:
                prod = x_mat * p_mat
                if prod != zero_mat:
                    next_candidates.append(_flatten_mat(prod, dimension))
        next_vecs = _rref_row_basis(next_candidates, flat_width, prime)
        if not next_vecs:
            nu = exponent
            break
        if len(next_vecs) == len(power_vecs):
            # J^k stabilized at a nonzero subalgebra => not nilpotent
            nu = None
            break
        power_vecs = next_vecs

    guard_ok = nu is not None and nu <= prime
    if nu is None:
        status = "COMMON_ALGEBRA_NONNILPOTENT"
    elif nu > prime:
        status = "COMMON_ALGEBRA_INDEX_EXCEEDS_PRIME"
    else:
        status = "COMMON_ALGEBRA_NILPOTENT_OK"

    return CommonAlgebraGuardResult(
        status=status,
        prime=prime,
        dimension=dimension,
        generator_count=len(generators),
        algebra_dimension=len(j_basis_mats),
        nilpotency_index=nu,
        guard_passed=guard_ok,
        all_generators_order_dividing_p=all_order_p,
        generators_commute=commute,
        basis_matrices=basis_tuples,
    )


def truncated_matrix_log(
    matrix: Sequence[Sequence[int]],
    prime: int,
    nilpotency_index: int,
) -> tuple[tuple[int, ...], ...]:
    """Compute log(I + X) = sum_{k=1}^{nu-1} ((-1)^(k-1) / k) X^k mod p for X = matrix - I."""
    if nilpotency_index > prime:
        raise ValueError("nilpotency_index <= prime required for denominators in truncated matrix log")
    d = len(matrix)
    id_mat = _matrix(_identity(d), prime)
    x_mat = _matrix(matrix, prime) - id_mat
    acc = id_mat - id_mat
    power = id_mat
    for k in range(1, nilpotency_index):
        power = power * x_mat
        coeff = ((-1) ** (k - 1) * pow(k, -1, prime)) % prime
        acc = acc + coeff * power
    return tuple(tuple(int(acc[i, j]) % prime for j in range(d)) for i in range(d))


def truncated_matrix_exp(
    lie_matrix: Sequence[Sequence[int]],
    prime: int,
    nilpotency_index: int,
) -> tuple[tuple[int, ...], ...]:
    """Compute exp(A) = sum_{k=0}^{nu-1} (1 / k!) A^k mod p for A in J with J^nu = 0."""
    if nilpotency_index > prime:
        raise ValueError("nilpotency_index <= prime required for denominators in truncated matrix exp")
    d = len(lie_matrix)
    id_mat = _matrix(_identity(d), prime)
    a_mat = _matrix(lie_matrix, prime)
    acc = id_mat
    power = id_mat
    fact_inv = 1
    for k in range(1, nilpotency_index):
        power = power * a_mat
        fact_inv = (fact_inv * pow(k, -1, prime)) % prime
        acc = acc + fact_inv * power
    return tuple(tuple(int(acc[i, j]) % prime for j in range(d)) for i in range(d))


def close_matrix_lie_span(
    log_generators: Sequence[Sequence[Sequence[int]]],
    prime: int,
    dimension: int,
) -> tuple[tuple[tuple[int, ...], ...], ...]:
    """Close the F_p-span of matrix logs under [A, B] = A*B - B*A."""
    flat_width = dimension * dimension
    zero_mat = _matrix([[0] * dimension for _ in range(dimension)], prime)
    basis_vecs = _rref_row_basis(
        [_flatten_mat(_matrix(m, prime), dimension) for m in log_generators],
        flat_width,
        prime,
    )
    while basis_vecs:
        current_rank = len(basis_vecs)
        basis_mats = [_unflatten_mat(v, dimension, prime) for v in basis_vecs]
        candidates = list(basis_vecs)
        for i in range(len(basis_mats)):
            for j in range(i + 1, len(basis_mats)):
                comm = basis_mats[i] * basis_mats[j] - basis_mats[j] * basis_mats[i]
                if comm != zero_mat:
                    candidates.append(_flatten_mat(comm, dimension))
        new_basis = _rref_row_basis(candidates, flat_width, prime)
        if len(new_basis) == current_rank:
            basis_vecs = new_basis
            break
        basis_vecs = new_basis
    return tuple(
        tuple(
            tuple(int(vec[i * dimension + j]) % prime for j in range(dimension))
            for i in range(dimension)
        )
        for vec in basis_vecs
    )


@dataclass(frozen=True)
class CommonAlgebraStabilizerResult:
    status: str
    prime: int
    dimension: int
    algebra_dimension: int
    nilpotency_index: int | None
    ambient_lie_dimension: int
    recognized_row_rank: int
    stabilizer_lie_dimension: int
    stabilizer_lie_basis: tuple[tuple[tuple[int, ...], ...], ...]
    stabilizer_group_generators: tuple[tuple[tuple[int, ...], ...], ...]
    stabilizer_lie_is_subalgebra: bool
    all_generators_fix_moore_form: bool


def recover_common_algebra_moore_stabilizer(
    recognition: MooreRecognition,
    generators: Sequence[Sequence[Sequence[int]]],
) -> CommonAlgebraStabilizerResult:
    """Recover exact stabilizer generators inside Gamma = <g_1, ..., g_s> when J^nu = 0 with nu <= p."""
    if not isinstance(recognition, MooreRecognition) or not recognition.accepted:
        raise ValueError("accepted MooreRecognition required")
    prime = recognition.prime
    dimension = recognition.dimension
    rows = recognition.rows
    r = len(rows)

    guard = compute_common_nonunital_algebra(prime, dimension, generators)
    if not guard.guard_passed or guard.nilpotency_index is None:
        return CommonAlgebraStabilizerResult(
            status=guard.status,
            prime=prime,
            dimension=dimension,
            algebra_dimension=guard.algebra_dimension,
            nilpotency_index=guard.nilpotency_index,
            ambient_lie_dimension=0,
            recognized_row_rank=r,
            stabilizer_lie_dimension=0,
            stabilizer_lie_basis=(),
            stabilizer_group_generators=(),
            stabilizer_lie_is_subalgebra=False,
            all_generators_fix_moore_form=False,
        )

    nu = guard.nilpotency_index
    log_gens = [truncated_matrix_log(g, prime, nu) for g in generators]
    lie_basis = close_matrix_lie_span(log_gens, prime, dimension)
    m = len(lie_basis)

    # Annihilator N has columns spanning {v in F_p^D : W * v = 0}, shape D x (D - r)
    null_cols = _right_nullspace_basis(rows, dimension, prime)
    nullity = len(null_cols)
    w_mat = _matrix(rows, prime)

    if nullity == 0 or m == 0:
        kernel_coords = tuple(tuple(int(i == j) for j in range(m)) for i in range(m))
    else:
        n_rows = [[null_cols[col_idx][row_idx] for col_idx in range(nullity)] for row_idx in range(dimension)]
        n_mat = _matrix(n_rows, prime)
        num_equations = r * nullity
        # Build num_equations x m constraint matrix M where column j is vec(W * B_j * N)
        constraint_rows = [[0] * m for _ in range(num_equations)]
        for j, b_grid in enumerate(lie_basis):
            b_mat = _matrix(b_grid, prime)
            wbn = w_mat * b_mat * n_mat
            for row_idx in range(r):
                for col_idx in range(nullity):
                    constraint_rows[row_idx * nullity + col_idx][j] = int(wbn[row_idx, col_idx]) % prime
        kernel_cols = _right_nullspace_basis(constraint_rows, m, prime)
        kernel_coords = _rref_row_basis(kernel_cols, m, prime)

    lie_mats = [_matrix(b_grid, prime) for b_grid in lie_basis]
    zero_mat = _matrix([[0] * dimension for _ in range(dimension)], prime)
    h_basis: list[tuple[tuple[int, ...], ...]] = []
    h_generators: list[tuple[tuple[int, ...], ...]] = []
    for coord in kernel_coords:
        acc = zero_mat
        for c_val, b_mat in zip(coord, lie_mats):
            if c_val % prime:
                acc = acc + (c_val % prime) * b_mat
        k_grid = tuple(tuple(int(acc[i, j]) % prime for j in range(dimension)) for i in range(dimension))
        h_basis.append(k_grid)
        h_generators.append(truncated_matrix_exp(k_grid, prime, nu))

    closed_h = close_matrix_lie_span(h_basis, prime, dimension)
    is_subalgebra = len(closed_h) == len(h_basis)
    all_fix = all(recognition.matrix_fixes_polynomial(g_mat) for g_mat in h_generators)

    return CommonAlgebraStabilizerResult(
        status="STABILIZER_GENERATORS_RECOVERED",
        prime=prime,
        dimension=dimension,
        algebra_dimension=guard.algebra_dimension,
        nilpotency_index=nu,
        ambient_lie_dimension=m,
        recognized_row_rank=r,
        stabilizer_lie_dimension=len(h_basis),
        stabilizer_lie_basis=tuple(h_basis),
        stabilizer_group_generators=tuple(h_generators),
        stabilizer_lie_is_subalgebra=is_subalgebra,
        all_generators_fix_moore_form=all_fix,
    )


def verify_commuting_order_p_common_algebra_falsifier() -> dict[str, Any]:
    """Verify the p=5, D=25 commuting order-p countercontrol where J^nu = 0 has nu = 9 > p = 5."""
    p = 5
    d = 25
    g_grid = _identity(d)
    h_grid = _identity(d)
    for i in range(p):
        for j in range(p):
            if i + 1 < p:
                g_grid[i * p + j][(i + 1) * p + j] = 1
            if j + 1 < p:
                h_grid[i * p + j][i * p + j + 1] = 1

    guard = compute_common_nonunital_algebra(p, d, (g_grid, h_grid), max_nilpotency_index=2 * p)
    # Individual nilpotency indices of X = g - I and Y = h - I are 5 <= p = 5
    id_mat = _matrix(_identity(d), p)
    zero_mat = id_mat - id_mat
    x_mat = _matrix(g_grid, p) - id_mat
    y_mat = _matrix(h_grid, p) - id_mat
    x_fifth_zero = (x_mat ** p) == zero_mat
    y_fifth_zero = (y_mat ** p) == zero_mat

    # Individual truncated logs of degree p-1 = 4 fail additivity on g*h even though g and h commute!
    gh_mat = _matrix(g_grid, p) * _matrix(h_grid, p)
    gh_grid = _lists(gh_mat)
    log_g = _matrix(truncated_matrix_log(g_grid, p, p), p)
    log_h = _matrix(truncated_matrix_log(h_grid, p, p), p)
    log_gh = _matrix(truncated_matrix_log(gh_grid, p, p), p)
    logs_additive = log_gh == (log_g + log_h)

    # Also verify that recover_common_algebra_moore_stabilizer fails closed on this pair
    nodes, out = moore_circuit(p, d, (tuple(int(j == 0) for j in range(d)),))
    rec = recognize_moore_form(p, d, nodes, out, seed=29)
    stab = recover_common_algebra_moore_stabilizer(rec, (g_grid, h_grid))

    return {
        "prime": p,
        "dimension": d,
        "generators_commute": guard.generators_commute,
        "all_generators_order_dividing_p": guard.all_generators_order_dividing_p,
        "individual_x_fifth_power_zero": bool(x_fifth_zero),
        "individual_y_fifth_power_zero": bool(y_fifth_zero),
        "common_algebra_dimension": guard.algebra_dimension,
        "common_algebra_nilpotency_index": guard.nilpotency_index,
        "guard_passed": guard.guard_passed,
        "guard_status": guard.status,
        "individual_truncated_logs_additive": bool(logs_additive),
        "solver_fails_closed": stab.status == "COMMON_ALGEBRA_INDEX_EXCEEDS_PRIME" and not stab.stabilizer_group_generators,
    }


def _close_finite_matrix_group(
    generators: Sequence[Sequence[Sequence[int]]],
    prime: int,
    dimension: int,
    *,
    cap: int = 20000,
) -> set[tuple[tuple[int, ...], ...]]:
    id_tuple = tuple(tuple(int(i == j) for j in range(dimension)) for i in range(dimension))
    gen_mats = [_matrix(g, prime) for g in generators]
    seen: set[tuple[tuple[int, ...], ...]] = {id_tuple}
    queue = [_matrix(id_tuple, prime)]
    while queue:
        curr = queue.pop()
        for g_mat in gen_mats:
            prod = curr * g_mat
            prod_tuple = tuple(tuple(int(prod[i, j]) % prime for j in range(dimension)) for i in range(dimension))
            if prod_tuple not in seen:
                if len(seen) >= cap:
                    raise RuntimeError("finite group closure cap exceeded")
                seen.add(prod_tuple)
                queue.append(prod)
    return seen


def verify_elementary_stabilizer_recovery_controls() -> dict[str, Any]:
    """Verify end-to-end Moore recognition + common-algebra stabilizer recovery across UT3, conjugated UT4, UT3^2, and UT10^5."""
    # 1. UT_3(F_5): D=3, p=5, rows = e_0, e_1 -> |Gamma| = 125, |H| = 5
    p1, d1 = 5, 3
    ut3_gens = []
    for i in range(d1 - 1):
        g = _identity(d1)
        g[i][i + 1] = 1
        ut3_gens.append(tuple(map(tuple, g)))
    rows1 = (tuple(int(j == 0) for j in range(d1)), tuple(int(j == 1) for j in range(d1)))
    nodes1, out1 = moore_circuit(p1, d1, rows1, scalar=2)
