"""Elementary common-matrix-algebra (J^nu = 0, nu <= p) Moore-form stabilizer
generator-recovery backend and polynomial-graph vs positive Rees cover audit.

Implements the Section 6 elementary backend from `research/MOORE_GRADIENT_CLASSICAL_FILTER.md`
without mutating `theorems/moore_gradient_filter.py`:
1. Computes the COMMON nonunital associative matrix algebra J generated by
   X_i = g_i - I in M_D(F_p), closing under left and right multiplication
   with a hard dimension cap D^2.
2. Verifies the common nilpotency index guard J^nu = 0 with nu <= p.
   Never replaces the common-J guard by checking only g_i^p = I or the
   abstract group class (falsified by the exact commuting p=5, D=25
   countercontrol J_5 x I_5, I_5 x J_5 where nu = 2p - 1 = 9 > 5 and
   individual truncated matrix logs fail additivity).
3. Under J^nu = 0 (nu <= p), computes truncated polynomial logs log(g_i),
   closes their F_p-span under matrix commutators [A, B] = AB - BA to obtain
   a canonical basis of L = log(Gamma), forms a right annihilator basis N
   for the recognized Moore row space W (so W * N = 0), solves the linear
   system W * A * N = 0 for A in L to obtain the stabilizer Lie subalgebra
   h = {A in L : W * A <= W}, and exponentiates its basis via truncated
   polynomial exp(K) to recover exact group generators of Stab_Gamma(F).
4. Contrasts abelian hidden polynomial-graph tuple evaluation
   (Childs-Schulman-Vazirani 2007; Decker-Draisma-Wocjan 2009) against the
   nonabelian positive Rees cover A = sum_{r=1}^c t^r gamma_r(L) (where
   each evaluation E_s : A -> L is an exact Lie homomorphism while A_1 = t L
   retains the full ambient Lie algebra).
"""

