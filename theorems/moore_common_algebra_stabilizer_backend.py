def verify_polynomial_graph_vs_rees_cover_prior_art() -> dict[str, Any]:
    """Compare abelian polynomial-graph tuple evaluation against the nonabelian positive Rees cover on ut_4(F_7)."""
    p = 7
    alg, slots4 = upper_triangular_lie(4, p)
    std4 = _units(len(slots4))
    cover = make_rees_cover(alg, std4)
    dim_l = alg.dimension  # 6
    dim_a = cover.dimension  # 6 + 3 + 1 = 10

    # 1. Naive scalar dilation x -> s*x on bare nonabelian L = ut_4(F_7) fails [s*X, s*Y] = s*[X, Y]
    s_scale = 2
    naive_dilation_failures = 0
    for i in range(dim_l):
        for j in range(dim_l):
            e_i = tuple(int(k == i) for k in range(dim_l))
            e_j = tuple(int(k == j) for k in range(dim_l))
            lhs = alg.bracket(
                tuple((s_scale * x) % p for x in e_i),
                tuple((s_scale * x) % p for x in e_j),
            )
            rhs = tuple((s_scale * x) % p for x in alg.bracket(e_i, e_j))
            if lhs != rhs:
                naive_dilation_failures += 1

    # 2. Every Rees evaluation map E_s : A -> L (s in {1, 2, 3}) is an EXACT Lie algebra homomorphism:
    #    [E_s(a), E_s(b)]_L == E_s([a, b]_A) for all basis pairs a, b in A
    eval_homomorphism_failures = 0
    for s_val in (1, 2, 3):
        for i in range(dim_a):
            for j in range(dim_a):
                a_vec = tuple(int(k == i) for k in range(dim_a))
                b_vec = tuple(int(k == j) for k in range(dim_a))
                bracket_in_a = cover.algebra.bracket(a_vec, b_vec)
                lhs = cover.evaluate(bracket_in_a, s_val)
                rhs = alg.bracket(
                    cover.evaluate(a_vec, s_val),
                    cover.evaluate(b_vec, s_val),
                )
                if lhs != rhs:
                    eval_homomorphism_failures += 1

    # 3. Non-homogeneous line h_line = span(E_01 + E_03) and pure central line h_central = span(E_03)
    e01 = std4[slots4.index((0, 1))]
    e03 = std4[slots4.index((0, 3))]
    h_line = (tuple((x + z) % p for x, z in zip(e01, e03)),)
    h_central = (e03,)

    # Lifted grade intersections h cap gamma_r(L):
    line_grade_intersections = [
        _subspace_intersection(h_line, level, dim_l, p) for level in cover.levels
    ]
    central_grade_intersections = [
        _subspace_intersection(h_central, level, dim_l, p) for level in cover.levels
    ]
    rees_grade1_line = _rref_row_basis(line_grade_intersections[0], dim_l, p)

    # In L / gamma_2(L), any vector is reduced modulo gamma_2(L):
    g2_and_h_central = _rref_row_basis(list(cover.levels[1]) + list(h_central), dim_l, p)
    assoc_graded_grade1_central_dim = len(g2_and_h_central) - len(cover.levels[1])

    return {
        "prime": p,
        "ambient_lie_dimension": dim_l,
        "rees_cover_dimension": dim_a,
        "naive_dilation_on_bare_lie_algebra_failures": naive_dilation_failures,
        "naive_dilation_is_lie_automorphism": naive_dilation_failures == 0,
        "rees_evaluation_homomorphism_failures": eval_homomorphism_failures,
        "rees_evaluations_are_exact_lie_homomorphisms": eval_homomorphism_failures == 0,
        "nonhomogeneous_line_recovered_in_rees_grade1": rees_grade1_line == _rref_row_basis(h_line, dim_l, p),
        "central_line_rees_grade1_dim": len(central_grade_intersections[0]),
        "central_line_associated_graded_grade1_dim": assoc_graded_grade1_central_dim,
        "prior_art_comparison": {
            "abelian_polynomial_graph_tuple_evaluation_scope": (
                "Abelian shift groups F_q^{m+k} where tuple evaluation linearizes polynomial graphs "
                "(Childs-Schulman-Vazirani 2007; Decker-Draisma-Wocjan 2009)"
            ),
            "rees_cover_nonabelian_homogenization_scope": (
                "Nonabelian exponent-p Lazard groups exp(L) of class c < p where bare scalar dilation is not a homomorphism "
                "and associated graded loses derived directions in grade 1, whereas A = sum_{r=1}^c t^r gamma_r(L) provides "
                "exact Lie evaluation homomorphisms E_s : A -> L and retains all of L in A_1 = t L"
            ),
        },
    }


