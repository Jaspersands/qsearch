    w_conj = _lists(w_std * c_inv)
    nodes2, out2 = moore_circuit(p2, d2, w_conj, scalar=4)
    rec2 = recognize_moore_form(p2, d2, nodes2, out2, seed=29)
    stab2 = recover_common_algebra_moore_stabilizer(rec2, ut4_std_gens)
    # In standard coordinates, fixing span(e_0, e_1) inside UT_4(F_7) kills entries (0,2),(0,3),(1,2),(1,3), leaving (0,1) and (2,3) -> dim 2, order 49
    recovered_h2 = _close_finite_matrix_group(stab2.stabilizer_group_generators, p2, d2)

    # 3. Two-block UT_3(F_5)^2: D=6, p=5, orbit rank 3^2 = 9, |Gamma| = 5^6 = 15625
