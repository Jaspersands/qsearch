    gamma1 = _close_finite_matrix_group(ut3_gens, p1, d1)
    recovered_h1 = _close_finite_matrix_group(stab1.stabilizer_group_generators, p1, d1)
    exact_h1 = {g for g in gamma1 if rec1.matrix_fixes_polynomial(g)}

    # 2. Conjugated UT_4(F_7) under a dense invertible basis change C = L * U in GL(4, 7) (det C = 1)
