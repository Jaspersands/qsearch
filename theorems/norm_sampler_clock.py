"""Exact norm-proposal clock bounds and promised-distance counting.

No quantum advantage or general search lower bound. The count approximation
trusts a row-distance promise; exact dual enumeration does not. No native
AG matrix is generated by the scaling report.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

from flint import fmpz, fmpz_mod_ctx, fmpz_mod_mat

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "research/classical_baselines/norm_sampler_clock.json"


def _integer(value, minimum, name):
    if type(value) is not int or value < minimum:
        raise ValueError(f"{name} must be an integer >= {minimum}")


def _prime(p):
    if type(p) is not int or p < 3 or not fmpz(p).is_prime():
        raise ValueError("verified odd prime required")


def _instance(p, parity, syndrome):
    _prime(p)
    matrix = tuple(tuple(row) for row in parity)
    target = tuple(syndrome)
    if not matrix or not matrix[0] or any(len(row) != len(matrix[0]) for row in matrix):
        raise ValueError("nonempty rectangular parity matrix required")
    if len(target) != len(matrix):
        raise ValueError("syndrome length mismatch")
    if any(type(x) is not int or not 0 <= x < p
           for row in (*matrix, target) for x in row):
        raise ValueError("canonical field entries required")
    if fmpz_mod_mat([list(row) for row in matrix], fmpz_mod_ctx(p)).rank() != len(matrix):
        raise ValueError("full row rank required")
    return matrix, target


def projective_vectors(p, dimension):
    """One representative per nonzero line; no ambient list or zero vector."""
    _prime(p)
    _integer(dimension, 1, "dimension")
    for first in range(dimension):
        width = dimension-first-1
        # itertools.product materializes its pools, which would cost O(p)
        # space even when the caller requests only the first few vectors.
        for encoded in range(p**width):
            tail = [0]*width
            for j in range(width-1, -1, -1):
                encoded, tail[j] = divmod(encoded, p)
            yield (0,)*first + (1,) + tuple(tail)


def _dual_count(p, matrix, target):
    k, m = len(matrix), len(matrix[0])
    numerator = (p-1)**m
    distance = m
    lines = 0
    for coefficient in projective_vectors(p, k):
        word = [sum(coefficient[j]*matrix[j][i] for j in range(k)) % p
                for i in range(m)]
        weight = sum(x != 0 for x in word)
        distance = min(distance, weight)
        pairing = sum(x*y for x, y in zip(coefficient, target)) % p
        character_sum = p-1 if pairing == 0 else -1
        numerator += character_sum * (-1)**weight * (p-1)**(m-weight)
        lines += 1
    count, remainder = divmod(numerator, p**k)
    if remainder or count < 0:
        raise ArithmeticError("dual count failed integrality or nonnegativity")
    return {"status": "EXACT_COUNT", "count": count,
            "projective_words": lines, "rowspace_distance": distance,
            "conditional_on_distance_promise": False}


def exact_full_support_count(p, parity, syndrome, *, max_projective=100000):
    matrix, target = _instance(p, parity, syndrome)
    lines = (p**len(matrix)-1)//(p-1)
    if max_projective is not None:
        _integer(max_projective, 0, "enumeration cap")
        if lines > max_projective:
            return {"status": "UNKNOWN_ENUMERATION_CAP", "count": None,
                    "required_projective_words": lines, "hardness_evidence": False}
    return _dual_count(p, matrix, target)


def count_under_distance_promise(p, parity, syndrome, distance, epsilon,
                                *, max_projective=100000):
    """Deterministic FPTAS under (p-1)^distance >= p^(2k), when uncapped.

    The fast branch does NOT certify the supplied distance. A resource cap
    can return UNKNOWN; the default capped interface is not a total FPTAS.
    """
    matrix, target = _instance(p, parity, syndrome)
    k, m = len(matrix), len(matrix[0])
    _integer(distance, 1, "distance lower bound")
    if distance > m or (p-1)**distance < p**(2*k):
        raise ValueError("square-gap distance condition is not met")
    if isinstance(epsilon, bool) or not isinstance(epsilon, (int, Fraction)):
        raise ValueError("exact rational epsilon required")
    epsilon = Fraction(epsilon)
    if not 0 < epsilon < 1:
        raise ValueError("epsilon must lie strictly between zero and one")
    if max_projective is not None:
        _integer(max_projective, 0, "enumeration cap")
    threshold = Fraction(1, p**k-1)
    if epsilon >= threshold:
        return {"status": "PROMISED_DISTANCE_APPROXIMATION",
                "count": Fraction((p-1)**m, p**k),
                "relative_error_upper": threshold, "epsilon": epsilon,
                "conditional_on_distance_promise": True,
                "distance_promise_verified": False, "projective_words": 0}
    result = exact_full_support_count(p, matrix, target, max_projective=max_projective)
    if result["status"] == "EXACT_COUNT" and result["rowspace_distance"] < distance:
        raise ValueError("enumeration contradicts the distance promise")
    result.update(epsilon=epsilon, projective_work_upper=Fraction(1, (p-1)*epsilon))
    return result


def acceptance_from_count(p, k, m, support_size, native_count, normalizer):
    """Exact mass identity for the specified whole-trial proposal only."""
    _prime(p)
    for value, low, name in ((k, 1, "rank"), (m, k, "length"),
                             (support_size, 0, "support"), (native_count, 0, "count")):
        _integer(value, low, name)
    if support_size > m or native_count > (p-1)**m:
        raise ValueError("inconsistent support or count")
    if isinstance(normalizer, bool) or not isinstance(normalizer, (int, Fraction)):
        raise ValueError("exact rational normalizer required")
    normalizer = Fraction(normalizer)
    if normalizer < 1:
        raise ValueError("normalizer must be at least one")
    mass = (Fraction(native_count*(p+1)**support_size*p**k,
                     (p-1)**(m-support_size)*p**(2*support_size)) / normalizer)
    if mass > 1:
        raise ValueError("supplied count and normalizer imply impossible probability")
    return mass


def clock_bound(p, k, distance):
    """Conditional upper bound, uniform over admissible auxiliary choices."""
    _prime(p)
    _integer(k, 1, "rank")
    _integer(distance, 1, "distance")
    slack = Fraction(p**k-1, (p-1)**distance)
    upper = (1+slack)*Fraction(p*p-1, p*p)**k / (1-Fraction(1, p**k))
    return {"fourier_slack_upper": slack,
            "trial_success_upper": min(Fraction(1), upper),
            "uncapped_trial_success_upper": upper,
            "distance_promise_verified": False,
            "scope": "fresh_rank_size_biased_norm_trials_including_ideal_proposal",
            "general_classical_lower_bound": False, "quantum_advantage": False}


def stopped_success_bound(success_upper, trial_cap):
    """Valid for adaptive fresh trials; not an expectation bound for caps."""
    _integer(trial_cap, 0, "trial cap")
    if isinstance(success_upper, bool) or not isinstance(success_upper, (int, Fraction)):
        raise ValueError("exact rational probability bound required")
    success_upper = Fraction(success_upper)
    if not 0 <= success_upper <= 1:
        raise ValueError("probability bound outside [0,1]")
    return 1-(1-success_upper)**trial_cap


def ag_forecast(p, e):
    """Symbolic forecast; avoids constructing exponentially long powers."""
    _prime(p)
    _integer(e, 8, "tower degree")
    if p < 1019:
        raise ValueError("AG field promise p>=1019 required")
    k, m, d = 5*e+3, 22*e, 12*e-3
    # Under the AG promise, (p-1)^d > p^(2k). The prefactor is <2;
    # ((p^2-1)/p^2)^(p^2) < 1/2 gives this integer-only exponent.
    exponent = max(0, k//(p*p)-1)
    return {"p": p, "e": e, "rank": k, "length": m,
            "rowspace_distance_lower_promise": d,
            "trial_success_upper_power_of_two": -exponent,
            "until_success_expected_trials_lower_power_of_two": exponent,
            "root_count_relative_error_bound": "1/(p^rank-1)",
            "previous_large_field_range": p*p >= 44*e,
            "native_matrix_generated": False, "ag_promise_verified": False,
            "scope": "conditional_parameter_forecast_not_measured_runtime"}


def _json_value(value):
    if isinstance(value, Fraction):
        return {"numerator": value.numerator, "denominator": value.denominator}
    raise TypeError(type(value).__name__)


def make_report():
    controls = []
    for n in (1, 2, 4, 8):
        m = 3*n+1
        root = exact_full_support_count(3, [[1]*m], [0])
        pinned = exact_full_support_count(3, [[1]], [0])
        controls.append({"length": m, "root": root,
                         "root_main_term": Fraction(2**m, 3),
                         "root_fourier_slack": Fraction(1, 2**(3*n)),
                         "nonzero_prefix": [1]*(3*n), "completion": pinned})
    approximate = count_under_distance_promise(3, [[1]*4], [0], 4, Fraction(3, 4))
    exact = count_under_distance_promise(3, [[1]*4], [0], 4, Fraction(1, 4))
    files = [Path(__file__), ROOT / "tests/test_norm_sampler_clock.py",
             ROOT / "research/NORM_SAMPLER_CLOCK_FALSIFIER.md"]
    return {"status": "SCOPED_CLOCK_FALSIFIER_AND_CONDITIONAL_COUNTING_SCHEME",
            "all_auxiliary_choices_covered_within_proposal_family": True,
            "ideal_size_biased_coset_proposal_included": True,
            "general_classical_hardness": False, "quantum_advantage": False,
            "native_search_or_uniform_sampler_supplied_by_counting": False,
            "default_count_interface_has_resource_cap": True,
            "fixed_field_forecasts": [ag_forecast(1019, e) for e in
                                      (8, 64, 16384, 23599, 2**20, 2**24, 2**32)],
            "approximation_control": approximate, "exact_precision_control": exact,
            "prefix_count_countercontrols": controls,
            "source_hashes": {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
                              for path in files}}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = make_report()
    encoded = json.dumps(data, sort_keys=True, indent=2, default=_json_value)+"\n"
    if args.write:
        REPORT.write_text(encoded)
    elif REPORT.read_text() != encoded:
        raise SystemExit("report mismatch")
    print(json.dumps({"status": "PASS", "report": str(REPORT),
                      "forecasts": len(data["fixed_field_forecasts"]),
                      "prefix_controls": len(data["prefix_count_countercontrols"]),
                      "quantum_advantage": False}))
