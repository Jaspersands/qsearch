"""Exact mixed-state covariant decoder criterion for the wreath HSP.

The physical source-conditioned HSP input is a normalized projector orbit,
not a pure matrix-coefficient state.  Let a finite group ``G`` act as

    U = direct_sum_nu rho_nu tensor I_(M_nu)

and let ``rho_g=U_g rho U_g^*``.  Its average is

    B = direct_sum_nu I_(d_nu)/d_nu tensor C_nu,
    C_nu = Tr_(V_nu)(Pi_nu rho Pi_nu).

A covariant POVM is generated by one positive seed ``E``.  On the support of
``B`` its exact completeness constraints are

    Tr_(V_nu)(Pi_nu E Pi_nu)
      = d_nu/|G| Pi_(supp C_nu).                         (1)

Writing ``E=sum_a |eta_a><eta_a|`` turns (1) into a tight-frame condition on
row-to-multiplicity maps.  If ``r_nu=rank(C_nu)``, every vector contributes
rank at most ``d_nu`` to the partial trace, so

    rank(E) >= max_nu ceil(r_nu/d_nu).                  (2)

Thus a single pure coherent Fourier seed is generally not a decoder for the
mixed physical state.  The canonical PGM seed is

    E_PGM = |G|^-1 B^-1/2 rho B^-1/2,                  (3)

which satisfies (1) exactly and has

    P_PGM = |G|^-1 Tr(B^-1/2 rho B^-1/2 rho).          (4)

Equations (1)--(4) replace the informal "extract one dual row" target by the
correct task: coherently implement a multiplicity tight frame, including the
sector operators ``C_nu^-1/2``, while preserving cross-sector coherence.

Finite physical W_3 controls below show that cross-isotypic coherence can
raise PGM success above the exact-label dephasing ceiling, while the required
seed rank is already greater than one.  A separate all-n frame-moment theorem
proves constant global PGM success.  These controls do not prove efficient
whitening, branchwise-uniform success, PGM optimality, or a new algorithm.
"""

