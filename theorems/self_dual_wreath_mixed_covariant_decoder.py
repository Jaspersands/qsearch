def _psd_support_and_inverse_sqrt(
    matrix: np.ndarray,
    tolerance: float,
) -> tuple[np.ndarray, np.ndarray, int]:
    hermitian = (matrix + matrix.conj().T) / 2
    eigenvalues, eigenvectors = np.linalg.eigh(hermitian)
    positive = eigenvalues > tolerance
    support = eigenvectors[:, positive] @ eigenvectors[:, positive].conj().T
    inverse_values = np.zeros_like(eigenvalues)
    inverse_values[positive] = 1 / np.sqrt(eigenvalues[positive])
    inverse_sqrt = (
        eigenvectors * inverse_values
    ) @ eigenvectors.conj().T
    return support, inverse_sqrt, int(np.count_nonzero(positive))


def canonical_pgm_seed(
    state: np.ndarray,
    average_state: np.ndarray,
    group_order: int,
    *,
    tolerance: float = 1e-10,
) -> np.ndarray:
    if group_order < 1:
        raise ValueError("group order must be positive")
    _, inverse_sqrt, _ = _psd_support_and_inverse_sqrt(
        average_state,
        tolerance,
    )
    seed = inverse_sqrt @ state @ inverse_sqrt / group_order
    return (seed + seed.conj().T) / 2


def minimum_covariant_seed_rank(
    sector_multiplicity_support: tuple[tuple[int, int], ...],
) -> int:
    """Return ``max_nu ceil(rank(C_nu)/d_nu)``."""

    if not sector_multiplicity_support:
        return 0
    bounds = []
    for dimension, support_rank in sector_multiplicity_support:
        if dimension < 1 or support_rank < 0:
            raise ValueError("sector dimensions and ranks must be valid")
        bounds.append(math.ceil(support_rank / dimension))
    return max(bounds)


def _matrix_rank(matrix: np.ndarray, tolerance: float) -> int:
    return int(np.count_nonzero(np.linalg.eigvalsh((matrix + matrix.T) / 2) > tolerance))


def audit_physical_projector_orbit(
    control_id: str,
    labels: tuple[Label, ...],
    *,
    tolerance: float = 1e-9,
) -> MixedCovariantDecoderControl:
    if not labels:
        raise ValueError("at least one physical label is required")
    n = sum(labels[0][0])
    if any(
        sum(left) != n or sum(right) != n or left == right
        for left, right in labels
    ):
        raise ValueError("unequal source partitions of one common size are required")

    group_order = math.factorial(n)
    group_rows = tuple_left_subgroup_matrices(labels)
    base_projector = _base_tensor_projector(labels)
    base_rank = int(round(float(np.trace(base_projector).real)))
    state = base_projector / base_rank
    average_projector = _direct_frame(labels)
    average_state = average_projector / base_rank
    support, _, support_rank = _psd_support_and_inverse_sqrt(
        average_state,
        tolerance,
    )
    seed = canonical_pgm_seed(
        state,
        average_state,
        group_order,
        tolerance=tolerance,
    )

    orbit_average = sum(
        matrix @ state @ matrix.conj().T
        for _, matrix in group_rows
    ) / group_order
    orbit_average_residual = float(
        np.linalg.norm(orbit_average - average_state, ord=2)
    )
    completeness = sum(
        matrix @ seed @ matrix.conj().T
        for _, matrix in group_rows
    )
    completeness_residual = float(np.linalg.norm(completeness - support, ord=2))
    seed_eigenvalues = np.linalg.eigvalsh(seed)
    seed_rank = int(np.count_nonzero(seed_eigenvalues > tolerance))
    success = float(np.trace(seed @ state).real)

    projectors = [
        _isotypic_projector(n, target, group_rows)
        for target in integer_partitions(n)
    ]
    dephased_seed = sum(projector @ seed @ projector for projector in projectors)
    dephased_success = float(np.trace(dephased_seed @ state).real)

    sector_records: list[MixedDecoderSectorRecord] = []
    support_profile: list[tuple[int, int]] = []
    maximum_formula_residual = 0.0
    active_dimensions: list[int] = []
    for target, projector in zip(integer_partitions(n), projectors):
        dimension = hook_length_dimension(target)
        sector_probability = float(np.trace(projector @ state).real)
        formula_probability = float(
            portfolio_sector_weight(n, target, labels)
        )
        formula_residual = abs(sector_probability - formula_probability)
        maximum_formula_residual = max(maximum_formula_residual, formula_residual)
        sector_frame = projector @ average_state @ projector
        sector_support_rank = _matrix_rank(sector_frame, tolerance)
        if sector_support_rank % dimension:
            raise ArithmeticError("isotypic support rank is not divisible by d_nu")
        multiplicity_support_rank = sector_support_rank // dimension
        support_profile.append((dimension, multiplicity_support_rank))
        if multiplicity_support_rank:
            active_dimensions.append(dimension)
        minimum_rank = math.ceil(multiplicity_support_rank / dimension)
        sector_records.append(
            MixedDecoderSectorRecord(
                partition=target,
                irrep_dimension=dimension,
                sector_probability=sector_probability,
                character_formula_sector_probability=formula_probability,
                sector_probability_formula_residual=formula_residual,
                multiplicity_support_rank=multiplicity_support_rank,
                minimum_seed_junk_rank=minimum_rank,
                pure_rank_one_sector_seed_possible=(minimum_rank <= 1),
            )
        )

    junk_lower_bound = minimum_covariant_seed_rank(tuple(support_profile))
    global_lower_bound = math.ceil(support_rank / group_order)
    dephasing_bound = max(dimension * dimension for dimension in active_dimensions) / group_order
    covariance_verified = orbit_average_residual <= tolerance
    verified = (
        covariance_verified
        and completeness_residual <= 100 * tolerance
        and seed_eigenvalues[0] >= -100 * tolerance
        and maximum_formula_residual <= 100 * tolerance
        and seed_rank >= junk_lower_bound >= global_lower_bound
    )
    return MixedCovariantDecoderControl(
        control_id=control_id,
        n=n,
        labels=labels,
        hidden_label_count=group_order,
        physical_dimension=len(state),
        base_projector_rank=base_rank,
        average_frame_support_rank=support_rank,
        pgm_seed_rank=seed_rank,
        global_seed_junk_rank_lower_bound=junk_lower_bound,
        support_rank_global_lower_bound=global_lower_bound,
        pure_coherent_fourier_seed_possible=(junk_lower_bound <= 1),
        pgm_correct_success_probability=success,
        isotypically_dephased_pgm_seed_success_probability=dephased_success,
        cross_isotypic_coherence_success_contribution=(success - dephased_success),
        exact_label_dephasing_success_upper_bound=dephasing_bound,
        pgm_beats_exact_label_dephasing_ceiling=(success > dephasing_bound + tolerance),
        orbit_average_residual=orbit_average_residual,
        pgm_seed_support_completeness_residual=completeness_residual,
        minimum_pgm_seed_eigenvalue=float(seed_eigenvalues[0]),
        maximum_sector_probability_formula_residual=maximum_formula_residual,
        sector_records=sector_records,
        exact_finite_mixed_decoder_validation=verified,
        finite_validation_only=True,
        status=(
            "exact-mixed-covariant-pgm-control"
            if verified
            else "mixed-covariant-decoder-validation-failure"
        ),
    )


