def valid_boolean_functional_count(
    coefficients: Sequence[Fraction | int],
) -> int:
    """Count cube inputs on which a linear functional is Boolean-valued."""

    values = tuple(Fraction(value) for value in coefficients)
    if len(values) < 2:
        raise ValueError("at least two coefficients are required")
    return sum(
        sum(coefficient * bit for coefficient, bit in zip(values, bits))
        in {Fraction(0), Fraction(1)}
        for bits in itertools.product((0, 1), repeat=len(values))
    )


def two_coordinate_boolean_hit_count(
    offset: Fraction | int,
    left_coefficient: Fraction | int,
    right_coefficient: Fraction | int,
) -> int:
    """Return the number of Boolean hits in one conditioned two-bit square."""

    offset_value = Fraction(offset)
    left = Fraction(left_coefficient)
    right = Fraction(right_coefficient)
    if left == 0 or right == 0:
        raise ValueError("both conditioned coefficients must be nonzero")
    return sum(
        offset_value + left * x + right * y in {Fraction(0), Fraction(1)}
        for x, y in itertools.product((0, 1), repeat=2)
    )


def functional_control(
    coefficients: Sequence[Fraction | int],
) -> BooleanFunctionalControl:
    values = tuple(Fraction(value) for value in coefficients)
    if len(values) < 2:
        raise ValueError("at least two coefficients are required")
    if sum(values) != 1:
        raise ValueError("the all-ones condition requires coefficient sum one")
    nonzero = sum(value != 0 for value in values)
    if nonzero < 2:
        raise ValueError("the functional must not be zero or a coordinate")
    valid = valid_boolean_functional_count(values)
    total = 1 << len(values)
    verified = 4 * valid <= 3 * total
    return BooleanFunctionalControl(
        coefficient_vector=tuple(str(value) for value in values),
        rank=len(values),
        coefficient_sum=str(sum(values)),
        nonzero_coefficient_count=nonzero,
        valid_boolean_input_count=valid,
        boolean_input_count=total,
        valid_fraction=valid / total,
        three_quarter_bound_verified=verified,
        sharp_three_quarter_example=4 * valid == 3 * total,
        status=(
            "boolean-section-three-quarter-gap-verified"
            if verified
            else "boolean-section-gap-failure"
        ),
    )


def integer_functional_census(
    rank: int,
    coefficient_radius: int = 2,
) -> IntegerFunctionalCensus:
    """Finite adversarial census; the theorem itself covers arbitrary reals."""

    if rank < 2 or coefficient_radius < 1:
        raise ValueError("rank and coefficient radius must be positive")
    tested = 0
    maximum = 0
    failures = 0
    for values in itertools.product(
        range(-coefficient_radius, coefficient_radius + 1), repeat=rank
    ):
        if sum(values) != 1 or sum(value != 0 for value in values) < 2:
            continue
        tested += 1
        valid = valid_boolean_functional_count(values)
        maximum = max(maximum, valid)
        failures += int(4 * valid > 3 * (1 << rank))
    if tested == 0:
        raise ArithmeticError("census did not contain a noncoordinate functional")
    return IntegerFunctionalCensus(
        rank=rank,
        coefficient_radius=coefficient_radius,
        tested_noncoordinate_function_count=tested,
        maximum_valid_boolean_input_count=maximum,
        boolean_input_count=1 << rank,
        maximum_valid_fraction=maximum / (1 << rank),
        three_quarter_bound_failure_count=failures,
        status=(
            "finite-integer-functional-census-consistent"
            if failures == 0
            else "finite-integer-functional-census-failure"
        ),
    )


def log2_bad_contribution_upper_bound(
    n_bits: int,
    moment_order: int,
    register_offset: int = 2,
) -> float:
    """Evaluate the constant-gap Smith-transfer upper bound in log base two."""

    if n_bits < 2 or moment_order < 2 or register_offset < 0:
        raise ValueError("invalid transfer scaling parameters")
    chain = lattice_chain_length_upper_bound(moment_order)
    register_count = n_bits + register_offset
    log2_pattern_choices = moment_order + math.log2(1.0 + 2.0 ** (-moment_order))
    return (
        chain * math.log2(register_count + 1)
        + chain * log2_pattern_choices
        + 0.5 * moment_order * math.log2(moment_order)
        + register_offset * moment_order
        + n_bits * math.log2(0.75)
    )


def normalized_path_overhead(
    n_bits: int,
    moment_order: int,
    register_offset: int = 2,
) -> float:
    """Return the positive path/Smith exponent divided by ``n``."""

    bound = log2_bad_contribution_upper_bound(
        n_bits, moment_order, register_offset
    )
    return bound / n_bits - math.log2(0.75)


def logarithmic_moment_order(n_bits: int, multiplier: float) -> int:
    if n_bits < 4 or multiplier <= 0:
        raise ValueError("invalid logarithmic schedule")
    return max(2, math.floor(multiplier * math.log2(n_bits)))


