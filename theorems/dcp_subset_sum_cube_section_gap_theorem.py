"""Constant Boolean-section gap for growing DCP subset-sum moments.

The Smith-transfer moment analysis represents an ordered ``k``-tuple of
distinct Boolean assignments by the integer lattice generated by its Boolean
columns and the all-ones target column.  If the terminal lattice has rank
``r``, its self-loop base is

    b = |L intersect {0,1}^k|.

Previous growing-order bounds used only ``b/2^r <= 1-2^-k``.  The row
distinctness and all-ones conditions force a constant gap.

For a rank-deficient rational span ``V``, project injectively onto ``r``
coordinates.  Some remaining coordinate is a linear functional
``ell(x)=sum_j a_j x_j`` which is not a projected coordinate.  Since the
all-ones vector lies in ``V``, ``sum_j a_j=1``; hence at least two coefficients
are nonzero.  After fixing all other Boolean coordinates, at most three of

    y, y+a, y+b, y+a+b

can lie in ``{0,1}``.  Thus ``|V intersect {0,1}^k| <= 3*2^(r-2)``.

For a full-rank source-nongeneric lattice, an even Smith factor makes its
mod-two image proper.  A nonzero parity equation then contains exactly half of
the Boolean cube.  Consequently every source-nongeneric terminal state obeys

    b/2^r <= 3/4.                                      (1)

Combining (1) with the existing ``O(k^2 log k)`` saturation-index chain bound
gives bad-tuple contribution

    k^(k/2) 2^(kc) (m+1)^L (2^k+1)^L (3/4)^n,

where ``m=n+c`` and ``L=O(k^2 log k)``.  It vanishes whenever

    L(k)(log n+k) + k log k = o(n).

This closes every ``k=O(log n)`` nonnegative moment schedule, including the
previously open final near-logarithmic window, and more generally all
``k=o((n/log n)^(1/3))`` schedules.  It does not cover signed observables,
reduced-basis geometry, coherent implicit contractions, or decoding.
"""

