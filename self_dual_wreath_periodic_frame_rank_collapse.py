"""Uniform rank collapse for the periodic nonidentity frame family.

The periodic frame-fiber construction makes the generic support-entropy bound
nearly tight, but its same-support relators have much more structure.  For a
zero-containing support ``U`` and an anchor ``a in U``, XOR re-rooting sends
the ordered-subword relators to those indexed by ``U xor a``.  If coordinate
``i`` has a row that agrees with ``a`` strictly after ``i`` and flips bit
``i``, the re-rooted relator contains ``x_i`` exactly once and no later
generator.  Descending through the coordinates therefore eliminates every
such generator over every group.  Only suffix-forced coordinates remain.

For the exact S3 periodic family, put

    P = 001110100010111010000011101000   (six periods),
    Q = 10011                            (one period).

Both the selected and complementary ordered products of ``P`` are identity,
as are those of the all-zero six-period block.  The pair for ``Q`` is the
same-fiber target.  Exact finite-state witnesses prove:

* in the first ``P`` block every coordinate except 1, 2, and 5 branches;
* in every later ``P`` block all 30 coordinates branch, using a witness on
  the preceding and current block;
* all five coordinates of the terminal ``Q`` branch, using a witness on
  ``P Q``.

Hence the frame presentation for ``P^m Q`` is generated by at most three
elements for every ``m >= 1``.  The ``m=0`` terminal block also has a
three-generator bound, using one same-fiber witness and the adjoined empty
relator.  This is a universal finite-group statement, not an extrapolation.

The existing outer conjugacy normal form contributes at most ``|G| k(G)``
assignments.  Thus the full marked presentation has at most

    |G|^4 k(G)

solutions.  For ``G=S_n`` this is ``|S_n|^(4+o(1))``.  Along ``k=6m+1`` the
same-fiber size is exactly

    S_m=(16*2^(30m)+8*2^(24m)-4*2^(6m)-2)/9,

and ``D_m=S_m+1``.  Since ``S_m <= 2^(u-4)`` for ``u=30m+5``, the scalar
crossing-pressure margin above ``-1`` is uniformly at least

    1 - 0.5*log2(3/2) > 0.70.

The periodic counterfamily therefore falsifies a uniform *support-only* gap,
but it cannot carry leading symmetric-group mass.  Its unresolved target
character is immaterial to this candidate because the unsigned mass is
already uniformly subleading.
"""

