def frame_pair(assignment: Assignment) -> State:
    if not assignment or len(assignment) % len(FRAME_BLOCK):
        raise ValueError("assignment must contain a positive whole number of periods")
    if any(bit not in (0, 1) for bit in assignment):
        raise ValueError("assignment must be binary")
    left = IDENTITY
    right = IDENTITY
    for value, bit in zip(
        FRAME_BLOCK * (len(assignment) // len(FRAME_BLOCK)),
        assignment,
    ):
        if bit:
            left = compose(left, value)
        else:
            right = compose(right, value)
    return left, right


def _suffix_branch_witness(
    anchor: Assignment,
    target_state: State,
    coordinate: int,
) -> SuffixBranchWitness | None:
    """Find a lexicographically first exact branch witness by 36-state DP."""

    if coordinate < 0 or coordinate >= len(anchor):
        raise ValueError("coordinate is outside the anchor")
    values = FRAME_BLOCK * (len(anchor) // len(FRAME_BLOCK))
    prefix_states: dict[State, Assignment] = {NEUTRAL_STATE: ()}
    for index in range(coordinate + 1):
        options = (1 - anchor[index],) if index == coordinate else (0, 1)
        output: dict[State, Assignment] = {}
        for (left, right), prefix in prefix_states.items():
            for bit in options:
                value = values[index]
                state = (
                    (compose(left, value), right)
                    if bit
                    else (left, compose(right, value))
                )
                output.setdefault(state, (*prefix, bit))
        prefix_states = output

    suffix = anchor[coordinate + 1 :]
    for state, prefix in prefix_states.items():
        left, right = state
        for value, bit in zip(values[coordinate + 1 :], suffix):
            if bit:
                left = compose(left, value)
            else:
                right = compose(right, value)
        if (left, right) != target_state:
            continue
        witness = (*prefix, *suffix)
        bit_flipped = witness[coordinate] == 1 - anchor[coordinate]
        suffix_agreement = witness[coordinate + 1 :] == suffix
        state_verified = frame_pair(witness) == target_state
        exact = bit_flipped and suffix_agreement and state_verified
        return SuffixBranchWitness(
            coordinate_one_based=coordinate + 1,
            anchor=anchor,
            witness=witness,
            target_state=target_state,
            bit_flipped=bit_flipped,
            strict_suffix_agreement=suffix_agreement,
            witness_state_verified=state_verified,
            status=(
                "exact-suffix-branch-witness" if exact else "suffix-witness-failure"
            ),
        )
    return None


def _witnesses(
    anchor: Assignment,
    target_state: State,
    coordinates: Iterable[int],
) -> tuple[SuffixBranchWitness, ...]:
    output = []
    for coordinate in coordinates:
        witness = _suffix_branch_witness(anchor, target_state, coordinate)
        if witness is not None:
            output.append(witness)
    return tuple(output)


def audit_periodic_suffix_branch_certificate() -> PeriodicSuffixBranchCertificate:
    first = _witnesses(
        NEUTRAL_BLOCK,
        NEUTRAL_STATE,
        range(len(NEUTRAL_BLOCK)),
    )
    repeated_anchor = (*NEUTRAL_BLOCK, *NEUTRAL_BLOCK)
    repeated = _witnesses(
        repeated_anchor,
        NEUTRAL_STATE,
        range(len(NEUTRAL_BLOCK), len(repeated_anchor)),
    )
    terminal_anchor = (*NEUTRAL_BLOCK, *TERMINAL_BLOCK)
    terminal = _witnesses(
        terminal_anchor,
        SAME_SUBSEQUENCE_STATE,
        range(len(NEUTRAL_BLOCK), len(terminal_anchor)),
    )
    single_terminal = _witnesses(
        TERMINAL_BLOCK,
        SAME_SUBSEQUENCE_STATE,
        range(len(TERMINAL_BLOCK)),
    )
    first_coordinates = tuple(row.coordinate_one_based for row in first)
    first_unresolved = tuple(
        coordinate
        for coordinate in range(1, len(NEUTRAL_BLOCK) + 1)
        if coordinate not in first_coordinates
    )
    repeated_coordinates = tuple(
        row.coordinate_one_based - len(NEUTRAL_BLOCK) for row in repeated
    )
    terminal_coordinates = tuple(
        row.coordinate_one_based - len(NEUTRAL_BLOCK) for row in terminal
    )
    single_coordinates = tuple(
        row.coordinate_one_based for row in single_terminal
    )
    zero_neutral = frame_pair((0,) * len(NEUTRAL_BLOCK))
    exact_witnesses = all(
        row.bit_flipped
        and row.strict_suffix_agreement
        and row.witness_state_verified
        for row in (*first, *repeated, *terminal, *single_terminal)
    )
    exact = (
        frame_pair(NEUTRAL_BLOCK) == NEUTRAL_STATE
        and zero_neutral == NEUTRAL_STATE
        and frame_pair(TERMINAL_BLOCK) == SAME_SUBSEQUENCE_STATE
        and first_unresolved == (1, 2, 5)
        and repeated_coordinates == tuple(range(1, 31))
        and terminal_coordinates == tuple(range(1, 6))
        and single_coordinates == (4,)
        and TERMINAL_BLOCK[-1] == 1
        and exact_witnesses
    )
    return PeriodicSuffixBranchCertificate(
        neutral_block=NEUTRAL_BLOCK,
        terminal_block=TERMINAL_BLOCK,
        neutral_block_state=frame_pair(NEUTRAL_BLOCK),
        zero_neutral_block_state=zero_neutral,
        terminal_block_state=frame_pair(TERMINAL_BLOCK),
        first_neutral_block_branch_coordinates=first_coordinates,
        first_neutral_block_unresolved_coordinates=first_unresolved,
        repeated_neutral_block_branch_coordinates=repeated_coordinates,
        terminal_block_branch_coordinates=terminal_coordinates,
        single_terminal_same_fiber_branch_coordinates=single_coordinates,
        single_terminal_exception_branch_coordinates=(5,),
        first_neutral_block_witnesses=first,
        repeated_neutral_block_witnesses=repeated,
        terminal_block_witnesses=terminal,
        single_terminal_witnesses=single_terminal,
        universal_finite_group_frame_generator_upper_bound=3,
        exact_suffix_branch_elimination_lemma_applied=exact,
        neutral_concatenation_induction_verified=exact,
        status=(
            "exact-all-period-suffix-branch-rank-collapse"
            if exact
            else "periodic-suffix-branch-certificate-failure"
        ),
    )


def periodic_same_fiber_closed_form(m_value: int) -> int:
    if m_value < 0:
        raise ValueError("m must be nonnegative")
    numerator = (
        16 * 2 ** (30 * m_value)
        + 8 * 2 ** (24 * m_value)
        - 4 * 2 ** (6 * m_value)
        - 2
    )
    if numerator % 9:
        raise AssertionError("closed-form fiber numerator is not divisible by nine")
    return numerator // 9


def audit_periodic_fiber_closed_form(
    maximum_checked_m: int = 6,
) -> PeriodicFiberClosedFormCertificate:
    checked = tuple(range(maximum_checked_m + 1))
    transfer_sizes = tuple(
        _period_fiber_counts(6 * m_value + 1)[SAME_SUBSEQUENCE_STATE]
        for m_value in checked
    )
    closed_sizes = tuple(periodic_same_fiber_closed_form(m_value) for m_value in checked)
    transfer = audit_transfer_certificate()
    recurrence_roots = (2**30, 2**24, 2**6, 1)
    initial_determines = transfer.exact_annihilating_polynomial_verified and all(
        transfer_sizes[index] == closed_sizes[index] for index in range(4)
    )
    density = all(
        size <= 2 ** (30 * m_value + 1)
        for m_value, size in zip(checked, transfer_sizes)
    )
    exact = initial_determines and transfer_sizes == closed_sizes and density
    return PeriodicFiberClosedFormCertificate(
        subsequence="k=6m+1, u=30m+5",
        checked_m_values=checked,
        transfer_fiber_sizes=transfer_sizes,
        closed_form_fiber_sizes=closed_sizes,
        recurrence_roots=recurrence_roots,
        closed_form_coefficients=("16/9", "8/9", "-4/9", "-2/9"),
        exact_transfer_annihilator_imported=(
            transfer.exact_annihilating_polynomial_verified
        ),
        initial_values_determine_closed_form=initial_determines,
        closed_form_verified=exact,
        uniform_density_bound="S_m <= 2^(u-4)",
        uniform_density_bound_verified=density,
        status=(
            "exact-periodic-fiber-closed-form-and-density-bound"
            if exact
            else "periodic-fiber-closed-form-failure"
        ),
    )


def periodic_rank_collapse_scaling_records(
    maximum_m: int = 6,
) -> list[PeriodicRankCollapseScalingRecord]:
    uniform_margin = 1.0 - 0.5 * math.log2(3.0 / 2.0)
    output = []
    for m_value in range(maximum_m + 1):
        width = 30 * m_value + 5
        same_size = periodic_same_fiber_closed_form(m_value)
        different_size = same_size + 1
        entropy = 0.5 * math.log2(same_size * different_size)
        pressure = 4.0 + entropy - width - 2.0
        margin = -1.0 - pressure
        output.append(
            PeriodicRankCollapseScalingRecord(
                m_value=m_value,
                period_count=6 * m_value + 1,
                frame_position_count=width,
                same_support_size=same_size,
                different_support_size=different_size,
                support_entropy_exponent=entropy,
                frame_generator_upper_bound=3,
                full_solution_exponent_before_conjugacy_classes=4,
                scalar_crossing_pressure_upper_bound=pressure,
                scalar_crossing_pressure_margin=margin,
                uniform_margin_lower_bound=uniform_margin,
                status=(
                    "periodic-family-uniformly-subleading"
                    if margin >= uniform_margin - 1e-12
                    else "periodic-rank-margin-certificate-failure"
                ),
            )
        )
    return output


