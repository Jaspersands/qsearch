def _validate_pattern(pattern: str) -> str:
    if not pattern or any(token not in "ABEF" for token in pattern):
        raise ValueError("pattern must be a nonempty A/B/E/F word")
    return pattern


def _identity(size: int) -> Permutation:
    return tuple(range(size))


def _products_by_color(
    sequence: tuple[Permutation, ...],
    bits: Iterable[int],
) -> tuple[Permutation, Permutation]:
    identity = _identity(len(sequence[0]))
    products = [identity, identity]
    for permutation, bit in zip(sequence, bits):
        products[bit] = _compose(products[bit], permutation)
    return products[0], products[1]


def partially_pinned_two_color_count(
    sequence: tuple[Permutation, ...],
    pattern: str,
    *,
    differing_coordinate: bool,
) -> int:
    """Return ``Q_0`` or ``Q_1`` from equation (2).

    Frame tokens ``A,B`` have a free orientation bit at every nonsplit source
    pair.  ``E`` is pinned to zero, while ``F`` is pinned to zero on an equal
    coordinate and one on a differing coordinate.
    """

    _validate_pattern(pattern)
    if len(sequence) != len(pattern) or not sequence:
        raise ValueError("the group sequence must match the marked pattern")
    degree = len(sequence[0])
    if any(len(permutation) != degree for permutation in sequence):
        raise ValueError("group elements must have one common permutation degree")
    identity = _identity(degree)
    free_positions = tuple(
        index for index, token in enumerate(pattern) if token in "AB"
    )
    count = 0
    for assignment in itertools.product((0, 1), repeat=len(free_positions)):
        assignment_by_position = dict(zip(free_positions, assignment))
        bits = tuple(
            assignment_by_position[index]
            if token in "AB"
            else (1 if token == "F" and differing_coordinate else 0)
            for index, token in enumerate(pattern)
        )
        products = _products_by_color(sequence, bits)
        count += products == (identity, identity)
    return count


def _split_positions(pattern: str) -> dict[int, tuple[int, ...]]:
    # At the distinguished final split, A/E/F lie in the left child and B in
    # the right child.  This bit is fixed rather than summed.
    return {
        0: tuple(index for index, token in enumerate(pattern) if token != "B"),
        1: tuple(index for index, token in enumerate(pattern) if token == "B"),
    }


@lru_cache(maxsize=None)
def leaf_marked_word_map_strata(
    n: int,
    pattern: str,
) -> tuple[MarkedStratum, ...]:
    """Enumerate the exact partially pinned strata in equation (2)."""

    if n < 2:
        raise ValueError("n must be at least two")
    _validate_pattern(pattern)
    group = tuple(itertools.permutations(range(n)))
    identity = _identity(n)
    positions = _split_positions(pattern)
    forced = {
        bit: selected[-1]
        for bit, selected in positions.items()
        if selected
    }
    free_positions = tuple(
        index for index in range(len(pattern)) if index not in forced.values()
    )
    counts: dict[tuple[int, int, Partition], int] = {}
    for assignment in itertools.product(group, repeat=len(free_positions)):
        sequence = [identity] * len(pattern)
        for position, permutation in zip(free_positions, assignment):
            sequence[position] = permutation
        for bit, selected in positions.items():
            if not selected:
                continue
            sequence[forced[bit]] = _inverse(
                _ordered_product(tuple(sequence), selected[:-1])
            )
        sequence_tuple = tuple(sequence)
        same = partially_pinned_two_color_count(
            sequence_tuple,
            pattern,
            differing_coordinate=False,
        )
        different = partially_pinned_two_color_count(
            sequence_tuple,
            pattern,
            differing_coordinate=True,
        )
        full_product = _ordered_product(
            sequence_tuple,
            range(len(sequence_tuple)),
        )
        key = (same, different, permutation_cycle_type(full_product))
        counts[key] = counts.get(key, 0) + 1
    expected = math.factorial(n) ** len(free_positions)
    if sum(counts.values()) != expected:
        raise ArithmeticError("marked word-map strata lost group assignments")
    return tuple(
        (same, different, cycle_type, count)
        for (same, different, cycle_type), count in sorted(counts.items())
    )


def independent_leaf_marked_word_moment(
    n: int,
    copy_count: int,
    hamming_distance: int,
    target: Partition,
    pattern: str,
) -> Fraction:
    """Evaluate equation (2) exactly for ``S_n``."""

    _validate_pattern(pattern)
    if sum(target) != n or copy_count < 1:
        raise ValueError("invalid target or copy count")
    remaining = copy_count - 1
    if not 0 <= hamming_distance <= remaining:
        raise ValueError("Hamming distance exceeds the child cube dimension")
    order = math.factorial(n)
    dimension = hook_length_dimension(target)
    numerator = Fraction()
    for same, different, cycle_type, count in leaf_marked_word_map_strata(
        n,
        pattern,
    ):
        numerator += (
            count
            * same ** (remaining - hamming_distance)
            * different**hamming_distance
            * Fraction(symmetric_character(target, cycle_type), dimension)
        )
    return numerator / order ** len(pattern)


def _direct_token_operators(
    target: Partition,
    labels: tuple[Label, ...],
    hamming_distance: int,
) -> dict[str, np.ndarray]:
    copy_count = len(labels)
    if not 0 <= hamming_distance <= copy_count - 1:
        raise ValueError("invalid child Hamming distance")
    projectors = tuple(
        orientation_invariant_projector(target, labels, mask)
        for mask in range(1 << copy_count)
    )
    zero = np.zeros_like(projectors[0])
    left = sum(
        (projector for mask, projector in enumerate(projectors) if not mask & 1),
        zero.copy(),
    )
    right = sum(
        (projector for mask, projector in enumerate(projectors) if mask & 1),
        zero.copy(),
    )
    comparison_mask = sum(1 << bit for bit in range(1, hamming_distance + 1))
    return {
        "A": left,
        "B": right,
        "E": projectors[0],
        "F": projectors[comparison_mask],
    }


def audit_direct_leaf_marked_moment(
    control_id: str,
    n: int,
    copy_count: int,
    hamming_distance: int,
    target: Partition,
    pattern: str,
) -> LeafMarkedMomentControl:
    """Average explicit physical projectors and compare with equation (2)."""

    _validate_pattern(pattern)
    if sum(target) != n:
        raise ValueError("target must partition n")
    partitions = tuple(integer_partitions(n))
    order = math.factorial(n)
    dimensions = {
        partition: hook_length_dimension(partition) for partition in partitions
    }
    weights = {
        partition: dimensions[partition] ** 2 / order
        for partition in partitions
    }
    direct = 0.0
    tuple_count = 0
    for sources in itertools.product(partitions, repeat=2 * copy_count):
        labels: tuple[Label, ...] = tuple(
            (sources[2 * index], sources[2 * index + 1])
            for index in range(copy_count)
        )
        probability = math.prod(weights[source] for source in sources)
        operators = _direct_token_operators(
            target,
            labels,
            hamming_distance,
        )
        product = np.eye(operators["A"].shape[0], dtype=complex)
        for token in pattern:
            product = product @ operators[token]
        carrier_dimension = dimensions[target] * math.prod(
            dimensions[source] for source in sources
        )
        direct += probability * float(np.trace(product).real) / carrier_dimension
        tuple_count += 1
    predicted_exact = independent_leaf_marked_word_moment(
        n,
        copy_count,
        hamming_distance,
        target,
        pattern,
    )
    predicted = float(predicted_exact)
    residual = abs(direct - predicted)
    exact = residual <= 1e-10
    positions = _split_positions(pattern)
    free_count = len(pattern) - sum(bool(selected) for selected in positions.values())
    return LeafMarkedMomentControl(
        control_id=control_id,
        n=n,
        copy_count=copy_count,
        hamming_distance=hamming_distance,
        target_partition=target,
        pattern=pattern,
        source_tuple_count=tuple_count,
        constrained_group_assignment_count=order**free_count,
        stratum_count=len(leaf_marked_word_map_strata(n, pattern)),
        direct_projector_moment=direct,
        marked_word_normal_form_moment=predicted,
        formula_residual=residual,
        target_character_forced_trivial="B" not in pattern,
        exact_direct_validation=exact,
        status=(
            "exact-leaf-marked-word-normal-form-verified"
            if exact
            else "leaf-marked-word-normal-form-control-failure"
        ),
    )


def uncompressed_pair_formula_control(
    n: int,
    copy_count: int,
    hamming_distance: int,
) -> UncompressedPairFormulaControl:
    if not 1 <= hamming_distance <= copy_count - 1:
        raise ValueError("two distinct child leaves are required")
    partitions = tuple(integer_partitions(n))
    values = []
    for target in partitions:
        noncrossing = independent_leaf_marked_word_moment(
            n,
            copy_count,
            hamming_distance,
            target,
            "EEFF",
        )
        crossing = independent_leaf_marked_word_moment(
            n,
            copy_count,
            hamming_distance,
            target,
            "EFEF",
        )
        values.append((target, noncrossing, crossing, 2 * (noncrossing - crossing)))
    order = math.factorial(n)
    closed = Fraction(2 * (order - len(partitions)), order**3)
    residual = max(abs(pair - closed) for _, _, _, pair in values)
    first = values[0]
    exact = residual == 0 and all(
        noncrossing == first[1] and crossing == first[2]
        for _, noncrossing, crossing, _ in values
    )
    return UncompressedPairFormulaControl(
        n=n,
        copy_count=copy_count,
        hamming_distance=hamming_distance,
        target_count=len(partitions),
        noncrossing_moment=str(first[1]),
        crossing_moment=str(first[2]),
        pair_commutator_trace=str(first[3]),
        closed_pair_commutator_trace=str(closed),
        maximum_target_residual=str(residual),
        exact_target_independent_pair_formula_verified=exact,
        status=(
            "exact-target-independent-uncompressed-pair-formula-recovered"
            if exact
            else "uncompressed-pair-formula-recovery-failure"
        ),
    )


def _psd_power(
    matrix: np.ndarray,
    exponent: float,
    *,
    tolerance: float,
) -> np.ndarray:
    hermitian = (matrix + matrix.conj().T) / 2.0
    values, vectors = np.linalg.eigh(hermitian)
    if len(values) and values[0] < -100 * tolerance:
        raise ValueError("matrix must be positive semidefinite")
    powered = np.zeros_like(values)
    positive = values > 100 * tolerance
    powered[positive] = values[positive] ** exponent
    return (vectors * powered) @ vectors.conj().T


def _support_basis(matrix: np.ndarray, tolerance: float) -> np.ndarray:
    values, vectors = np.linalg.eigh((matrix + matrix.conj().T) / 2.0)
    return vectors[:, values > 100 * tolerance]


def _common_basis(
    left_basis: np.ndarray,
    right_basis: np.ndarray,
    tolerance: float,
) -> np.ndarray:
    if not left_basis.shape[1] or not right_basis.shape[1]:
        return np.zeros((left_basis.shape[0], 0), dtype=complex)
    vectors, singular_values, _ = np.linalg.svd(
        left_basis.conj().T @ right_basis,
        full_matrices=False,
    )
    return left_basis @ vectors[:, singular_values >= 1 - 100 * tolerance]


def basis_free_common_green_kernel(
    left_frame: np.ndarray,
    right_frame: np.ndarray,
    *,
    tolerance: float = 1e-9,
) -> tuple[np.ndarray, np.ndarray]:
    """Return the common projection and equation (1)'s basis-free kernel."""

    if left_frame.shape != right_frame.shape or left_frame.ndim != 2:
        raise ValueError("sibling frames must share one square ambient space")
    left_basis = _support_basis(left_frame, tolerance)
    right_basis = _support_basis(right_frame, tolerance)
    common = _common_basis(left_basis, right_basis, tolerance)
    projection = common @ common.conj().T
    left_inverse = _psd_power(left_frame, -1.0, tolerance=tolerance)
    compressed = projection @ left_inverse @ projection
    compressed_inverse = _psd_power(compressed, -1.0, tolerance=tolerance)
    green = (
        left_inverse
        @ projection
        @ compressed_inverse
        @ projection
        @ left_inverse
    )
    return projection, green


def audit_sibling_green_algebra(
    control_id: str,
    left_frame: np.ndarray,
    right_frame: np.ndarray,
    *,
    alternating_iterations: int = 32,
    tolerance: float = 1e-9,
) -> SiblingGreenAlgebraControl:
    if alternating_iterations < 1:
        raise ValueError("at least one alternating-projection step is required")
    left_basis = _support_basis(left_frame, tolerance)
    right_basis = _support_basis(right_frame, tolerance)
    common = _common_basis(left_basis, right_basis, tolerance)
    left_support = left_basis @ left_basis.conj().T
    right_support = right_basis @ right_basis.conj().T
    common_projection = common @ common.conj().T
    alternating_operator = left_support @ right_support @ left_support
    alternating = np.linalg.matrix_power(
        alternating_operator,
        alternating_iterations,
    )
    alternating_values = np.linalg.eigvalsh(
        (alternating_operator + alternating_operator.conj().T) / 2.0
    )
    noncommon = alternating_values[alternating_values < 1 - 100 * tolerance]
    largest_noncommon = float(max(0.0, noncommon[-1] if len(noncommon) else 0.0))
    predicted = largest_noncommon**alternating_iterations
    observed = float(np.linalg.norm(alternating - common_projection, ord=2))

    left_inverse = _psd_power(left_frame, -1.0, tolerance=tolerance)
    metric = common.conj().T @ left_inverse @ common
    metric_inverse = _psd_power(metric, -1.0, tolerance=tolerance)
    direct_green = (
        left_inverse
        @ common
        @ metric_inverse
        @ common.conj().T
        @ left_inverse
    )
    formula_projection, formula_green = basis_free_common_green_kernel(
        left_frame,
        right_frame,
        tolerance=tolerance,
    )
    basis_residual = float(np.linalg.norm(direct_green - formula_green, ord=2))
    projection_residual = float(
        np.linalg.norm(common_projection - formula_projection, ord=2)
    )
    reflexive = float(
        np.linalg.norm(formula_green @ left_frame @ formula_green - formula_green, ord=2)
    )
    projection_exact = max(
        projection_residual,
        abs(observed - predicted),
    ) <= 1000 * tolerance
    green_exact = max(basis_residual, reflexive) <= 1000 * tolerance
    return SiblingGreenAlgebraControl(
        control_id=control_id,
        ambient_dimension=left_frame.shape[0],
        left_support_rank=left_basis.shape[1],
        right_support_rank=right_basis.shape[1],
        common_span_rank=common.shape[1],
        alternating_projection_iteration_count=alternating_iterations,
        largest_noncommon_alternating_eigenvalue=largest_noncommon,
        predicted_alternating_projection_residual=predicted,
        observed_alternating_projection_residual=observed,
        basis_free_green_formula_residual=basis_residual,
        green_reflexive_inverse_residual=reflexive,
        exact_common_projection_limit_verified=projection_exact,
        exact_basis_free_green_formula_verified=green_exact,
        sibling_frame_algebra_contains_green_kernel=projection_exact and green_exact,
        status=(
            "exact-sibling-frame-algebra-green-kernel-verified"
            if projection_exact and green_exact
            else "sibling-frame-algebra-green-control-failure"
        ),
    )


def _physical_green_algebra_control() -> SiblingGreenAlgebraControl:
    standard = (2, 1)
    labels: tuple[Label, ...] = ((standard, standard),) * 3
    projectors = tuple(
        orientation_invariant_projector(standard, labels, mask)
        for mask in range(8)
    )
    zero = np.zeros_like(projectors[0])
    left = sum(projectors[:4], zero.copy())
    right = sum(projectors[4:], zero.copy())
    return audit_sibling_green_algebra(
        "S3-REPEATED-STANDARD-FINAL-SIBLINGS",
        left,
        right,
    )


def leaf_marked_green_scaling_record(n: int) -> LeafMarkedGreenScalingRecord:
    if n < 5:
        raise ValueError("n must be at least five")
    order = math.factorial(n)
    copies = (order - 1).bit_length() + 2
    remaining = copies - 1
    q = 1 << remaining
    pair_trace = Fraction(
        2 * (order - len(integer_partitions(n))),
        order**3,
    )
    return LeafMarkedGreenScalingRecord(
        n=n,
        group_order_log2=math.log2(order),
        selected_copy_count=copies,
        remaining_cube_dimension=remaining,
        child_leaf_count_log2=remaining,
        typical_hamming_distance=remaining // 2,
        exact_hamming_dependence_dimension=2,
        uncompressed_rescaled_pair_trace=float(q**2 * pair_trace),
        target_character_absent_for_all_left_words=True,
        exact_green_is_sibling_frame_algebra_function=True,
        growing_marked_word_rigidity_proved=False,
        natural_green_pair_gap_proved=False,
        status="exact-marked-word-reduction-growing-rigidity-open",
    )


