"""Leaf-marked sibling-word normal form for the natural Green pair gap.

The natural leaf trace profile has the right ``q^-2`` pair scale, but the
canonical component effects contain the exact sibling-common Green kernel.
This module removes the common span as an independent probabilistic object.

Let ``A`` and ``B`` be the two final-root child frames and let ``P_A,P_B`` be
their support projections.  Their common-range projection and the left-child
Green kernel are, basis independently,

    P = P_A meet P_B = s-lim_t (P_A P_B P_A)^t,

    K = A^+ P (P A^+ P)^+ P A^+.                         (1)

Thus ``P`` and ``K`` belong to the finite-dimensional von Neumann algebra
generated by ``A,B``.  Every polynomial/ridge approximation to a component
pair term is consequently a linear combination of traces of words in
``A,B`` and two marked left-child leaves ``E,F``.

There is an exact independent-Plancherel formula for every such word.  Use
tokens ``A,B,E,F`` where ``A,B`` denote child-frame sums, ``E`` is a base
left leaf, and ``F`` is a second left leaf.  Relabel coordinates so that
``E`` has all-zero orientation and ``F`` differs in ``w`` of the remaining
``m=K-1`` coordinates.  For a group tuple ``x=(x_1,...,x_p)``:

* ``I_split(x)`` requires the ordered product on ``A/E/F`` positions and the
  ordered product on ``B`` positions to be the identity;
* ``Q_0(x)`` is the number of two-color assignments on frame-token positions
  for which both color products are the identity when both marked leaves are
  pinned to color zero;
* ``Q_1(x)`` is the analogous count with ``E`` pinned to zero and ``F``
  pinned to one.

For target irrep ``nu`` of a group of order ``g``, independent source pairs
give exactly

    E Tr(word)/D = g^-p sum_x I_split(x)
        chi_nu(x_1...x_p)/d_nu Q_0(x)^(m-w) Q_1(x)^w.     (2)

If the word contains no ``B``, ``I_split`` forces ``x_1...x_p=1`` and the
target character disappears exactly.  In particular, (2) recovers the
natural uncompressed pair formula from ``EEFF-EFEF``.  More importantly,
equations (1)-(2) reduce the unresolved normalized Green pair gap to one
explicit problem: control partially pinned high-count word-map strata for
the growing-degree ``A/B`` approximants to (1).

This is a reduction, not a positive Green-moment theorem.  It proves neither
the required growing-word rigidity nor a nonzero component M4.  It also does
not turn a finite polynomial screen into evidence for an asymptotic edge,
decoder, compiler, or speedup.
"""

