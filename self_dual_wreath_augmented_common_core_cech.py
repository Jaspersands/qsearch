def _matrix_rank(matrix: np.ndarray, tolerance: float) -> int:
    if not matrix.size:
        return 0
    return int(np.sum(np.linalg.svd(matrix, compute_uv=False) > 100 * tolerance))


def _direct_common_range_basis(
    leaf_bases: dict[int, np.ndarray],
    family: tuple[int, ...],
    tolerance: float,
) -> np.ndarray:
    """Intersect leaf ranges in the smallest leaf's coefficient space."""

    seed_mask = min(family, key=lambda mask: leaf_bases[mask].shape[1])
    seed = leaf_bases[seed_mask]
    if not seed.shape[1]:
        return np.zeros((seed.shape[0], 0), dtype=complex)
    constraints = []
    for mask in family:
        if mask == seed_mask:
            continue
        other = leaf_bases[mask]
        constraints.append(seed - other @ (other.conj().T @ seed))
    if not constraints:
        return seed
    constraint = np.concatenate(constraints, axis=0)
    _, singular_values, right = np.linalg.svd(
        constraint,
        full_matrices=True,
    )
    rank = int(np.sum(singular_values > 100 * tolerance))
    coefficients = right[rank:, :].conj().T
    basis = seed @ coefficients
    if basis.shape[1]:
        residual = max(
            float(
                np.linalg.norm(
                    basis - leaf_bases[mask] @ (leaf_bases[mask].conj().T @ basis),
                    ord=2,
                )
            )
            for mask in family
        )
        if residual > 1000 * tolerance:
            raise ArithmeticError("direct common-range intersection is unstable")
    return basis


def augmented_common_core_cech_data(
    target: tuple[int, ...],
    labels: tuple[Label, ...],
    orientation_masks: tuple[int, ...],
    *,
    tolerance: float = 1e-8,
) -> tuple[
    dict[tuple[int, ...], np.ndarray],
    dict[int, tuple[tuple[int, ...], ...]],
    dict[int, np.ndarray],
    np.ndarray,
    float,
]:
    """Build all nonzero cells, boundaries, and the physical augmentation."""

    if len(set(orientation_masks)) != len(orientation_masks):
        raise ValueError("orientation masks must be distinct")
    leaf_bases = {
        mask: orientation_invariant_range_basis(
            target,
            labels,
            mask,
            tolerance=tolerance,
        )[0]
        for mask in orientation_masks
    }
    bases: dict[tuple[int, ...], np.ndarray] = {
        (mask,): basis for mask, basis in leaf_bases.items() if basis.shape[1]
    }
    cells: dict[int, tuple[tuple[int, ...], ...]] = {
        1: tuple((mask,) for mask in orientation_masks if (mask,) in bases)
    }
    n = sum(target)
    for family_size in range(2, len(orientation_masks) + 1):
        family_cells = []
        for family in itertools.combinations(orientation_masks, family_size):
            if n >= 5:
                if not fixed_family_common_range_dimension(target, labels, family):
                    continue
                basis = fixed_family_common_range_basis(
                    target,
                    labels,
                    family,
                    tolerance=tolerance,
                )
            else:
                basis = _direct_common_range_basis(leaf_bases, family, tolerance)
                if not basis.shape[1]:
                    continue
            bases[family] = basis
            family_cells.append(family)
        cells[family_size] = tuple(family_cells)

    offsets: dict[int, dict[tuple[int, ...], tuple[int, int]]] = {}
    dimensions: dict[int, int] = {}
    for family_size, family_cells in cells.items():
        cursor = 0
        offsets[family_size] = {}
        for family in family_cells:
            width = bases[family].shape[1]
            offsets[family_size][family] = (cursor, cursor + width)
            cursor += width
        dimensions[family_size] = cursor

    boundaries: dict[int, np.ndarray] = {}
    inclusion_residual = 0.0
    for family_size in range(2, len(orientation_masks) + 1):
        boundary = np.zeros(
            (dimensions[family_size - 1], dimensions[family_size]),
            dtype=complex,
        )
        for family in cells[family_size]:
            column_start, column_end = offsets[family_size][family]
            for removed_index in range(family_size):
                face = family[:removed_index] + family[removed_index + 1 :]
                if face not in offsets[family_size - 1]:
                    continue
                row_start, row_end = offsets[family_size - 1][face]
                inclusion = bases[face].conj().T @ bases[family]
                inclusion_residual = max(
                    inclusion_residual,
                    float(
                        np.linalg.norm(
                            bases[face] @ inclusion - bases[family],
                            ord=2,
                        )
                    ),
                )
                boundary[row_start:row_end, column_start:column_end] = (
                    (-1) ** removed_index * inclusion
                )
        boundaries[family_size] = boundary

    synthesis = np.concatenate(
        [bases[cell] for cell in cells[1]],
        axis=1,
    ) if cells[1] else np.zeros((next(iter(leaf_bases.values())).shape[0], 0))
    return bases, cells, boundaries, synthesis, inclusion_residual


def audit_augmented_common_core_cech_control(
    control_id: str,
    target: tuple[int, ...],
    labels: tuple[Label, ...],
    orientation_masks: tuple[int, ...],
    *,
    tolerance: float = 1e-8,
) -> AugmentedCommonCoreCechControl:
    bases, cells, boundaries, synthesis, inclusion_residual = (
        augmented_common_core_cech_data(
            target,
            labels,
            orientation_masks,
            tolerance=tolerance,
        )
    )
    compositions = []
    if 2 in boundaries and boundaries[2].size:
        compositions.append(float(np.linalg.norm(synthesis @ boundaries[2], ord=2)))
    for family_size in range(3, len(orientation_masks) + 1):
        if boundaries[family_size].size:
            compositions.append(
                float(
                    np.linalg.norm(
                        boundaries[family_size - 1] @ boundaries[family_size],
                        ord=2,
                    )
                )
            )

    chain_records = []
    minimum_positive_values = []
    conditions = []
    for family_size in range(1, len(orientation_masks) + 1):
        chain_dimension = sum(
            bases[cell].shape[1] for cell in cells[family_size]
        )
        outgoing = synthesis if family_size == 1 else boundaries[family_size]
        outgoing_rank = _matrix_rank(outgoing, tolerance)
        kernel_dimension = chain_dimension - outgoing_rank
        incoming = boundaries.get(
            family_size + 1,
            np.zeros((chain_dimension, 0), dtype=complex),
        )
        incoming_rank = _matrix_rank(incoming, tolerance)
        homology = kernel_dimension - incoming_rank
        hodge = outgoing.conj().T @ outgoing + incoming @ incoming.conj().T
        values = np.linalg.eigvalsh((hodge + hodge.conj().T) / 2)
        positive = values[values > 100 * tolerance]
        zero_count = int(np.sum(values <= 100 * tolerance))
        minimum_positive = float(min(positive, default=0.0))
        maximum = float(max(positive, default=0.0))
        condition = (
            float(maximum / minimum_positive) if minimum_positive else math.inf
        )
        if minimum_positive:
            minimum_positive_values.append(minimum_positive)
            conditions.append(condition)
        chain_records.append(
            AugmentedCechChainRecord(
                chain_degree=family_size - 1,
                common_family_size=family_size,
                nonzero_cell_count=len(cells[family_size]),
                coefficient_dimension=chain_dimension,
                outgoing_boundary_rank=outgoing_rank,
                boundary_kernel_dimension=kernel_dimension,
                incoming_boundary_rank=incoming_rank,
                homology_dimension=homology,
                hodge_zero_eigenvalue_count=zero_count,
                minimum_positive_hodge_eigenvalue=minimum_positive,
                maximum_hodge_eigenvalue=maximum,
                positive_hodge_condition_number=condition,
            )
        )

    maximum_composition = max(compositions, default=0.0)
    homology_dimensions = [record.homology_dimension for record in chain_records]
    verified = bool(
        all(value >= 0 for value in homology_dimensions)
        and all(
            record.homology_dimension == record.hodge_zero_eigenvalue_count
            for record in chain_records
        )
        and maximum_composition <= 1000 * tolerance
        and inclusion_residual <= 1000 * tolerance
    )
    exact = verified and not any(homology_dimensions)
    h0 = chain_records[0]
    return AugmentedCommonCoreCechControl(
        control_id=control_id,
        n=sum(target),
        target_partition=target,
        labels=labels,
        orientation_masks=orientation_masks,
        physical_ambient_dimension=synthesis.shape[0],
        active_leaf_count=len(cells[1]),
        leaf_coefficient_dimension=h0.coefficient_dimension,
        leaf_synthesis_rank=h0.outgoing_boundary_rank,
        raw_leaf_dependency_dimension=h0.boundary_kernel_dimension,
        pair_boundary_rank=h0.incoming_boundary_rank,
        emergent_leaf_dependency_homology_dimension=h0.homology_dimension,
        maximum_positive_degree_homology_dimension=max(
            (record.homology_dimension for record in chain_records[1:]),
            default=0,
        ),
        maximum_boundary_composition_residual=maximum_composition,
        maximum_common_cell_inclusion_residual=inclusion_residual,
        minimum_positive_hodge_eigenvalue=min(minimum_positive_values, default=0.0),
        maximum_positive_hodge_condition_number=max(conditions, default=0.0),
        augmented_cech_exact=exact,
        exact_augmented_cech_audit=verified,
        chain_groups=chain_records,
        status=(
            "exact-augmented-cech-complex"
            if exact
            else "emergent-leaf-dependency-homology"
            if verified and h0.homology_dimension
            else "positive-degree-cech-homology"
            if verified
            else "augmented-cech-audit-failure"
        ),
    )


