"""Augmented common-core Cech complex and emergent-dependency audit.

The pair-core complex alone starts at ``C_1`` and can only test whether pair
cycles are generated by triple cores.  Full generation of dependencies also
requires the augmentation

    ... -> C_2 -> C_1 -> C_0 -> V,
    C_p = direct_sum_{|F|=p+1} intersection_{e in F} U_e.  (1)

Here ``C_0`` is the direct sum of leaf ranges and ``D_0`` synthesizes their
physical vectors.  Therefore

    H_0 = ker(D_0) / im(D_1)                              (2)

is precisely the space of many-leaf dependencies not generated by pairwise
common ranges.  Vanishing pair-cycle homology does not constrain (2).

For ``n>=5`` common cells use the exact sparse parity intertwiners.  The W3
adversarial controls use direct physical intersections, since the independent
``A_n`` pattern theorem does not apply below five.  This module is a finite
exactness/falsification workbench, not an all-n sheaf theorem or a circuit.
"""

