@dataclass(frozen=True)
class CanonicalizationResult:
    canonical_tuple: tuple[Permutation, ...]
    transporter: Permutation
    seed_coordinates: tuple[int, int]
    seed_orientations: tuple[int, int]
    root: int
    candidate_count: int


def _conjugate(
    element: Permutation,
    value: Permutation,
) -> Permutation:
    return compose_permutations(
        compose_permutations(element, value), inverse_permutation(element)
    )


def _canonical_coset_representative(
    representative: Permutation,
    hidden: Permutation,
) -> Permutation:
    return min(
        representative,
        compose_permutations(representative, hidden),
    )


def _traversal_labeling(
    hidden: Permutation,
    first: Permutation,
    second: Permutation,
    root: int,
) -> Permutation | None:
    degree = len(hidden)
    generators = (
        hidden,
        first,
        inverse_permutation(first),
        second,
        inverse_permutation(second),
    )
    labels = [-1] * degree
    labels[root] = 0
    queue = [root]
    position = 0
    while position < len(queue):
        vertex = queue[position]
        position += 1
        for generator in generators:
            image = generator[vertex]
            if labels[image] < 0:
                labels[image] = len(queue)
                queue.append(image)
    if len(queue) != degree:
        return None
    return tuple(labels)


def _matching_normalizer(transformed_hidden: Permutation) -> Permutation:
    degree = len(transformed_hidden)
    seen: set[int] = set()
    pairs = []
    for vertex in range(degree):
        if vertex in seen:
            continue
        partner = transformed_hidden[vertex]
        if partner == vertex or transformed_hidden[partner] != vertex:
            raise ValueError("transformed hidden element is not a perfect matching")
        pair = tuple(sorted((vertex, partner)))
        pairs.append(pair)
        seen.update(pair)
    pairs.sort()
    normalizer = [0] * degree
    for index, (left, right) in enumerate(pairs):
        normalizer[left] = 2 * index
        normalizer[right] = 2 * index + 1
    return tuple(normalizer)


def _is_in_centralizer(
    transporter: Permutation,
    hidden: Permutation,
) -> bool:
    return _conjugate(transporter, hidden) == hidden


def apply_transporter_to_tuple(
    source_tuple: tuple[Permutation, ...],
    transporter: Permutation,
    hidden: Permutation,
) -> tuple[Permutation, ...]:
    return tuple(
        _canonical_coset_representative(
            _conjugate(transporter, representative), hidden
        )
        for representative in source_tuple
    )


def canonicalize_source_tuple(
    source_tuple: tuple[Permutation, ...],
) -> CanonicalizationResult | None:
    if len(source_tuple) < 2:
        raise ValueError("at least two source coordinates are required")
    degree = len(source_tuple[0])
    if degree < 4 or degree % 2 or any(len(item) != degree for item in source_tuple):
        raise ValueError("source tuple must contain even-degree permutations")
    half_degree = degree // 2
    hidden = canonical_matching_involution(half_degree)
    normalized_source = tuple(
        _canonical_coset_representative(item, hidden) for item in source_tuple
    )
    candidates: list[
        tuple[
            tuple[Permutation, ...],
            Permutation,
            tuple[int, int],
            tuple[int, int],
            int,
        ]
    ] = []
    for left, right in itertools.combinations(range(len(source_tuple)), 2):
        for left_orientation, right_orientation in itertools.product((0, 1), repeat=2):
            first = normalized_source[left]
            second = normalized_source[right]
            if left_orientation:
                first = compose_permutations(first, hidden)
            if right_orientation:
                second = compose_permutations(second, hidden)
            for root in range(degree):
                labeling = _traversal_labeling(hidden, first, second, root)
                if labeling is None:
                    continue
                transformed_hidden = _conjugate(labeling, hidden)
                normalizer = _matching_normalizer(transformed_hidden)
                transporter = compose_permutations(normalizer, labeling)
                if not _is_in_centralizer(transporter, hidden):
                    raise ArithmeticError("matching normalization left the centralizer")
                transformed = apply_transporter_to_tuple(
                    normalized_source, transporter, hidden
                )
                candidates.append(
                    (
                        transformed,
                        transporter,
                        (left, right),
                        (left_orientation, right_orientation),
                        root,
                    )
                )
    if not candidates:
        return None
    canonical_tuple = min(candidate[0] for candidate in candidates)
    canonical_candidates = [
        candidate for candidate in candidates if candidate[0] == canonical_tuple
    ]
    chosen = min(canonical_candidates, key=lambda candidate: candidate[1:])
    return CanonicalizationResult(
        canonical_tuple=canonical_tuple,
        transporter=chosen[1],
        seed_coordinates=chosen[2],
        seed_orientations=chosen[3],
        root=chosen[4],
        candidate_count=len(candidates),
    )


def _stabilizer_size(
    source_tuple: tuple[Permutation, ...],
    elements: tuple[Permutation, ...],
    hidden: Permutation,
) -> int:
    return sum(
        apply_transporter_to_tuple(source_tuple, element, hidden) == source_tuple
        for element in elements
    )


def audit_trimmed_canonicalizer(
    half_degree: int,
    copy_count: int,
    *,
    maximum_controls: int = 96,
    seed: int = 81173,
) -> CanonicalizerFiniteControl:
    if half_degree < 2 or half_degree > 3:
        raise ValueError("finite control supports half_degree in [2,3]")
    if copy_count < 2:
        raise ValueError("copy_count must be at least two")
    cosets = canonical_plus_cosets(half_degree)
    elements = tuple(
        element
        for element, _, _ in hyperoctahedral_elements(half_degree)
    )
    hidden = canonical_matching_involution(half_degree)
    tuple_count = len(cosets) ** copy_count
    if tuple_count <= maximum_controls:
        controls = list(itertools.product(cosets, repeat=copy_count))
    else:
        rng = random.Random(seed + 1009 * half_degree + copy_count)
        controls = [
            tuple(rng.choice(cosets) for _ in range(copy_count))
            for _ in range(maximum_controls)
        ]
    free = 0
    successful = 0
    covariance_checks = 0
    covariance_failures = 0
    reconstruction_failures = 0
    centralizer_failures = 0
    duplicate_failures = 0
    maximum_candidates = 0
    covariance_elements = elements[: min(8, len(elements))]
    for source_tuple in controls:
        normalized = tuple(
            _canonical_coset_representative(item, hidden)
            for item in source_tuple
        )
        is_free = _stabilizer_size(normalized, elements, hidden) == 1
        result = canonicalize_source_tuple(normalized)
        if is_free:
            free += 1
            successful += result is not None
        if result is None:
            continue
        maximum_candidates = max(maximum_candidates, result.candidate_count)
        centralizer_failures += not _is_in_centralizer(result.transporter, hidden)
        reconstruction_failures += (
            apply_transporter_to_tuple(normalized, result.transporter, hidden)
            != result.canonical_tuple
        )
        if is_free:
            matching_transporters = [
                element
                for element in elements
                if apply_transporter_to_tuple(normalized, element, hidden)
                == result.canonical_tuple
            ]
            duplicate_failures += len(matching_transporters) != 1
        for element in covariance_elements:
            transformed = apply_transporter_to_tuple(normalized, element, hidden)
            transformed_result = canonicalize_source_tuple(transformed)
            covariance_checks += 1
            if (
                transformed_result is None
                or transformed_result.canonical_tuple != result.canonical_tuple
            ):
                covariance_failures += 1
                continue
            if is_free:
                expected = compose_permutations(
                    result.transporter, inverse_permutation(element)
                )
                covariance_failures += transformed_result.transporter != expected
    verified = bool(
        free > 0
        and successful == free
        and covariance_failures == 0
        and reconstruction_failures == 0
        and centralizer_failures == 0
        and duplicate_failures == 0
    )
    return CanonicalizerFiniteControl(
        half_degree=half_degree,
        degree=2 * half_degree,
        copy_count=copy_count,
        tuple_control_count=len(controls),
        free_tuple_control_count=free,
        successful_free_tuple_count=successful,
        covariance_check_count=covariance_checks,
        covariance_failure_count=covariance_failures,
        reconstruction_failure_count=reconstruction_failures,
        transporter_centralizer_failure_count=centralizer_failures,
        duplicate_transporter_failure_count=duplicate_failures,
        maximum_candidate_count=maximum_candidates,
        trimmed_canonicalizer_control_verified=verified,
        status=(
            "trimmed-source-canonicalizer-control-verified"
            if verified
            else "trimmed-canonicalizer-control-failure"
        ),
    )


def transitivity_failure_upper_bound(degree: int) -> float:
    if degree < 2:
        raise ValueError("degree must be at least two")
    return min(
        1.0,
        sum(
            1.0 / math.comb(degree, subset_size)
            for subset_size in range(1, degree // 2 + 1)
        ),
    )


def canonicalizer_scaling_record(
    half_degree: int,
) -> CanonicalizerScalingRecord:
    if half_degree < 3:
        raise ValueError("half_degree must be at least three")
    degree = 2 * half_degree
    matchings = perfect_matching_count(half_degree)
    copies = flatness_copy_count(matchings)
    seed_pairs = copies // 2
    one_pair_failure = transitivity_failure_upper_bound(degree)
    all_seed_failure = one_pair_failure**seed_pairs
    order = (2**half_degree) * math.factorial(half_degree)
    log_nonfree = math.log(order - 1) + copies * math.log(
        nonidentity_character_bound(half_degree)
    )
    nonfree = min(1.0, math.exp(log_nonfree))
    total_failure = min(1.0, nonfree + all_seed_failure)
    eta = (matchings - 1) / (2**copies)
    alternative_failure = min(
        1.0, math.sqrt((1.0 + eta) * total_failure)
    )
    return CanonicalizerScalingRecord(
        half_degree=half_degree,
        degree=degree,
        perfect_matching_count_decimal=str(matchings),
        copy_count=copies,
        disjoint_seed_pair_count=seed_pairs,
        one_pair_intransitivity_upper_bound=one_pair_failure,
        all_seed_pairs_failure_upper_bound=all_seed_failure,
        nonfree_source_fraction_upper_bound=nonfree,
        total_trimmed_source_failure_upper_bound=total_failure,
        trimmed_alternative_failure_upper_bound=alternative_failure,
        trimmed_alternative_success_lower_bound=1.0 - alternative_failure,
        canonicalizer_classical_cost_order="poly(k,m) via seed-pair/root traversal",
        reversible_trimmed_canonicalizer_polynomial=True,
        regular_source_multiplicity_basis_compiled_on_trimmed_mass=True,
        matrix_hecke_transfer_compiled=False,
        status="trimmed-canonicalizer-compiled-physical-transfer-open",
    )


