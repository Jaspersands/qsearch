"""Polynomial canonicalizer on overwhelming free hidden-involution source mass.

The free-orbit boundary leaves coherent canonicalization of tuples in
``X^k=(S_(2m)/<h>)^k`` as an explicit source-basis problem.  On almost all of
the natural source this canonicalizer is polynomial.

Choose two source coordinates ``g_i<h>`` and ``g_j<h>``.  Enumerate their four
orientations ``p=g_i h^a``, ``q=g_j h^b``.  If the labeled permutation action
generated by ``(h,p,q)`` is transitive, then choosing one root vertex fixes a
unique breadth-first labeling using the ordered generators
``h,p,p^-1,q,q^-1``.  Enumerate the ``2m`` roots, normalize the transformed
matching back to canonical ``h``, transform the full tuple, and retain the
lexicographically least result over all seed pairs, orientations, and roots.

For tuples with trivial ``K=C_2 wr S_m`` stabilizer, the resulting transporter
is unique.  The map

    z -> (canonical(z), transporter(z))                 (1)

is injective and equivariant; under ``a in K`` the transporter changes by
right multiplication by ``a^-1``.  A deterministic polynomial classical
circuit for (1) has a reversible polynomial implementation, and a ``K`` QFT
on the transporter exposes an exact regular source copy.

For two independent uniformly oriented cosets, ``p,q`` are independent
uniform permutations.  A union bound over common invariant subsets gives

    Pr[<p,q> intransitive]
      <= delta_n := sum_(s=1)^floor(n/2) 1/binom(n,s).   (2)

Trying ``L`` disjoint coordinate pairs makes seed failure at most
``delta_n^L``.  Combining this with the exact free-orbit bound and the frame
second moment proves that the canonicalizer succeeds on ``1-o(1)`` source and
alternative contribution at the target copy width.

This resolves a high-mass source multiplicity basis, not the algorithm.  The
matrix-valued Hecke transfer from these source copies to physical
multiplicities remains unclassified, and no polar, physical analysis map,
classical separation, or hidden-involution speedup is constructed.
"""

