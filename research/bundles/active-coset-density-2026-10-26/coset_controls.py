def conjugate(order, value, delta):
    """Known-coordinate conjugation; delta is SUPPLIED, not discovered."""
    delta = Matrix(delta)
    size, cols = value.shape
    if size != cols or size % 16:
        raise ValueError("square dimension divisible by 16 required")
    if delta.shape != (4, 1) or any(x.is_Integer is not True for x in delta):
        raise ValueError("integral supplied translation required")
    s = shear(order, delta).repeat(size//16)
    inverse = shear(order, -delta).repeat(size//16)
    return multiply(order, multiply(order, inverse, value), s)


def quadratic_conjugate(order, value, delta):
    """Independent expanded identity, not a quotient-ring computation."""
    size, cols = value.shape
    delta = Matrix(delta)
    if size != cols or size % 16:
        raise ValueError("square dimension divisible by 16 required")
    if delta.shape != (4, 1) or any(x.is_Integer is not True for x in delta):
        raise ValueError("integral supplied translation required")
    nilpotent = shear(order, delta).repeat(size//16)-scalar_matrix(order, eye(size))
    left = multiply(order, nilpotent, value)
    return value+multiply(order, value, nilpotent)-left-multiply(order, left, nilpotent)


def pell_unit_i_generators(order, n, k):
    """Complete ONLY if the caller proves O^* is generated by basis element1.

    This contract holds for the p=11 fixture. The function itself neither
    authenticates a native E nor determines the complete unit group.
    """
    p, inverse = pell_product_factor(n, k)
    p, inverse = scalar_matrix(order, p), scalar_matrix(order, inverse)
    coefficients = [a.copy() for a in scalar_matrix(order, eye(16)).coefficients]
    unit = eye(4)[:, 1]
    for i in range(4):
        coefficients[i][0, 0] = unit[i]
    values = [QMatrix(tuple(coefficients))]
    for j in range(15):
        permutation = eye(16)
        permutation.row_swap(j, j+1)
        values.append(scalar_matrix(order, permutation))
    return tuple(multiply(order, multiply(order, inverse, w), p) for w in values)


def pell_coset_probabilities(n, k):
    """Exact counting formula; no experimental hit rate or native sampler."""
    if type(n) is not int or type(k) is not int or n < 2 or k < 1 or n*n-2*k*k != 1:
        raise ValueError("positive nontrivial Pell pair required")
    return {
        "queries": n**4,
        "cosets": n**3,
        "integral_coset_size": n,
        "useful_integral_queries": n-1,
        "conditional_integral_hit_fraction": Fraction(n-1, n),
        "uniform_integral_hit_fraction": Fraction(n-1, n**4),
        "division_expected_trials": Fraction(n**4, n-1),
    }
