"""Dixmier-Lister: image of Aut on the centre gamma_3, and of Aut(DL/Z') on the centre of DL/Z'
for every line Z' of gamma_3 (exact, GAP/autpgrp; Lie automorphisms re-verified in Python).
Reuses alg.py (pc presentation from BCH) of the adaptive-twist audit; writes only into ./gap/."""
import sys, os, json, subprocess, itertools, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '2026-11-12-rees-adaptive-twist'))
from alg import adapt, gap_pc
from lie import br, bch, tensor, center, rref, rank, nullspace, lcs
GAP = '/opt/anaconda3/envs/qsearch-cas/bin/gap'
OUT = os.path.join(HERE, 'gap')

# DL brackets (1-based, paper sec:dixmier-lister)
DLB = {(1,2):{5:1},(1,3):{6:1},(1,4):{7:1},(1,5):{8:-1},(2,3):{8:1},(2,4):{6:1},(2,6):{7:-1},
       (3,4):{5:-1},(3,5):{7:-1},(4,6):{8:-1}}
def dl(p):
    return 8, {(i-1, j-1): {k-1: c % p for k, c in d.items()} for (i, j), d in DLB.items()}

def quotient(m, brk, Zline, p):
    """L / F_p Zline: basis = complement; returns (m-1, brk') in a basis of the quotient"""
    C = tensor(m, brk, p)
    # basis of quotient: standard basis vectors except a pivot coordinate of Zline
    piv = next(i for i in range(m) if Zline[i] % p)
    keep = [i for i in range(m) if i != piv]
    inv = pow(int(Zline[piv]), -1, p)
    def red(v):  # reduce v modulo Zline, express in 'keep' coords
        v = (v - v[piv] * inv * Zline) % p
        return [int(v[i]) for i in keep]
    out = {}
    E = np.eye(m, dtype=np.int64)
    for a, i in enumerate(keep):
        for b, j in enumerate(keep):
            if a < b:
                r = red(br(E[i], E[j], C, p))
                d = {k: c for k, c in enumerate(r) if c}
                if d: out[(a, b)] = d
    return m - 1, out

def log_word(a, D, p, cls):
    m = D.shape[0]; X = np.zeros(m, dtype=np.int64)
    for i in range(m):
        if a[i]:
            e = np.zeros(m, dtype=np.int64); e[i] = a[i] % p
            X = bch(X, e, D, p, cls)
    return X % p

def autgens(name, m, brk, p):
    fn = os.path.join(OUT, f'{name}_{p}.json')
    if os.path.exists(fn): return json.load(open(fn))
    D, level, cls = adapt(m, brk, p)
    g = gap_pc(name, D, level, cls, p)
    tmp = os.path.join(OUT, f'{name}_{p}.g'); res = os.path.join(OUT, f'{name}_{p}.gout')
    with open(tmp, 'w') as f:
        f.write('LoadPackage("autpgrp");;\n' + g + '\n')
        f.write(f'''pc := FamilyPcgs(G);; if not IsConfluent(G) then Print("NOTCONFLUENT\\n"); fi;
A := AutomorphismGroup(G);;
PrintTo("{res}", "SIZE ", Size(A), "\\n");
for a in GeneratorsOfGroup(A) do AppendTo("{res}", "GEN ", List(pc, x -> ExponentsOfPcElement(pc, Image(a, x))), "\\n"); od;
AppendTo("{res}", "END\\n");
QUIT;
''')
    subprocess.run(['nice', '-n', '19', GAP, '-q', tmp], stdin=subprocess.DEVNULL, capture_output=True, timeout=3300)
    txt = open(res).read().replace('\n ', '').replace('\\\n', '')
    assert 'END' in txt, txt[:300]
    size = int(txt.split('SIZE ')[1].split()[0]); gens = []
    for line in txt.splitlines():
        if line.startswith('GEN '):
            ex = json.loads(line[4:].replace(' ', ''))
            M = np.array([log_word(a, D, p, cls) for a in ex], dtype=np.int64)
            for i in range(m):
                for j in range(m):
                    assert ((D[i, j] @ M) % p == br(M[i], M[j], D, p)).all(), 'not a Lie aut'
            gens.append(M.tolist())
    rec = dict(name=name, p=p, m=m, cls=cls, D=D.tolist(), size=size, gens=gens)
    json.dump(rec, open(fn, 'w')); return rec

def closure(mats, p):
    """finite matrix group generated by mats (small), as set of tuples"""
    I = tuple(np.eye(mats[0].shape[0], dtype=np.int64).flatten())
    seen = {I}; frontier = [np.eye(mats[0].shape[0], dtype=np.int64)]
    while frontier:
        nf = []
        for X in frontier:
            for g in mats:
                Y = (X @ g) % p; t = tuple(Y.flatten())
                if t not in seen: seen.add(t); nf.append(Y)
        frontier = nf
        if len(seen) > 20000: break
    return seen

def centre_image(rec):
    p = rec['p']; D = np.array(rec['D']); m = rec['m']
    Zb = center(D, p)                       # rows: basis of centre (coords in adapted basis)
    k = len(Zb); mats = []
    for G in rec['gens']:
        G = np.array(G)                     # rows = images of basis vectors; x -> x @ G
        img = (Zb @ G) % p                  # images of centre basis vectors
        # express img rows in basis Zb: solve c @ Zb = img
        M = []
        for v in img:
            for c in itertools.product(range(p), repeat=k):
                if (((np.array(c) @ Zb) - v) % p == 0).all(): M.append(list(c)); break
            else: raise RuntimeError('centre not preserved')
        mats.append(np.array(M, dtype=np.int64))
    grp = closure(mats, p)
    scal = sorted({t[0] for t in grp if all(t[i*k+j] == (t[0] if i == j else 0) for i in range(k) for j in range(k))})
    return k, len(grp), scal

if __name__ == '__main__':
    primes = [int(a) for a in sys.argv[1:]] or [5, 7]
    for p in primes:
        m, brk = dl(p)
        rec = autgens('DL', m, brk, p)
        k, n, sc = centre_image(rec)
        print(f'DL p={p} |Aut|={rec["size"]} = {rec["size"]//p**12} * p^12? {rec["size"] % p**12 == 0}'
              f'  dim Z={k}  |image on Z|={n}  scalars={sc}', flush=True)
        if p > 7: continue
        # quotients by lines of gamma_3 = span(e7, e8) (0-based 6, 7)
        for t in [(0, 1)] + [(1, a) for a in range(p)]:
            Zl = np.zeros(8, dtype=np.int64); Zl[6], Zl[7] = t
            mq, bq = quotient(8, brk, Zl, p)
            rq = autgens(f'DLq{t[0]}{t[1]}', mq, bq, p)
            Dq = np.array(rq['D']); ser = lcs(Dq, p)
            kq, nq, scq = centre_image(rq)
            print(f'  DL/<{t[0]}e7+{t[1]}e8> p={p} class={rq["cls"]} lcs dims={[len(s) for s in ser]}'
                  f' |Aut|={rq["size"]} (= {rq["size"]/p**rank(np.eye(1),p) if False else rq["size"]}) dim Z={kq} |image on Z|={nq} scalars={scq}', flush=True)
