import itertools, random, sys
import numpy as np

def inv_mod(a, p):
    return pow(int(a) % p, p - 2, p)

def mat_exp(x, p):
    """truncated exp sum_{j<p} x^j/j! mod p (x nilpotent with x^p = 0)."""
    N = x.shape[0]
    out = np.eye(N, dtype=np.int64)
    term = np.eye(N, dtype=np.int64)
    fact = 1
    for j in range(1, p):
        term = (term @ x) % p
        fact = fact * j % p
        out = (out + term * inv_mod(fact, p)) % p
    return out

def mat_log(g, p):
    N = g.shape[0]
    y = (g - np.eye(N, dtype=np.int64)) % p
    out = np.zeros((N, N), dtype=np.int64)
    term = np.eye(N, dtype=np.int64)
    for j in range(1, p):
        term = (term @ y) % p
        c = inv_mod(j, p) * (1 if j % 2 == 1 else p - 1) % p
        out = (out + c * term) % p
    return out

def exp_ad(x, M, p):
    """truncated sum_{k<p} ad_x^k(M)/k!."""
    out = M.copy() % p
    term = M.copy() % p
    fact = 1
    for k in range(1, p):
        term = (x @ term - term @ x) % p
        fact = fact * k % p
        out = (out + term * inv_mod(fact, p)) % p
    return out

def span_elements(basis, p):
    """all F_p-combinations of a list of matrices."""
    if not basis:
        yield np.zeros((1, 1), dtype=np.int64)
        return
    for coeffs in itertools.product(range(p), repeat=len(basis)):
        x = sum(c * b for c, b in zip(coeffs, basis)) % p
        yield x

def strict_upper_basis(N):
    B = []
    for i in range(N):
        for j in range(i + 1, N):
            E = np.zeros((N, N), dtype=np.int64); E[i, j] = 1; B.append(E)
    return B

def key(M):
    return tuple(M.flatten().tolist())

def lie_closure(gens, p, N):
    """basis (row-reduced) of the Lie subalgebra generated by gens."""
    def rank_basis(mats):
        rows = [m.flatten() % p for m in mats]
        A = np.array(rows, dtype=np.int64) if rows else np.zeros((0, N * N), dtype=np.int64)
        # row reduce mod p
        A = A.copy(); r = 0; piv = []
        for c in range(A.shape[1]):
            pr = None
            for i in range(r, A.shape[0]):
                if A[i, c] % p:
                    pr = i; break
            if pr is None:
                continue
            A[[r, pr]] = A[[pr, r]]
            A[r] = A[r] * inv_mod(A[r, c], p) % p
            for i in range(A.shape[0]):
                if i != r and A[i, c] % p:
                    A[i] = (A[i] - A[i, c] * A[r]) % p
            r += 1
            if r == A.shape[0]:
                break
        return [A[i].reshape(N, N) for i in range(r)]
    basis = rank_basis(gens)
    while True:
        new = basis + [(a @ b - b @ a) % p for a in basis for b in basis]
        nb = rank_basis(new)
        if len(nb) == len(basis):
            return nb
        basis = nb

def check_stabilizer(N, p, L_basis, tuples, label):
    G = [(x, mat_exp(x, p)) for x in span_elements(L_basis, p)] if L_basis else [(np.zeros((N, N), dtype=np.int64), np.eye(N, dtype=np.int64))]
    # sanity: exp(L) is closed under products, log(exp x) = x
    gk = {key(g) for _, g in G}
    assert len(gk) == len(G), "exp not injective"
    for x, g in G:
        assert key(mat_log(g, p)) == key(x)
    rnd = random.Random(1)
    for _ in range(min(200, len(G) ** 2)):
        (_, g1), (_, g2) = rnd.choice(G), rnd.choice(G)
        assert key((g1 @ g2) % p) in gk, "exp(L) not closed"
    bad = 0
    for A in tuples:
        brute = {key(g) for x, g in G if all(np.array_equal((g @ Ai) % p, (Ai @ g) % p) for Ai in A)}
        lin = {key(g) for x, g in G if all(np.array_equal((x @ Ai) % p, (Ai @ x) % p) for Ai in A)}
        if brute != lin:
            bad += 1
    print(f"[stab] N={N} p={p} {label}: |G|={len(G)} tuples={len(tuples)} mismatches={bad}")
    return bad

def random_tuples(N, p, k, n, rnd, L_basis):
    T = []
    for _ in range(n):
        T.append([np.array([[rnd.randrange(p) for _ in range(N)] for _ in range(N)], dtype=np.int64) for _ in range(k)])
    # structured: elements of L, E_{N1}, sparse matrices, diagonal, low rank
    E = np.zeros((N, N), dtype=np.int64); E[N - 1, 0] = 1
    T.append([E])
    J = np.eye(N, k=1, dtype=np.int64)
    T.append([J]); T.append([J.T]); T.append([(J @ J) % p])
    for _ in range(n):
        x = sum(rnd.randrange(p) * b for b in L_basis) % p if L_basis else np.zeros((N, N), dtype=np.int64)
        T.append([x])
        M = np.zeros((N, N), dtype=np.int64)
        for _ in range(2):
            M[rnd.randrange(N), rnd.randrange(N)] = rnd.randrange(1, p)
        T.append([M, x])
        D = np.diag([rnd.randrange(p) for _ in range(N)]).astype(np.int64)
        T.append([D])
    return T

def check_transporter(N, p, n, rnd):
    L_basis = strict_upper_basis(N)
    G = [mat_exp(x, p) for x in span_elements(L_basis, p)]
    bad = 0; nonempty = 0
    for t in range(n):
        k = 1 + t % 2
        A = [np.array([[rnd.randrange(p) for _ in range(N)] for _ in range(N)], dtype=np.int64) for _ in range(k)]
        if t % 3:
            g0 = rnd.choice(G); g0i = mat_exp((-mat_log(g0, p)) % p, p)
            B = [(g0 @ Ai @ g0i) % p for Ai in A]
        else:
            B = [np.array([[rnd.randrange(p) for _ in range(N)] for _ in range(N)], dtype=np.int64) for _ in range(k)]
        brute = set()
        for g in G:
            ginv = mat_exp((-mat_log(g, p)) % p, p)
            if all(np.array_equal((g @ Ai @ ginv) % p, Bi % p) for Ai, Bi in zip(A, B)):
                brute.add(key(g))
        lin = set()
        for X in span_elements(L_basis, p):
            if all(np.array_equal((X @ Ai - Bi @ X) % p, (Bi - Ai) % p) for Ai, Bi in zip(A, B)):
                lin.add(key((np.eye(N, dtype=np.int64) + X) % p))
        nonempty += bool(brute)
        if brute != lin:
            bad += 1
    print(f"[transporter] N={N} p={p}: cases={n} nonempty={nonempty} mismatches={bad}")
    return bad

def check_exp_ad(N, p, exhaustive_limit=20000):
    """returns (differs_somewhere, witness_differs)."""
    J = np.eye(N, k=1, dtype=np.int64)
    E = np.zeros((N, N), dtype=np.int64); E[N - 1, 0] = 1
    wit = not np.array_equal((mat_exp(J, p) @ E @ mat_exp((-J) % p, p)) % p, exp_ad(J, E, p))
    L_basis = strict_upper_basis(N)
    units = []
    for i in range(N):
        for j in range(N):
            U = np.zeros((N, N), dtype=np.int64); U[i, j] = 1; units.append(U)
    differs = wit
    total = p ** len(L_basis)
    if total <= exhaustive_limit:
        exhaust = True
        for x in span_elements(L_basis, p):
            ex, exm = mat_exp(x, p), mat_exp((-x) % p, p)
            for U in units:
                if not np.array_equal((ex @ U @ exm) % p, exp_ad(x, U, p)):
                    differs = True; break
            if differs and wit:
                break
    else:
        exhaust = False
    return differs, wit, exhaust

