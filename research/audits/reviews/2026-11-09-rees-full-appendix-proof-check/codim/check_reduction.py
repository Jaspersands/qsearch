# validate BCH implementation: associativity and inverse on a class-4 and a class-5 algebra
from check_examples_defs import g6, filiform
for (L, c) in [(filiform(5, 7), 4), (g6(7), 5), (g6(11), 5)]:
    bch = make_bch(L, c)
    okA = True
    for _ in range(20):
        x, y, z = [rand_vec_in(L.basis(), L.p, rng) for _ in range(3)]
        if bch(bch(x, y), z) != bch(x, bch(y, z)): okA = False
        if any(bch(x, tuple((-v) % L.p for v in x))): okA = False
        if bch(x, tuple([0] * L.n)) != x: okA = False
    log(f"BCH recurrence validated (assoc, inverse, identity) on n={L.n} class={c} p={L.p}: {okA}")

viol = []
for a in range(NALG):
    p = rng.choice([5, 7, 11])
    L = random_algebra(p)
    if L.n == 0: continue
    c0 = nil_class(L)
    if c0 >= p: continue
    stats["algs"] += 1
    bch0 = make_bch(L, max(1, c0)) if (c0 <= 5 and L.n <= 8) else None
    for t in range(4):
        h = random_subalgebra(L)
        codim = L.n - len(h)
        for k in sorted(set([codim, codim + rng.choice([0, 1, 2])])):
            stats["pairs"] += 1
            r = run_reduction(L, h, k, bch0, c0)
            if r is not None:
                viol.append((p, L.n, c0, codim, k, r))
                log("VIOLATION", p, L.n, c0, codim, k, r)
