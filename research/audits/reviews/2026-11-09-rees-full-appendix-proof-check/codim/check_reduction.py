rng = random.Random(seed)
out = []
def log(*a):
    s = " ".join(str(x) for x in a)
    print(s, flush=True); out.append(s)

# ---------- random nilpotent algebras ----------
def matmul(A, B, p):
    N = len(A)
    return [[sum(A[i][k] * B[k][j] for k in range(N)) % p for j in range(N)] for i in range(N)]

def comm(A, B, p):
    X = matmul(A, B, p); Y = matmul(B, A, p)
    return [[(X[i][j] - Y[i][j]) % p for j in range(len(A))] for i in range(len(A))]

def flat(A):
    return tuple(x for row in A for x in row)

def unflat(v, N):
    return [list(v[i * N:(i + 1) * N]) for i in range(N)]

def lie_from_matrices(gens, N, p):
    S = span([flat(g) for g in gens], p)
    while True:
        new = span(S + [flat(comm(unflat(a, N), unflat(b, N), p)) for a in S for b in S], p)
        if len(new) == len(S):
            break
        S = new
    n = len(S)
    C = [[None] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            C[i][j] = coords_in(flat(comm(unflat(S[i], N), unflat(S[j], N), p)), S, p)
    return Lie(n, p, C)

def rand_ut(N, p, dens):
    A = [[0] * N for _ in range(N)]
    for i in range(N):
        for j in range(i + 1, N):
            if rng.random() < dens:
                A[i][j] = rng.randrange(p)
    return A

def quotient_by(L, K):
    # quotient by an ideal K
    Lq, comp, proj = quotient(L, L.basis(), span(K, L.p), rng)
    return Lq

def random_algebra(p):
    t = rng.random()
    if t < 0.5:
        N = rng.choice([3, 4, 5])
        gens = [rand_ut(N, p, rng.choice([0.3, 0.5, 0.8])) for _ in range(rng.choice([2, 2, 3]))]
        L = lie_from_matrices(gens, N, p)
    elif t < 0.75:
        N = rng.choice([4, 5])
        gens = [rand_ut(N, p, rng.choice([0.4, 0.7])) for _ in range(rng.choice([2, 3]))]
        L = lie_from_matrices(gens, N, p)
        if L.n >= 3:
            # quotient by the ideal generated by a random element of gamma_2 (or centre)
            g = lcs(L)
            if len(g) > 2 and g[1]:
                v = rand_vec_in(g[1], p, rng)
                K = span([v], p)
                while True:
                    K2 = span(K + [L.br(u, k) for u in L.basis() for k in K], p)
                    if len(K2) == len(K): break
                    K = K2
                if 0 < len(K) < L.n:
                    L = quotient_by(L, K)
    else:
        # named algebras
        from check_examples_defs import g6, five, filiform, heis
        L = rng.choice([lambda: g6(p), lambda: five(p), lambda: filiform(rng.choice([4, 5, 6]), p), lambda: heis(p)])()
    return L

def random_subalgebra(L):
    p = L.p
    t = rng.random()
    if t < 0.6:
        gens = []
        for _ in range(rng.choice([1, 1, 2, 2, 3])):
            v = [0] * L.n
            for i in range(L.n):
                if rng.random() < rng.choice([0.3, 0.6, 1.0]):
                    v[i] = rng.randrange(p)
            gens.append(tuple(v))
        return subalgebra_generated(L, gens)
    elif t < 0.8:
        g = lcs(L)
        j = rng.randrange(1, len(g))
        return subalgebra_generated(L, g[j] + [rand_vec_in(L.basis(), p, rng)])
    else:
        return subalgebra_generated(L, [rand_vec_in(L.basis(), p, rng) for _ in range(rng.choice([1, 2]))])

stats = {"algs": 0, "pairs": 0, "ideals": 0, "terminals": 0, "viol": 0, "recovered": 0,
         "group_pairs_checked": 0, "nonlin_checked": 0}
extremal = {}

def check_ideal(L, xs):
    p = L.p
    I = span(xs, p)
    ok = is_abelian(L, I) and is_ideal(L, I)
    # flag
    for i, x in enumerate(xs):
        prev = span(xs[:i], p) if i else []
        for u in L.basis():
            if any(L.br(u, x)) and not (prev and in_span(L.br(u, x), prev, p)):
                ok = False
    sc = subspace_eq(centralizer(L, I), I, p)
    b = len(I)
    cl = nil_class(L)
    size_ok = L.n <= b * (b + 1) // 2 and (L.n == 0 or cl <= 2 * b - 1)
    return ok and sc and size_ok, b, cl

def ad_list(L, h):
    g = lcs(L)
    res = []
    for d in range(2, len(g)):
        gd = g[d - 1]
        if not gd: break
        res.append(len(gd) - len(intersect(h, gd, L.n, L.p)) if h else len(gd))
    return res

def run_reduction(L0, h0, k, bch0, c0):
    """Lie-level reduction with exact learning; group-level sampled checks of transport."""
    p = L0.p
    levels = []
    L, h, kk = L0, h0, k
    Lam = L0.basis()  # images of basis vectors of L_j in L_0
    while True:
        n = L.n
        codim = n - len(h)
        if codim > kk:
            return "codim>k invariant broken"
        if kk <= 0:
            if codim != 0: return "k<=0 but codim>0"
            hJ = L.basis(); break
        if all(not any(L.br(a, b)) for a in L.basis() for b in L.basis()):
            hJ = h; break
        xs, ext = ideal_construction(L, rng)
        stats["ideals"] += 1
        ok, b, cl = check_ideal(L, xs)
        if not ok: return f"ideal check failed n={n} b={b} cl={cl}"
        I = span(xs, p)
        if b <= kk:
            stats["terminals"] += 1
            if not (n <= k * (k + 1) // 2 and cl <= min(2 * k - 1, c0)):
                return f"terminal bound violated n={n} cl={cl} k={k}"
            ad = ad_list(L, h)
            if any(a > k for a in ad) or any(a > codim for a in ad):
                return f"a_d bound violated {ad} k={k}"
            key = k
            extremal[key] = max(extremal.get(key, (0, 0)), (n, cl))
            extremal[(key, 'class')] = max(extremal.get((key, 'class'), (0, 0)), (cl, n))
            hJ = h; break
        kj = intersect(h, I, n, p) if h else []
        if not (len(kj) >= b - kk and len(kj) > 0):
            return "dim k_j < b-k"
        s = normalizer(L, kj)
        if not contains(s, h, p): return "h not in normalizer"
        if not contains(s, kj, p) or not all(in_span(L.br(y, v), kj, p) for y in s for v in kj):
            return "k not ideal of s"
        Lq, comp, proj = quotient(L, s, kj, rng)
        hq = span([proj(v) for v in h], p)
        if Lq.n > n - 1: return "dimension did not drop"
        if nil_class(Lq) > nil_class(L): return "class increased"
        k_next = kk - (n - len(s))
        if (Lq.n - len(hq)) != codim - (n - len(s)): return "codim formula"
        Lam_next = [apply_lin(Lam, c, p) for c in [coords_in(v, L.basis(), p) for v in comp]]
        levels.append((L, kj, comp, s, proj, Lam, h))
        L, h, kk, Lam = Lq, hq, k_next, Lam_next
    # unwind
    hcur = hJ
    for (Lj, kj, comp, s, proj, Lamj, hj) in reversed(levels):
        lifted = [apply_lin(comp, w, p) for w in hcur]
        hcur = span(lifted + kj, p)
        if not subspace_eq(hcur, hj, p): return "unwind mismatch"
    if not subspace_eq(hcur, h0, p): return "final mismatch"
    # group-level sampled transport checks at every level (BCH available only if class<=4 here)
    if bch0 is not None:
        for (Lj, kj, comp, s, proj, Lamj, hj) in levels + [(L, None, None, None, None, Lam, h)]:
            cj = max(1, nil_class(Lj))
            bchj = make_bch(Lj, cj)
            # f_j(x) == f_j(y) iff x^{-1}*y in h_j, f_j = f o Lam_j, f hides h0 in L0
            def inH0(v):
                return in_span(v, h0, p) if h0 else not any(v)
            def neg(v): return tuple((-x) % p for x in v)
            for _ in range(6):
                x = rand_vec_in(Lj.basis(), p, rng)
                if hj and rng.random() < 0.5:
                    y = bchj(x, rand_vec_in(hj, p, rng))
                else:
                    y = rand_vec_in(Lj.basis(), p, rng)
                lhs = inH0(bch0(neg(apply_lin(Lamj, x, p)), apply_lin(Lamj, y, p)))
                xy = bchj(neg(x), y)
                rhs = in_span(xy, hj, p) if hj else not any(xy)
                stats["group_pairs_checked"] += 1
                if lhs != rhs:
                    return "group-level hiding broken at a level"
            if kj is not None and kj:
                # nonlinear section tau(q) = sigma(q) + kappa(q), kappa: random function into k_j
                memo = {}
                def tau(qv):
                    if qv not in memo:
                        memo[qv] = vec_add(apply_lin(comp, qv, p), rand_vec_in(kj, p, rng), p)
                    return memo[qv]
                Lq_basis_dim = len(comp)
                Lq = None
                for _ in range(6):
                    q1 = tuple(rng.randrange(p) for _ in range(Lq_basis_dim))
                    q2 = tuple(rng.randrange(p) for _ in range(Lq_basis_dim))
                    t1, t2 = tau(q1), tau(q2)
                    lhs = inH0(bch0(neg(apply_lin(Lamj, t1, p)), apply_lin(Lamj, t2, p)))
                    # q1^{-1} * q2 in pi(h_j)  <=> (tau q1)^{-1} * (tau q2) in h_j (by the lemma); compute in s/k:
                    g_ = bchj(neg(t1), t2)
                    pg = proj(g_)
                    phj = span([proj(v) for v in hj], p)
                    rhs = in_span(pg, phj, p) if phj else not any(pg)
                    stats["nonlin_checked"] += 1
                    if lhs != rhs:
                        return "nonlinear transport broken"
    stats["recovered"] += 1
    return None

