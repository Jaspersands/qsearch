def primes_of(n):
    return [q for q in range(2, n + 1) if n % q == 0 and all(q % r for r in range(2, q))]

if NAME == 'EllCheck':
    out = [HEAD]
else:
    out = ['import Formal.Schedule1HPlusReview.EllCheck\n\n/-! Generated by `gen_ell_lean.py`: the level-4 table(s) '
           + ', '.join(CASES) + ' checked against `IsEllContraction` (see `EllCheck.lean`). Not imported by `Formal.lean`. -/\n\n'
           'namespace QSearch.Schedule1HPlus.Review\n\nopen QSearch.Schedule1H QSearch.Schedule1HPlus Finset\n']
done_p = set()
for c in CASES:
    p, k, l, g, f = META[c]
    tab = json.load(open(os.path.join(SRC, f)))
    assert len(tab) == k ** l
    tag = c.replace('_', '')
    if p == 13:
        Cn = 'C13'
    else:
        Cn = f'C{p}'
        if p not in done_p:
            pr = primes_of(p - 1)
            out.append(CMAP.format(p=p, g=g, primes='[' + ', '.join(map(str, pr)) + ']',
                                   pats=' | '.join('rfl' for _ in pr)))
            done_p.add(p)
    h = (p - 1) // k
    tmpl = CASE3 if l == 3 else CASE4
    k0 = next(x for x in sorted(tab) if x != '0' * l and tab[x] % p)
    ykey = '![' + ', '.join(k0) + ']'
    ytest = '![' + ', '.join(d if d != '0' else '1' for d in k0) + ']'
    sub = ''; clsx = ''; annx = ''
    if l == 4:
        for a in range(k):
            sub += (f"theorem cls_{tag}_{a} : ∀ b c d : ZMod {k}, tab{tag} ![{a}, b, c, d] ≠ 0 →\n"
                    f"    tab{tag} ![{a}, b, c, d] ^ {h} = 1 := by decide +kernel\n\n")
            clsx += f"    · exact cls_{tag}_{a}\n"
            if a:
                for b in range(1, k):
                    sub += (f"theorem ann_{tag}_{a}_{b} : ∀ c d : ZMod {k}, (∀ r, ![({a} : ZMod {k}), {b}, c, d] r ≠ 0) →\n"
                            f"    fullContr ({g} : ZMod {p}) 4 tab{tag} ![{a}, {b}, c, d] = 0 := by decide +kernel\n\n")
                annx += f"    · intro b; fin_cases b\n      · intro c d h; exact (h 1 rfl).elim\n"
                annx += ''.join(f"      · exact ann_{tag}_{a}_{b}\n" for b in range(1, k))
    out.append(tmpl.format(sub=sub, clsx=clsx.rstrip('\n'), annx=annx.rstrip('\n'), ykey=ykey, ytest=ytest, tag=tag, f=f, data=nested(tab, k, l), g=g, p=p, k=k, h=h, Cn=Cn,
                           half=(p - 1) // 2))
out.append('\n'.join(f'#print axioms ell_{c.replace("_", "")}\n#print axioms ell_{c.replace("_", "")}_scaled' for c in CASES))
if NAME == 'EllCheck': out.append('#print axioms ann_iff_fullContr')
out.append('\nend QSearch.Schedule1HPlus.Review\n')
open(OUT, 'w').write('\n'.join(out))
