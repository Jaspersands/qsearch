def nested(tab, k, l, prefix=''):
    if len(prefix) == l:
        return str(tab[prefix])
    return '[' + ', '.join(nested(tab, k, l, prefix + str(d)) for d in range(k)) + ']'

HEAD = r'''import Formal.Schedule1HPlusReview.EllTable

/-!
# Hostile review (2026-11-14): a verified checker for `def:plus-ell` and the paper's tables

Not imported by `Formal.lean`. Generated by
`research/audits/reviews/2026-11-14-rees-lean-schedule1hplus-review/gen_ell_lean.py`
(tables read from `research/audits/reviews/2026-11-13-rees-k9-below-21/`).

* `fullContr`: contract the table on every axis with `x ↦ x_a - z_a x_0` (the paper's
  remark after `def:plus-ell`); `sum_E_eq_fullContr` proves it equals the basis-tensor
  sum of `EllTable.lean`, so `ann_iff_fullContr`: condition (iii) holds iff every full
  contraction at `y'` without zero coordinate vanishes. `2^ℓ` table reads per `y'`.
* The tables, `C_y = g^{y_1+…+y_ℓ} B(y)`, checked against the Lean `IsEllContraction`
  by `decide +kernel` (no `native_decide`).
-/

namespace QSearch.Schedule1HPlus.Review

open QSearch.Schedule1H QSearch.Schedule1HPlus Finset

section Checker

variable {K : Type*} [Field K] [DecidableEq K] {N : ℕ} (C : ClassMap K N)
variable {κ : ℕ} [NeZero κ]

/-- Contract the first axis with `x ↦ x_a - z^a x_0`. -/
def contr1 (z : K) {n : ℕ} (Ct : (Fin (n + 1) → ZMod κ) → K) (a : ZMod κ)
    (t : Fin n → ZMod κ) : K :=
  Ct (Fin.cons a t) - z ^ a.val * Ct (Fin.cons 0 t)

/-- Contract every axis, at `y'`. -/
def fullContr (z : K) : (n : ℕ) → ((Fin n → ZMod κ) → K) → (Fin n → ZMod κ) → K
  | 0, Ct, y' => Ct y'
  | n + 1, Ct, y' => fullContr z n (contr1 z Ct (y' 0)) (Fin.tail y')

omit [DecidableEq K] [NeZero κ] in
theorem sum_pi_succ {α : Type*} [Fintype α] {n : ℕ} (F : (Fin (n + 1) → α) → K) :
    ∑ y, F y = ∑ a, ∑ t : Fin n → α, F (Fin.cons a t) := by
  rw [← Fintype.sum_prod_type' (fun a (t : Fin n → α) => F (Fin.cons a t))]
  exact (Fintype.sum_equiv (Fin.consEquiv fun _ => α) _ _ (fun _ => rfl)).symm

omit [DecidableEq K] in
theorem sum_axis (z : K) {a : ZMod κ} (ha : a ≠ 0) (g : ZMod κ → K) :
    ∑ u, ecoefz z u a * g u = g a - z ^ a.val * g 0 := by
  rw [Fintype.sum_eq_add 0 a (Ne.symm ha)]
  · simp only [ecoefz, ha, ite_false, ite_true, one_mul]
    ring
  · intro x ⟨hx0, hxa⟩
    simp [ecoefz, ha, hx0, hxa]

omit [DecidableEq K] in
theorem sum_E_eq_fullContr (z : K) : ∀ (n : ℕ) (Ct : (Fin n → ZMod κ) → K)
    (y' : Fin n → ZMod κ), (∀ r, y' r ≠ 0) → ∑ y, Ct y * Ecoefz z y y' = fullContr z n Ct y'
  | 0, Ct, y', _ => by
    rw [Fintype.sum_unique]
    simp only [Ecoefz, Finset.univ_eq_empty, Finset.prod_empty, mul_one, fullContr]
    exact congrArg Ct (Subsingleton.elim _ _)
  | n + 1, Ct, y', hy' => by
    have ha : y' 0 ≠ 0 := hy' 0
    rw [sum_pi_succ]
    have h1 : ∀ a (t : Fin n → ZMod κ), Ct (Fin.cons a t) * Ecoefz z (Fin.cons a t) y' =
        ecoefz z a (y' 0) * (Ct (Fin.cons a t) * Ecoefz z t (Fin.tail y')) := by
      intro a t
      simp only [Ecoefz, Fin.prod_univ_succ, Fin.cons_zero, Fin.cons_succ, Fin.tail]
      ring
    simp_rw [h1]
    rw [Finset.sum_comm]
    simp_rw [sum_axis z ha (fun a => Ct (Fin.cons a _) * Ecoefz z _ (Fin.tail y'))]
    have h2 : ∀ t : Fin n → ZMod κ,
        Ct (Fin.cons (y' 0) t) * Ecoefz z t (Fin.tail y') -
          z ^ (y' 0).val * (Ct (Fin.cons 0 t) * Ecoefz z t (Fin.tail y')) =
        contr1 z Ct (y' 0) t * Ecoefz z t (Fin.tail y') := by
      intro t; simp only [contr1]; ring
    simp_rw [h2]
    exact sum_E_eq_fullContr z n _ (Fin.tail y') (fun r => hy' r.succ)

/-- **Condition (iii) of `def:plus-ell` iff all full contractions vanish.** -/
theorem ann_iff_fullContr {ℓ : ℕ} (Ct : (Fin ℓ → ZMod κ) → K) :
    (∀ X : (Fin ℓ → ZMod κ) → K, AxisRel C ℓ X → ∑ y, Ct y * X y = 0) ↔
      ∀ y' : Fin ℓ → ZMod κ, (∀ r, y' r ≠ 0) → fullContr C.xi ℓ Ct y' = 0 := by
  rw [ann_iff_check]
  constructor
  · intro h y' hy
    rw [← sum_E_eq_fullContr C.xi ℓ Ct y' hy]
    exact h y'
  · intro h y'
    by_cases hy : ∀ r, y' r ≠ 0
    · rw [sum_E_eq_fullContr C.xi ℓ Ct y' hy]; exact h y' hy
    · push Not at hy
      obtain ⟨r, hr⟩ := hy
      refine Finset.sum_eq_zero fun y _ => ?_
      have : Ecoefz C.xi y y' = 0 :=
        Finset.prod_eq_zero (Finset.mem_univ r) (by simp [ecoefz, hr])
      rw [this, mul_zero]

/-- Decidable form of `IsEllContraction C ℓ {0}` through `fullContr`. -/
theorem isEll_zero_iff' {K : Type*} [Field K] [Fintype K] [DecidableEq K] {N : ℕ}
    (C : ClassMap K N) {κ : ℕ} [NeZero κ] {h : ℕ} (hκ : κ ∣ N)
    (hκh : κ * h = Fintype.card K - 1) (hh : 0 < h) {ℓ : ℕ} (Ct : (Fin ℓ → ZMod κ) → K) :
    IsEllContraction C ℓ {0} Ct ↔
      ((∀ y, Ct y ≠ 0 → Ct y ^ h = 1) ∧ (Ct 0 ≠ 0 ∧ Ct 0 ^ h = 1) ∧
        ∀ y' : Fin ℓ → ZMod κ, (∀ r, y' r ≠ 0) → fullContr C.xi ℓ Ct y' = 0) := by
  rw [isEll_zero_iff C hκ hκh hh, ← ann_iff_check, ann_iff_fullContr]

omit [DecidableEq K] [NeZero κ] in
theorem forall_fin3 {P : (Fin 3 → ZMod κ) → Prop} (h : ∀ a b c, P ![a, b, c]) : ∀ y, P y := by
  intro y
  have : y = ![y 0, y 1, y 2] := by funext r; fin_cases r <;> rfl
  rw [this]; exact h _ _ _

omit [DecidableEq K] [NeZero κ] in
theorem forall_fin4 {P : (Fin 4 → ZMod κ) → Prop} (h : ∀ a b c d, P ![a, b, c, d]) :
    ∀ y, P y := by
  intro y
  have : y = ![y 0, y 1, y 2, y 3] := by funext r; fin_cases r <;> rfl
  rw [this]; exact h _ _ _ _

end Checker
'''

