"""Small exact Lie-algebra / Lazard-group toolkit for the 2026-11-12 harsh Sec. 4 referee.

Independent of the paper's artifacts. Everything is mod p, exact integers.
Run with /opt/anaconda3/bin/python. Finite checks only falsify.
"""
import itertools
import numpy as np


class Lie:
    """Nilpotent Lie algebra over F_p with basis e_0..e_{n-1}.

    brackets: dict (i, j) -> {k: coeff} for i < j (antisymmetry implied).
    weight[i] = filtration weight (e_i in gamma_{weight[i]}); used only to build
    the Rees cover, and checked against the lower central series.
    """

    def __init__(self, p, n, brackets, cls, names=None):
        self.p, self.n, self.cls = p, n, cls
        self.names = names or [f"e{i}" for i in range(n)]
        ent = []
        for (i, j), d in brackets.items():
            for k, c in d.items():
                c %= p
                if c:
                    ent.append((i, j, k, c))
                    ent.append((j, i, k, (-c) % p))
        self.ent = ent

    def br(self, X, Y):
        """Vectorised bracket. X, Y arrays (..., n) of ints mod p."""
        X = np.asarray(X, dtype=np.int64)
        Y = np.asarray(Y, dtype=np.int64)
        shape = np.broadcast_shapes(X.shape, Y.shape)
        out = np.zeros(shape, dtype=np.int64)
        for i, j, k, c in self.ent:
            out[..., k] += c * X[..., i] * Y[..., j]
        return out % self.p

    def bch(self, X, Y):
        """Truncated BCH product up to class self.cls (<= 4 supported)."""
        p = self.p
        X = np.asarray(X, dtype=np.int64)
        Y = np.asarray(Y, dtype=np.int64)
        inv = lambda a: pow(a, -1, p)
        Z = X + Y
        if self.cls >= 2:
            XY = self.br(X, Y)
            Z = Z + inv(2) * XY
        if self.cls >= 3:
            XXY = self.br(X, XY)
            YYX = self.br(Y, (-XY) % p)
            Z = Z + inv(12) * (XXY + YYX)
        if self.cls >= 4:
            YXXY = self.br(Y, XXY)
            Z = Z - inv(24) * YXXY
        if self.cls >= 5:
            raise NotImplementedError
        return Z % p

    # ---- helpers ----
    def span_closure_sub(self, gens):
        """Return row-reduced basis of the Lie subalgebra generated by gens."""
        p = self.p
        B = rref(np.array(gens, dtype=np.int64).reshape(-1, self.n) % p, p)
        while True:
            new = [self.br(a, b) for a in B for b in B]
            B2 = rref(np.vstack([B] + new) if new else B, p)
            if B2.shape[0] == B.shape[0]:
                return B2
            B = B2

    def lcs(self):
        """Lower central series bases gamma_1..gamma_{cls+1}."""
        p = self.p
        I = np.eye(self.n, dtype=np.int64)
        g = [rref(I, p)]
        for _ in range(self.cls + 1):
            prev = g[-1]
            new = [self.br(I[i], v) for i in range(self.n) for v in prev]
            g.append(rref(np.array(new).reshape(-1, self.n) % p, p) if new else np.zeros((0, self.n), dtype=np.int64))
        return g


def rref(M, p):
    M = np.array(M, dtype=np.int64) % p
    if M.ndim == 1:
        M = M.reshape(1, -1)
    M = M.copy()
    r = 0
    rows, cols = M.shape
    for c in range(cols):
        piv = None
        for i in range(r, rows):
            if M[i, c] % p:
                piv = i
                break
        if piv is None:
            continue
        M[[r, piv]] = M[[piv, r]]
        M[r] = (M[r] * pow(int(M[r, c]), -1, p)) % p
        for i in range(rows):
            if i != r and M[i, c]:
                M[i] = (M[i] - M[i, c] * M[r]) % p
        r += 1
        if r == rows:
            break
    return M[:r]


def in_span(B, V, p):
    """Vectorised membership: rows of V in rowspace of B (B in rref)."""
    V = np.asarray(V, dtype=np.int64) % p
    if B.shape[0] == 0:
        return np.all(V == 0, axis=-1)
    W = V.copy()
    for row in B:
        c = int(np.nonzero(row)[0][0])
        W = (W - W[..., c:c + 1] * row) % p
    return np.all(W == 0, axis=-1)


def null_space(M, p):
    """Basis of {x : M x = 0}."""
    M = rref(M, p)
    n = M.shape[1]
    pivs = [int(np.nonzero(r)[0][0]) for r in M]
    free = [c for c in range(n) if c not in pivs]
    out = []
    for f in free:
        v = np.zeros(n, dtype=np.int64)
        v[f] = 1
        for r, pc in zip(M, pivs):
            v[pc] = (-r[f]) % p
        out.append(v)
    return np.array(out, dtype=np.int64).reshape(-1, n)


# ---------------- Rees cover ----------------
class Cover:
    """Positive lower-central Rees algebra of L, built from an adapted basis.

    Cover basis: (k, i) with 1 <= k <= c and weight[i] >= k. Quotient level d keeps k <= d.
    """

    def __init__(self, L, weight, d=None):
        self.L, self.p = L, L.p
        c = L.cls
        self.c = c
        d = c if d is None else d
        self.d = d
        self.basis = [(k, i) for k in range(1, d + 1) for i in range(L.n) if weight[i] >= k]
        idx = {b: t for t, b in enumerate(self.basis)}
        br = {}
        for (a, (k, i)) in enumerate(self.basis):
            for (b, (l, j)) in enumerate(self.basis):
                if a >= b or k + l > d:
                    continue
                vec = L.br(np.eye(L.n, dtype=np.int64)[i], np.eye(L.n, dtype=np.int64)[j])
                dd = {}
                for r in np.nonzero(vec)[0]:
                    assert weight[r] >= k + l, "basis not adapted to the LCS"
                    dd[idx[(k + l, int(r))]] = int(vec[r])
                if dd:
                    br[(a, b)] = dd
        self.A = Lie(L.p, len(self.basis), br, min(L.cls, d))
        self.A.cls = L.cls  # BCH truncation at class c is valid (class <= c)
        self.n = len(self.basis)
        self.grade = np.array([k for k, i in self.basis])
        self.top = [t for t, (k, i) in enumerate(self.basis) if k == d]

    def E(self, s, X):
        """Evaluation E_s : cover -> L."""
        X = np.asarray(X, dtype=np.int64)
        out = np.zeros(X.shape[:-1] + (self.L.n,), dtype=np.int64)
        for t, (k, i) in enumerate(self.basis):
            out[..., i] += pow(s, k, self.p) * X[..., t]
        return out % self.p

    def dil(self, th, X):
        X = np.asarray(X, dtype=np.int64)
        f = np.array([pow(th, int(k), self.p) for k in self.grade], dtype=np.int64)
        return (X * f) % self.p

    def proj(self, X, lower):
        """Project cover-level-d coordinates to a lower Cover object (drop grades > lower.d)."""
        X = np.asarray(X, dtype=np.int64)
        idx = [self.basis.index(b) for b in lower.basis]
        return X[..., idx]

    def section_from(self, lower, Y):
        """Zero-insertion section lower -> self."""
        Y = np.asarray(Y, dtype=np.int64)
        out = np.zeros(Y.shape[:-1] + (self.n,), dtype=np.int64)
        for t, b in enumerate(lower.basis):
            out[..., self.basis.index(b)] = Y[..., t]
        return out


def all_elements(n, p):
    return np.array(list(itertools.product(range(p), repeat=n)), dtype=np.int64)


def encode(X, p):
    X = np.asarray(X, dtype=np.int64)
    n = X.shape[-1]
    w = p ** np.arange(n - 1, -1, -1, dtype=np.int64)
    return (X * w).sum(axis=-1)


# ---------------- example algebras ----------------
def heisenberg(p):
    # x, y, z ; [x,y]=z
    return Lie(p, 3, {(0, 1): {2: 1}}, 2, ["x", "y", "z"]), [1, 1, 2]


def filiform4(p):
    # x, y, z, u ; [x,y]=z, [x,z]=u   (class 3)
    return Lie(p, 4, {(0, 1): {2: 1}, (0, 2): {3: 1}}, 3, ["x", "y", "z", "u"]), [1, 1, 2, 3]


def free23(p):
    # x, y, z=[x,y], u=[x,z], w=[y,z]  (class 3)
    return Lie(p, 5, {(0, 1): {2: 1}, (0, 2): {3: 1}, (1, 2): {4: 1}}, 3, ["x", "y", "z", "u", "w"]), [1, 1, 2, 3, 3]
