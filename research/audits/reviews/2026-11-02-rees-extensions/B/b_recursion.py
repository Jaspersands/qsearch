"""Item B of research/REES_EXTENSIONS_CHECK_BRIEF.md: exact checks of Thm ring-to-field
(docs/papers/rees-hsp/main.tex:563-580) on finite Lie rings L = (+)_i Z/p^{e_i} of class c < p.

What is checked (all exact; integer lattices via Sage/FLINT HNF, group checks by brute force):

  (i)  L[p] = {x : px = 0} is an ideal; dim [L[p],L[p]] <= R; class(L[p]) <= min(c, R+1).
       Brute force on small rings: {g : g^p = 1} under the BCH product equals L[p].
  (ii) Lazard on mixed orders (brute force): the group generated by random elements equals
       the Lie closure of the same elements.
  (iii) The paper's outer recursion, run with a TRUTH oracle for the field core (the core is
       taken as given; only the outer algebra is tested):
         S = L, K = 0;  loop:  Om = {x in S : px in K};  call core on Om/K -> H1 = H cap Om;
         stop if H1 = K;  else N = idealizer of H1 in S;  S, K = N, H1.
       At every step: H <= N; H1 is an ideal of N; the section N/H1 has class <= c and
       derived additive rank <= R; Om/K (the core's input) has class <= min(c, R+1) and
       derived dimension <= R; the call count is <= b; the output equals log H.
       Brute force on small rings (first 12 subgroups of each): the group normalizer N_G(H1)
       equals the idealizer, and left cosets x*H1 (x in N) equal additive cosets x + H1.
       A second variant restarts in the ORIGINAL L each round (N = N_L(K)), as the source
       note does; both must return log H.

Run (a few minutes):
  /opt/anaconda3/envs/qsearch-cas/bin/python b_recursion.py
"""
import itertools
import random
import sys
import time

from sage.all import ZZ, FreeModule, matrix, vector, prod

random.seed(int(20261102))


# ----------------------------------------------------------------------------- rings
class Ring:
    def __init__(self, name, p, e, brackets):
        """brackets: dict (i, j) -> integer list, for i < j; antisymmetry implied."""
        self.name, self.p, self.e = name, p, list(e)
        self.n = n = len(e)
        self.E = max(e)
        self.mod = [p ** ei for ei in e]
        self.br = [[[0] * n for _ in range(n)] for _ in range(n)]
        for (i, j), v in brackets.items():
            self.br[i][j] = list(v)
            self.br[j][i] = [-x for x in v]
        self.V = FreeModule(ZZ, n)
        self.D = self.V.span([self.V.gen(i) * self.mod[i] for i in range(n)])
        self.full = self.V.span(self.V.gens())
        self.b = sum(e)

    def bracket(self, x, y):
        n = self.n
        out = [0] * n
        for i in range(n):
            if x[i] == 0:
                continue
            for j in range(n):
                if y[j] == 0:
                    continue
                c = x[i] * y[j]
                for k, v in enumerate(self.br[i][j]):
                    if v:
                        out[k] += c * v
        return vector(ZZ, out)

    def red(self, x):
        return tuple(int(x[i]) % self.mod[i] for i in range(self.n))

    # -- sanity of the input: well defined on the quotient, Jacobi, class
    def validate(self):
        V, D = self.V, self.D
        for i in range(self.n):
            for j in range(self.n):
                assert self.bracket(D.basis()[i], V.gen(j)) in D, (self.name, "not well defined")
        for i, j, k in itertools.product(range(self.n), repeat=3):
            a, b_, c = V.gen(i), V.gen(j), V.gen(k)
            jac = (self.bracket(a, self.bracket(b_, c)) + self.bracket(b_, self.bracket(c, a))
                   + self.bracket(c, self.bracket(a, b_)))
            assert jac in D, (self.name, "Jacobi fails")


# ----------------------------------------------------------------------------- lattice ops
def span(R, gens):
    return R.V.span(list(gens) + list(R.D.basis()))


def index(U, W):
    """[U : W] for full-rank lattices W <= U."""
    return abs(W.basis_matrix().det()) // abs(U.basis_matrix().det())


def logp(R, x):
    k = 0
    while x % R.p == 0 and x > 1:
        x //= R.p
        k += 1
    assert x == 1
    return k


def br_span(R, A, B, K):
    return span(R, [R.bracket(a, b) for a in A.basis() for b in B.basis()] + list(K.basis()))


def lie_closure(R, gens):
    L = span(R, gens)
    while True:
        L2 = L + br_span(R, L, L, R.D)
        if L2 == L:
            return L
        L = L2


def preimage_mult(R, S, K, scal):
    """{x in S : scal * x in K} as a lattice."""
    Sb, Kb = S.basis_matrix(), K.basis_matrix()
    M = Sb.stack(Kb) if False else matrix(ZZ, list(scal * Sb) + list(Kb))
    ker = M.left_kernel().basis_matrix()
    k = Sb.nrows()
    coeffs = ker[:, :k]
    return R.V.span(list(coeffs * Sb) + list(R.D.basis()))


def idealizer(R, S, Kl):
    """{x in S : [x, Kl] subset Kl}, by linear congruences."""
    Sb = S.basis_matrix()
    Kgens = Kl.basis()
    g = len(Kgens)
    n = R.n
    rows = []
    for s in Sb.rows():
        rows.append(sum([list(R.bracket(s, kk)) for kk in Kgens], []))
    Phi = matrix(ZZ, rows)
    Kb = Kl.basis_matrix()
    block = matrix(ZZ, g * Kb.nrows(), g * n)
    for t in range(g):
        block.set_block(t * Kb.nrows(), t * n, Kb)
    ker = Phi.stack(block).left_kernel().basis_matrix()
    coeffs = ker[:, :Sb.nrows()]
    return R.V.span(list(coeffs * Sb) + list(R.D.basis()))


def lcs_class(R, S, K):
    """Class of S/K and the lower central terms."""
    terms = [S]
    while not terms[-1].is_submodule(K):
        terms.append(br_span(R, S, terms[-1], K))
        if len(terms) > 60:
            raise RuntimeError("not nilpotent")
    return len(terms) - 1 if len(terms) > 1 else 0, terms


def d_add(R, U, K):
    """dim_Fp (U/K)/p(U/K) for K <= U."""
    pU = R.V.span([R.p * v for v in U.basis()]) + K
    return logp(R, index(U, pU))


def derived_rank(R, S, K):
    return d_add(R, br_span(R, S, S, K), K)


# ----------------------------------------------------------------------------- recursion
def run_recursion(R, H, c, Rk, nested=True):
    S, K = R.full, R.D
    calls = 0
    log = []
    while True:
        if S == K:
            break
        Om = preimage_mult(R, S, K, R.p)
        assert K.is_submodule(Om) and Om.is_submodule(S)
        assert br_span(R, S, Om, K).is_submodule(Om), "Omega not an ideal of the section"
        cl_om, _ = lcs_class(R, Om, K)
        dr_om = derived_rank(R, Om, K)
        assert cl_om <= min(c, Rk + 1) and cl_om < R.p, ("core class", cl_om)
        assert dr_om <= Rk, ("core derived dim", dr_om)
        calls += 1
        H1 = H.intersection(Om)            # TRUTH oracle for the field core
        assert K.is_submodule(H1)
        assert br_span(R, H1, H1, K).is_submodule(H1)
        if H1 == K:
            break
        base = S if nested else R.full
        N = idealizer(R, base, H1)
        assert H.is_submodule(N), "H not in the normalizer"
        assert br_span(R, N, H1, R.D).is_submodule(H1), "H1 not an ideal of N"
        cl_sec, _ = lcs_class(R, N, H1)
        dr_sec = derived_rank(R, N, H1)
        assert cl_sec <= c, ("section class", cl_sec)
        assert dr_sec <= Rk, ("section derived rank", dr_sec)
        log.append((logp(R, index(H1, R.D)),
                    cl_om, dr_om, cl_sec, dr_sec))
        S, K = N, H1
    assert K == H, "recursion returned the wrong subgroup"
    assert calls <= R.b, ("calls", calls, R.b)
    return calls, log


# ----------------------------------------------------------------------------- brute force
def bch_factory(R, c):
    E, p = R.E, R.p
    P = p ** E
    inv2 = pow(2, -1, P)
    inv12 = pow(12, -1, P) if c >= 3 else 0
    assert c <= 3

    nz = [[[(k, v) for k, v in enumerate(R.br[i][j]) if v] for j in range(R.n)] for i in range(R.n)]
    mods = R.mod

    def br(x, y):
        out = [0] * R.n
        for i, xi in enumerate(x):
            if xi:
                for j, yj in enumerate(y):
                    if yj:
                        for k, v in nz[i][j]:
                            out[k] += xi * yj * v
        return tuple(o % mods[k] for k, o in enumerate(out))

    def add(*vs):
        return tuple(sum(v[i] for v in vs) % R.mod[i] for i in range(R.n))

    def sc(k, v):
        return tuple((k * v[i]) % R.mod[i] for i in range(R.n))

    def mul(x, y):
        xy = br(x, y)
        terms = [x, y, sc(inv2, xy)]
        if c >= 3:
            terms += [sc(inv12, br(x, xy)), sc(-inv12, br(y, xy))]
        return add(*terms)

    def inv(x):
        return sc(-1, x)
    return mul, inv


def lattice_elements(R, U):
    """All elements of U/D as reduced tuples (small rings only)."""
    gens = [R.red(v) for v in U.basis()]
    seen = {tuple([0] * R.n)}
    frontier = list(seen)
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = tuple((x[i] + g[i]) % R.mod[i] for i in range(R.n))
                if y not in seen:
                    seen.add(y)
                    new.append(y)
        frontier = new
    return seen


def group_closure(mul, gens, n):
    seen = {tuple([0] * n)}
    frontier = list(seen)
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in seen:
                    seen.add(y)
                    new.append(y)
        frontier = new
    return seen


def brute_checks(R, c, Hs):
    mul, inv = bch_factory(R, c)
    allL = lattice_elements(R, R.full)
    zero = tuple([0] * R.n)

    def power(x, k):
        y = zero
        for _ in range(k):
            y = mul(y, x)
        return y
    om_group = {g for g in allL if power(g, R.p) == zero}
    om_lie = lattice_elements(R, preimage_mult(R, R.full, R.D, R.p))
    assert om_group == om_lie, "Omega_1 mismatch"
    checked_norm = 0
    for t, H in enumerate(Hs):
        gens = [R.red(v) for v in H.basis()]
        Hset = lattice_elements(R, H)
        assert group_closure(mul, gens, R.n) == Hset, "Lazard: group closure != Lie closure"
        if t >= 12:          # normalizer brute force on the first 12 subgroups only
            continue
        Om = preimage_mult(R, R.full, R.D, R.p)
        H1 = H.intersection(Om)
        H1set = lattice_elements(R, H1)
        Nlie = lattice_elements(R, idealizer(R, R.full, H1))
        Ngrp = {x for x in allL
                if all(mul(mul(x, h), inv(x)) in H1set for h in H1set)}
        assert Ngrp == Nlie, "group normalizer != idealizer"
        sample = random.sample(sorted(Nlie), min(40, len(Nlie)))
        for x in sample:
            left = {mul(x, h) for h in H1set}
            addc = {tuple((x[i] + h[i]) % R.mod[i] for i in range(R.n)) for h in H1set}
            assert left == addc, "left coset != additive coset"
        checked_norm += 1
    return len(allL), checked_norm


# ----------------------------------------------------------------------------- driver
def make_rings():
    rings = []
    # Heisenberg over Z/9 (p = 3, class 2)
    rings.append((Ring("Heis3(Z/9)", 3, (2, 2, 2), {(0, 1): (0, 0, 1)}), True))
    # [x,y] = p y on (Z/125)^2 (p = 5, class 3, R = 1)
    rings.append((Ring("[x,y]=py on (Z/125)^2", 5, (3, 3), {(0, 1): (0, 5)}), True))
    # [x,y] = p y on (Z/625)^2 (p = 5, class 4, R = 1)
    rings.append((Ring("[x,y]=py on (Z/625)^2", 5, (4, 4), {(0, 1): (0, 5)}), False))
    # mixed orders: x, z of order 25, y of order 5; [x,y] = 5z, [x,z] = y (class 3, R = 2)
    rings.append((Ring("mixed Z/25+Z/5+Z/25", 5, (2, 1, 2), {(0, 1): (0, 0, 5), (0, 2): (0, 1, 0)}), True))
    # strictly upper triangular 4x4 over Z/25 (p = 5, class 3, R = 3); basis e12,e13,e14,e23,e24,e34
    idx = {(1, 2): 0, (1, 3): 1, (1, 4): 2, (2, 3): 3, (2, 4): 4, (3, 4): 5}
    br = {}
    for (a, b_), i in idx.items():
        for (c_, d_), j in idx.items():
            if i < j:
                v = [0] * 6
                if b_ == c_:
                    v[idx[(a, d_)]] += 1
                if d_ == a:
                    v[idx[(c_, b_)]] -= 1
                if any(v):
                    br[(i, j)] = tuple(v)
    rings.append((Ring("n4(Z/25)", 5, (2,) * 6, br), False))
    # mixed-order section-like ring: Heis over Z/27 x Z/9 x Z/3 at p = 3? class 2 needs [x,y]=z
    # with ord z | gcd: x order 27, y order 9, z order 9, [x,y] = z (class 2, R = 1)
    rings.append((Ring("Heis mixed 27,9,9 (p=3)", 3, (3, 2, 2), {(0, 1): (0, 0, 1)}), False))
    return rings


def random_H(R, k):
    gens = [vector(ZZ, [random.randrange(R.mod[i]) for i in range(R.n)]) for _ in range(k)]
    # bias towards torsion-heavy elements as well
    gens = [g * (R.p ** random.randrange(0, R.E)) if random.random() < 0.4 else g for g in gens]
    return lie_closure(R, gens)


def main():
    t0 = time.time()
    total_H = 0
    for R, brute in make_rings():
        R.validate()
        c, _ = lcs_class(R, R.full, R.D)
        Rk = derived_rank(R, R.full, R.D)
        assert c < R.p
        Om = preimage_mult(R, R.full, R.D, R.p)
        cl_om, _ = lcs_class(R, Om, R.D)
        dr_om = derived_rank(R, Om, R.D)
        assert br_span(R, R.full, Om, R.D).is_submodule(Om)
        Hs = [R.D, R.full, Om, br_span(R, R.full, R.full, R.D)]
        Hs += [lie_closure(R, [R.V.gen(i)]) for i in range(R.n)]
        Hs += [random_H(R, k) for k in (1, 1, 2, 2, 3) for _ in range(12)]
        Hs = list({tuple(map(tuple, H.basis_matrix().rows())): H for H in Hs}.values())
        calls_nested, calls_restart, depths = [], [], []
        max_sec_class = max_core_class = max_sec_rank = 0
        for H in Hs:
            k1, log1 = run_recursion(R, H, c, Rk, nested=True)
            k2, _ = run_recursion(R, H, c, Rk, nested=False)
            calls_nested.append(k1)
            calls_restart.append(k2)
            depths.append(len(log1))
            for (_, clo, dro, cls, drs) in log1:
                max_core_class = max(max_core_class, clo)
                max_sec_class = max(max_sec_class, cls)
                max_sec_rank = max(max_sec_rank, drs)
        total_H += len(Hs)
        msg = (f"{R.name}: p={R.p} b={R.b} class={c} R={Rk}; L[p]: dim={R.n} class={cl_om} "
               f"derived={dr_om} (<= min(c,R+1)={min(c, Rk + 1)}); subgroups H tested={len(Hs)}; "
               f"calls nested max={max(calls_nested)} restart max={max(calls_restart)} (cap b={R.b}); "
               f"max core class met={max_core_class}, max section class={max_sec_class} (<= c), "
               f"max section derived rank={max_sec_rank} (<= R)")
        if brute:
            size, nn = brute_checks(R, c, Hs)
            msg += f"; brute force on |G|={size}: Omega_1, Lazard closure, normalizer=idealizer and cosets OK for {nn} H"
        print(msg + f" [{time.time() - t0:.0f}s]", flush=True)
    print(f"all assertions passed on {total_H} (ring, H) pairs in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    sys.exit(main())
