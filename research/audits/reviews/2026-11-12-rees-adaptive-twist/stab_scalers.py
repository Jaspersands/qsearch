"""Step (ii) of the adaptive scheme, exhaustively: for every K = H*gamma_c with H cyclic of order p
(every line of L/gamma_c), and (for dim <= 6) every cyclic H itself (every line of L), compute the
image of Stab_Aut(G)(K) (resp. Stab(H)) in GL(gamma_c), its order, and the scalars mu with
mu*I in the image.  Aut generators come from GAP/autpgrp via auts_gap.py (verified Lie auts).
Stabilizer images by Schreier generators (exact).  Row convention: v -> v @ M."""
import sys, os, json, itertools, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))

def norm_line(v, p):
    v = np.asarray(v) % p; nz = np.nonzero(v)[0]
    if len(nz) == 0: return None
    return tuple((v * pow(int(v[nz[0]]), -1, p) % p).tolist())

def all_lines(n, p):
    out = []
    for v in itertools.product(range(p), repeat=n):
        nz = [i for i, x in enumerate(v) if x]
        if nz and v[nz[0]] == 1: out.append(v)
    return out

def matinv(M, p):
    import sympy
    return np.array(sympy.Matrix(M.tolist()).inv_mod(p), dtype=np.int64) % p

def closure(gens, p, cap=3_000_000):
    """the matrix group generated by gens (tuples of tuples), BFS"""
    d = None; G = set(); frontier = []
    for g in gens:
        d = len(g)
    if d is None: return {()}
    I = tuple(tuple(int(i == j) for j in range(d)) for i in range(d))
    G = {I}; frontier = [I]; gl = [np.array(g, dtype=np.int64) for g in set(gens)]
    while frontier:
        nf = []
        for x in frontier:
            X = np.array(x, dtype=np.int64)
            for g in gl:
                y = tuple(map(tuple, (X @ g % p).tolist()))
                if y not in G:
                    G.add(y); nf.append(y)
                    if len(G) > cap: raise RuntimeError('closure too big')
        frontier = nf
    return G

def analyse(rec, mode):
    p, m, cls = rec['p'], rec['m'], rec['cls']; level = rec['level']
    d = sum(1 for l in level if l == cls); q = m - d
    gens = [np.array(M, dtype=np.int64) for M in rec['gens']]
    if mode == 'K':
        acts = [M[:q, :q] for M in gens]; n = q
    else:
        acts = [M for M in gens]; n = m
    zs = [M[q:, q:] for M in gens]
    zinv = [matinv(Z, p) for Z in zs]
    pts = all_lines(n, p); idx = {x: i for i, x in enumerate(pts)}
    P = np.array(pts, dtype=np.int64)
    perm = []
    for A in acts:
        img = P @ A % p
        perm.append([idx[norm_line(r, p)] for r in img])
    seen = [False] * len(pts); orbits = []
    I = np.eye(d, dtype=np.int64)
    for s in range(len(pts)):
        if seen[s]: continue
        # BFS with transversal (z-part only needed, plus inverse)
        tz = {s: I}; order = [s]; seen[s] = True; k = 0
        while k < len(order):
            x = order[k]; k += 1
            for gi, pm in enumerate(perm):
                y = pm[x]
                if y not in tz:
                    tz[y] = tz[x] @ zs[gi] % p; seen[y] = True; order.append(y)
        sch = set()
        tzinv = {}
        for x in order:
            for gi, pm in enumerate(perm):
                y = pm[x]
                if y not in tzinv: tzinv[y] = matinv(tz[y], p)
                S = tz[x] @ zs[gi] % p @ tzinv[y] % p
                sch.add(tuple(map(tuple, S.tolist())))
        img = closure(list(sch), p)
        mus = sorted(mu for mu in range(1, p)
                     if tuple(tuple(mu * int(i == j) for j in range(d)) for i in range(d)) in img)
        rep = pts[s]
        lev = level[next(i for i, x in enumerate(rep) if x)]
        orbits.append(dict(rep=rep, size=len(order), rep_level=lev, img_order=len(img), scalars=mus))
    return dict(d=d, npts=len(pts), orbits=orbits)

def global_scalars(rec):
    p = rec['p']; level = rec['level']; cls = rec['cls']; m = rec['m']
    d = sum(1 for l in level if l == cls); q = m - d
    img = closure([tuple(map(tuple, np.array(M)[q:, q:].tolist())) for M in rec['gens']], p)
    return len(img), sorted(mu for mu in range(1, p)
                            if tuple(tuple(mu * int(i == j) for j in range(d)) for i in range(d)) in img)

if __name__ == '__main__':
    files = sorted(f for f in os.listdir(os.path.join(HERE, 'auts')) if f.endswith('.json'))
    if sys.argv[1:]: files = [f for f in files if f.rsplit('_', 1)[0] in sys.argv[1:]]
    summary = []
    for f in files:
        rec = json.load(open(os.path.join(HERE, 'auts', f)))
        go, gs = global_scalars(rec)
        line = dict(alg=rec['name'], p=rec['p'], cls=rec['cls'], m=rec['m'], aut=rec['size'],
                    gamma_c_image=go, global_scalars=gs)
        dil = {pow(t, rec['cls'], rec['p']) for t in range(1, rec['p'])}
        line['dilation_scalars_theta^c'] = sorted(dil)
        for mode in ('K', 'H'):
            if mode == 'H' and rec['m'] > 6: continue
            r = analyse(rec, mode)
            hard = [o for o in r['orbits'] if o['rep_level'] == 1]
            line[mode] = dict(
                orbits=len(r['orbits']), points=r['npts'],
                hard_points=sum(o['size'] for o in hard),
                hard_no_scalar=sum(o['size'] for o in hard if o['scalars'] == [1]),
                hard_pm1_only=sum(o['size'] for o in hard if set(o['scalars']) <= {1, rec['p'] - 1}),
                hard_missing_dilation_scalars=sum(o['size'] for o in hard if not dil <= set(o['scalars'])),
                img_orders=sorted({o['img_order'] for o in r['orbits']}),
                hard_trivial_image=sum(o['size'] for o in hard if o['img_order'] == 1),
                any_no_scalar=sum(o['size'] for o in r['orbits'] if o['scalars'] == [1]),
                examples_no_scalar=[o for o in r['orbits'] if o['scalars'] == [1]][:3],
                scalar_sets=sorted({tuple(o['scalars']) for o in r['orbits']}))
        print(json.dumps(line), flush=True)
