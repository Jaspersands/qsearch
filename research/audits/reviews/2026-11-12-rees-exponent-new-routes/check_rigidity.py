"""Finite checks for Theorem R (rigidity of dilations) -- finite checks only.
(1) Heisenberg, p = 3, 5: every linear map T of L with T v in F_p v for all
    v not in gamma_2 is a scalar (brute force over all p^9 matrices).
(2) For heis/free3/fili4 at p = 5, 7: the Lie subalgebra of the Rees cover A
    generated by tL is all of A (so an endomorphism is fixed by tL)."""
import itertools
import numpy as np
from lie import algebra, rank_mod

def check_lines(p):
    m, C, gam = algebra("heis")
    vs = np.array([v for v in itertools.product(range(p), repeat=m) if v[0] or v[1]])
    sols = 0; scal = 0
    for T in itertools.product(range(p), repeat=m * m):
        T = np.array(T).reshape(m, m)
        Tv = (vs @ T.T) % p
        # Tv parallel to v  <=>  all 2x2 minors vanish
        ok = True
        for i, j in [(0, 1), (0, 2), (1, 2)]:
            if np.any((Tv[:, i] * vs[:, j] - Tv[:, j] * vs[:, i]) % p):
                ok = False; break
        if ok:
            sols += 1
            if np.array_equal(T, T[0, 0] * np.eye(m, dtype=int)):
                scal += 1
    return sols, scal

def generated_dim(name, p):
    m, C, gam = algebra(name); c = max(gam)
    # basis of A: (k, e_j) for j in gam[k]; generated subalgebra from tL
    cur = {1: [np.eye(m, dtype=np.int64)[j] for j in gam[1]]}
    for k in range(2, c + 1):
        vecs = []
        for i in range(1, k):
            for a in cur.get(i, []):
                for b in cur.get(k - i, []):
                    vecs.append(np.einsum('i,j,ijk->k', a, b, C) % p)
        cur[k] = vecs
    gen = sum(rank_mod(np.array(cur[k]), p) if cur[k] else 0 for k in cur)
    full = sum(len(gam[k]) for k in gam)
    return gen, full

if __name__ == "__main__":
    for p in (3, 5):
        s, sc = check_lines(p)
        print(f"heis p={p}: line-preserving maps on L = {s}, of which scalars = {sc}")
    for name in ("heis", "free3", "fili4"):
        for p in (5, 7):
            g, f = generated_dim(name, p)
            print(f"{name} p={p}: dim <tL> = {g}, dim A = {f}")
