"""Section 1.4 / 2 dependency: every subgroup H of (L,*) has log H a Lie subalgebra (subgroup form of
Lazard), and exp(hlift) is closed under the cover's group law (it is the subgroup cap_i E_{s_i}^{-1}(H)).

L1 random subgroups of G = (L,*) generated by 1-3 random elements (closure under * and inverse by
   BFS on group elements), compared with the Lie closure of the span of the generators.
L2 exhaustive on Heisenberg F_3: subgroups generated by every pair of elements.
L3 exp(hlift) as a SET of cover elements is closed under * and inverse (Heisenberg F_3, every
   subalgebra, all pairs; free(2,3) F_5 random pairs).
"""
import random
from itertools import product
from lie import *

rng = random.Random(3)


def group_closure(Gp, gens):
    S = {tuple([0] * Gp.L.m)}
    frontier = [tuple(g) for g in gens]
    gens = [list(g) for g in gens] + [Gp.neg(g) for g in gens]
    while frontier:
        new = []
        for x in frontier:
            if x in S:
                continue
            S.add(x)
            for g in gens:
                y = tuple(Gp.mul(list(x), g))
                if y not in S:
                    new.append(y)
        frontier = new
    return S


def run_L1(L, trials):
    Gp = Group(L)
    bad = 0
    for _ in range(trials):
        gens = [[rng.randrange(L.p) for _ in range(L.m)] for _ in range(rng.randrange(1, 4))]
        S = group_closure(Gp, gens)
        B = L.closure(gens)
        span = {tuple(v) for v in all_span(B, L.p)} if B else {tuple([0] * L.m)}
        if S != span:
            bad += 1
    print("L1 %s p=%d: %d random subgroups, mismatches with Lie closure: %d" % (L.name, L.p, trials, bad))
    return bad


def run_L2():
    L = heisenberg(3)
    Gp = Group(L)
    els = [list(t) for t in product(range(3), repeat=3)]
    bad = 0
    for a in els:
        for b in els:
            S = group_closure(Gp, [a, b])
            B = L.closure([a, b])
            span = {tuple(v) for v in all_span(B, 3)} if B else {(0, 0, 0)}
            bad += S != span
    print("L2 Heisenberg F_3, all 729 two-generator subgroups: mismatches %d" % bad)
    return bad


def run_L3():
    bad = 0
    L = heisenberg(3)
    cov = Cover(L)
    for hh in all_subspaces(3, 3):
        if not L.is_subalgebra(hh):
            continue
        hl = cov.hlift_coords(hh)
        els = [cov.from_coords(v) for v in (all_span(hl, 3) if hl else [[0] * cov.n])]
        for x in els:
            if hl and not elem_in_coords_space(cov, cov.neg(x), hl):
                bad += 1
            for y in els:
                if hl and not elem_in_coords_space(cov, cov.mul(x, y), hl):
                    bad += 1
    print("L3a Heisenberg F_3 all subalgebras, all pairs: failures %d" % bad)
    L = free23(5)
    cov = Cover(L)
    for _ in range(40):
        hh = L.closure([[rng.randrange(5) for _ in range(5)] for _ in range(rng.randrange(1, 3))])
        hl = cov.hlift_coords(hh)
        for _ in range(20):
            cx = [rng.randrange(5) for _ in hl]
            cy = [rng.randrange(5) for _ in hl]
            x = cov.from_coords([sum(a * b[i] for a, b in zip(cx, hl)) % 5 for i in range(cov.n)])
            y = cov.from_coords([sum(a * b[i] for a, b in zip(cy, hl)) % 5 for i in range(cov.n)])
            if not elem_in_coords_space(cov, cov.mul(x, y), hl):
                bad += 1
    print("L3 exp(hlift) closed under the cover product: failures %d" % bad)
    return bad


if __name__ == "__main__":
    t = run_L1(heisenberg(5), 60) + run_L1(free23(5), 40) + run_L2() + run_L3()
    print("TOTAL FAILURES:", t)
