"""Prop black-box (i),(iii) and Lemma tb-kernel on G = C_{p^2} x| C_p, p=3,5,7.

G elements (i,j) = a^i b^j, b a b^-1 = a^{1+p}. Phi : F_{2,2}(Z/p^2) -> G is
evaluated ONLY through the black-box multiplication, with the Lazard words of
theorems/universal_lazard_words.py (modulus p^2) and a Hall basis
w1=X1, w2=X2, w3=[X1,X2]: Phi(u) = Pi_+(Pi_+(h1^u1, h2^u2), h3^u3).
Checks: Phi is a homomorphism for BCH_2 on F (all pairs at p=3, sampled at
p=5,7), surjective, |ker| = p^6/p^3; Phi(F[p]) = mho_1(G) (order p) is strictly
inside Omega_1(G) (order p^2); b has no order-p preimage; Phi(pX1) = a^p;
Phi^{-1}(Omega_1) = {x : px in ker}; Phi(K cap F[p]) = H cap mho_1(G) for
every subgroup H; and ker pi is an ideal of F.
"""
import random, sys
from itertools import product
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[4]))
from theorems.universal_lazard_words import UniversalLazardWords

random.seed(3)

def run(p, exhaustive):
    P2 = p * p
    def mul(x, y):
        (i, j), (k, l) = x, y
        return ((i + k * pow(1 + p, j, P2)) % P2, (j + l) % p)
    e = (0, 0)
    G = [(i, j) for i in range(P2) for j in range(p)]
    def order(g):
        n, x = 1, g
        while x != e:
            x = mul(x, g); n += 1
        return n
    W = UniversalLazardWords(p, 2, e, mul, modulus=P2)
    a, b = (1, 0), (0, 1)
    h = [a, b, W.lie_bracket(a, b)]
    F = list(product(range(P2), repeat=3))
    def Phi(u):
        return W.linear_combination(h, list(u))
    # F_{2,2} over Z/p^2: [w1,w2] = w3, BCH_2(u,v) = u+v+[u,v]/2
    inv2 = pow(2, -1, P2)
    def fbr(u, v):
        return (0, 0, (u[0] * v[1] - u[1] * v[0]) % P2)
    def fbch(u, v):
        c = fbr(u, v)
        return tuple((x + y + inv2 * z) % P2 for x, y, z in zip(u, v, c))
    img = {u: Phi(u) for u in F}
    assert set(img.values()) == set(G), "surjective"
    pairs = product(F, F) if exhaustive else ((random.choice(F), random.choice(F)) for _ in range(4000))
    for u, v in pairs:
        assert img[fbch(u, v)] == mul(img[u], img[v]), "homomorphism"
    ker = [u for u in F if img[u] == e]
    assert len(ker) == P2**3 // (P2 * p)
    kset = set(ker)
    for u in ker:  # ideal
        for v in random.sample(F, 30):
            assert fbr(u, v) in kset
    Fp = [u for u in F if all((p * x) % P2 == 0 for x in u)]
    mho = {g for g in G if g[1] == 0 and g[0] % p == 0}
    omega = {g for g in G if order(g) in (1, p)}
    assert {img[u] for u in Fp} == mho and len(mho) == p and len(omega) == p * p
    assert all(img[u] != b for u in Fp), "b has an order-p preimage?!"
    assert img[(p, 0, 0)] == (p, 0), "Phi(pX1) = a^p"
    pre_omega = {u for u in F if img[u] in omega}
    assert pre_omega == {u for u in F if tuple(p * x % P2 for x in u) in kset}
    # every subgroup H of G (generated by <= 2 elements suffices: G is 2-generated)
    subs = set()
    for x in G:
        for y in G:
            S, fr = {e}, [e]
            while fr:
                nf = []
                for s in fr:
                    for g in (x, y):
                        t = mul(s, g)
                        if t not in S:
                            S.add(t); nf.append(t)
                fr = nf
            subs.add(frozenset(S))
    for H in subs:
        K = {u for u in F if img[u] in H}
        assert {img[u] for u in Fp if u in K} == set(H) & mho
    # generator orders and the exponent rule of Lemma tb-sylow(c)
    assert max(order(a), order(b)) == max(order(g) for g in G) == P2
    return len(subs), W.multiplication_calls

for p, ex in [(3, True), (5, False), (7, False)]:
    n, calls = run(p, ex)
    print(f"p={p}: all identities hold; {n} subgroups checked; multiplications used {calls}")
