"""Relative common-core Cech complex and phase-sensitive Laplacian audit.

For orientation ranges ``U_e`` define the common-core coefficient spaces

    C_p = direct_sum_{|F|=p+1} K_F,
    K_F = intersection_{e in F} U_e,                       (1)

starting with pair cores in ``C_1``.  The boundary is the alternating sum of
the exact inclusion intertwiners from ``K_F`` to each codimension-one face.
If ``D_1`` denotes the
pair-relation synthesis into one physical copy per leaf, then

    D_(p-1) D_p = 0,       G_1 D_2 = 0,
    G_1 = D_1^* D_1.                                      (2)

Thus ``H_1=ker D_1 / im D_2`` measures pair-relation cycles not generated by
higher common cores.  On a Boolean affine atom, (1) is the ordinary simplex
chain complex: its exact cycle quotient is a graph Laplacian with a constant
positive gap.  This preserves signs and phases that absolute-value weighted
graphs discard.

The finite controls below include a dense S6 plane where the sign-blind
comparison is inconclusive and an eight-orientation affine cube containing
that plane plus exposed noncommuting pair cores.  Their pair-cycle complexes
are exact and constant-conditioned.  This is a finite prototype, not an all-n
exactness, full augmented-dependency exactness, or efficient-transform theorem.
"""

