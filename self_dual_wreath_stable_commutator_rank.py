"""Stable-partition rank and natural-mass audit for mixed commutator kernels.

Stable partitions with bounded boxes below the first row have character
polynomials and are the most plausible low-complexity sector for a four-class
commutator contraction. This module tests that shortcut in two ways:

* on finite S_n controls, it computes exact modular ranks of the Hadamard
  algebra generated by physical third-moment features on the refined
  (r,q,r^-1q,[r,q]) class kernel;
* at growing n, it computes the exact Plancherel mass of partitions with at
  most b boxes below the first row.

The physical wreath irrep label law is an unordered pair of independent
Plancherel partitions after equal signs are summed. Thus a bounded-tail source
set has one-copy physical mass equal to the square of its Plancherel mass.
For every fixed b this is poly(n)/n! per source and vanishes. A stable-sector
recoupling rule cannot establish a typical-sector decoder.
"""

