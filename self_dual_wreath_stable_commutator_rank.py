def bounded_tail_partitions(
    n: int,
    tail_budget: int,
) -> tuple[tuple[int, ...], ...]:
    if n < 1:
        raise ValueError("n must be positive")
    if tail_budget < 0:
        raise ValueError("tail_budget must be nonnegative")
    result = []
    for tail_size in range(min(tail_budget, n - 1) + 1):
        tails = ((),) if tail_size == 0 else integer_partitions(tail_size)
        for tail in tails:
            first = n - tail_size
            if tail and first < tail[0]:
                continue
            result.append((first, *tail))
    return tuple(sorted(set(result), reverse=True))


def stable_physical_descriptors(
    n: int,
    tail_budget: int,
) -> tuple[PhysicalWreathIrrepDescriptor, ...]:
    partitions = bounded_tail_partitions(n, tail_budget)
    descriptors: list[PhysicalWreathIrrepDescriptor] = []
    for partition in partitions:
        descriptors.append(equal_pair_descriptor(partition, 1))
        descriptors.append(equal_pair_descriptor(partition, -1))
    for left_index, left in enumerate(partitions):
        for right in partitions[left_index + 1 :]:
            descriptors.append(unequal_pair_descriptor(left, right))
    return tuple(descriptors)


def physical_third_feature(
    descriptor: PhysicalWreathIrrepDescriptor,
    quadruple: ClassQuadruple,
) -> int:
    alpha, beta, gamma, commutator = quadruple
    if descriptor.kind == "equal-pair-extension":
        partition = descriptor.left_partition
        return (
            descriptor.dimension
            + 3 * descriptor.bridge_character
            + symmetric_character(partition, alpha) ** 2
            + symmetric_character(partition, beta) ** 2
            + symmetric_character(partition, gamma) ** 2
            + int(descriptor.sign or 0)
            * symmetric_character(partition, commutator)
        )
    return (
        descriptor.dimension
        + 2
        * symmetric_character(descriptor.left_partition, alpha)
        * symmetric_character(descriptor.right_partition, alpha)
        + 2
        * symmetric_character(descriptor.left_partition, beta)
        * symmetric_character(descriptor.right_partition, beta)
        + 2
        * symmetric_character(descriptor.left_partition, gamma)
        * symmetric_character(descriptor.right_partition, gamma)
    )


def _insert_modular_vector(
    vector: Iterable[int],
    basis: dict[int, dict[int, int]],
    prime: int,
) -> bool:
    sparse = {
        index: value % prime
        for index, value in enumerate(vector)
        if value % prime
    }
    while sparse:
        pivot = min(sparse)
        pivot_value = sparse[pivot]
        if pivot not in basis:
            inverse = pow(pivot_value, -1, prime)
            basis[pivot] = {
                index: value * inverse % prime
                for index, value in sparse.items()
                if value % prime
            }
            return True
        row = basis[pivot]
        for index, value in row.items():
            reduced = (
                sparse.get(index, 0) - pivot_value * value
            ) % prime
            if reduced:
                sparse[index] = reduced
            elif index in sparse:
                del sparse[index]
    return False


def audit_stable_feature_rank(
    n: int,
    tail_budget: int = 2,
    maximum_degree: int = 4,
    prime: int = MODULAR_PRIME,
) -> StableFeatureRankRecord:
    kernel = refined_commutator_kernel(n)
    support = tuple(quadruple for quadruple, _ in kernel)
    descriptors = stable_physical_descriptors(n, tail_budget)
    features = [
        tuple(
            physical_third_feature(descriptor, quadruple)
            for quadruple in support
        )
        for descriptor in descriptors
    ]
    basis: dict[int, dict[int, int]] = {}
    _insert_modular_vector((1,) * len(support), basis, prime)
    ranks = []
    monomial_count = 1
    for degree in range(1, maximum_degree + 1):
        for indices in itertools.combinations_with_replacement(
            range(len(features)), degree
        ):
            vector = [
                math.prod(features[index][row] for index in indices)
                for row in range(len(support))
            ]
            _insert_modular_vector(vector, basis, prime)
            monomial_count += 1
            if len(basis) == len(support):
                break
        ranks.append(len(basis))
        if len(basis) == len(support):
            ranks.extend(
                [len(basis)] * (maximum_degree - degree)
            )
            break
    rank = len(basis)
    return StableFeatureRankRecord(
        n=n,
        tail_budget=tail_budget,
        stable_partition_count=len(
            bounded_tail_partitions(n, tail_budget)
        ),
        physical_descriptor_count=len(descriptors),
        refined_kernel_support_count=len(support),
        maximum_degree=maximum_degree,
        monomial_count=monomial_count,
        modular_rank_by_degree=ranks,
        final_modular_rank=rank,
        final_rank_fraction=round(
            rank / len(support) if support else 0.0,
            12,
        ),
        full_kernel_separated=rank == len(support),
        status=(
            "stable-feature-algebra-saturates-finite-kernel"
            if rank == len(support)
            else "stable-feature-algebra-finite-low-rank-control"
        ),
    )


def stable_source_plancherel_mass(
    n: int,
    tail_budget: int,
) -> Fraction:
    numerator = sum(
        hook_length_dimension(partition) ** 2
        for partition in bounded_tail_partitions(n, tail_budget)
    )
    return Fraction(numerator, math.factorial(n))


def _fraction_log2(value: Fraction) -> float:
    if value <= 0:
        return -math.inf
    return math.log2(value.numerator) - math.log2(value.denominator)


def stable_mass_record(
    n: int,
    tail_budget: int,
) -> StableMassRecord:
    source_mass = stable_source_plancherel_mass(n, tail_budget)
    physical_mass = source_mass * source_mass
    copy_count = math.ceil(math.log2(math.factorial(n)))
    log_source = _fraction_log2(source_mass)
    log_physical = 2 * log_source
    return StableMassRecord(
        n=n,
        tail_budget=tail_budget,
        stable_partition_count=len(
            bounded_tail_partitions(n, tail_budget)
        ),
        threshold_copy_count=copy_count,
        exact_source_plancherel_mass=str(source_mass),
        log2_source_plancherel_mass=round(log_source, 12),
        exact_one_copy_physical_label_mass=str(physical_mass),
        log2_one_copy_physical_label_mass=round(log_physical, 12),
        log2_all_threshold_labels_stable_mass=round(
            copy_count * log_physical,
            12,
        ),
        fixed_tail_mass_vanishes=True,
        typical_sector_coverage=False,
        status="bounded-tail-plancherel-mass-vanishes",
    )


