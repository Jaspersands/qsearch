def _identity_wreath(n: int) -> WreathElement:
    identity = tuple(range(n))
    return identity, identity, 0


def bridge_generated_subgroup(n: int) -> tuple[WreathElement, ...]:
    if n < 2:
        raise ValueError("n must be at least two")
    bridges = tuple(
        bridge_element(permutation)
        for permutation in itertools.permutations(range(n))
    )
    identity = _identity_wreath(n)
    discovered = {identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for bridge in bridges:
            product = wreath_multiply(current, bridge)
            if product not in discovered:
                discovered.add(product)
                frontier.append(product)
    return tuple(discovered)


def validate_bridge_subgroup(n: int) -> BridgeSubgroupValidationRecord:
    factorial = math.factorial(n)
    generated_order = len(bridge_generated_subgroup(n))
    return BridgeSubgroupValidationRecord(
        n=n,
        wreath_group_order=2 * factorial * factorial,
        generated_subgroup_order=generated_order,
        expected_index_two_subgroup_order=factorial * factorial,
        index_two_verified=generated_order == factorial * factorial,
    )


def _endpoint_factor(element: WreathElement, bridge_count: int) -> Fraction:
    if is_identity_wreath(element):
        return Fraction(1)
    if is_bridge_class_element(element):
        return Fraction(1, bridge_count)
    return Fraction()


def exact_coupled_walk_moment(
    n: int,
    copy_count: int,
    moment_order: int,
) -> Fraction:
    if n < 2:
        raise ValueError("n must be at least two")
    if copy_count < 1:
        raise ValueError("copy_count must be positive")
    if moment_order < 1:
        raise ValueError("moment_order must be positive")
    bridges = tuple(
        bridge_element(permutation)
        for permutation in itertools.permutations(range(n))
    )
    identity = _identity_wreath(n)
    start = (identity,) * copy_count
    counts: dict[tuple[WreathElement, ...], int] = {start: 1}
    step_denominator = len(bridges) * (1 << copy_count)
    for _ in range(moment_order):
        next_counts: dict[tuple[WreathElement, ...], int] = {}
        for state, multiplicity in counts.items():
            for bridge in bridges:
                for mask in range(1 << copy_count):
                    target = tuple(
                        wreath_multiply(element, bridge)
                        if mask & (1 << index)
                        else element
                        for index, element in enumerate(state)
                    )
                    next_counts[target] = (
                        next_counts.get(target, 0) + multiplicity
                    )
        counts = next_counts
    numerator = sum(
        Fraction(multiplicity)
        * math.prod(
            _endpoint_factor(element, len(bridges))
            for element in state
        )
        for state, multiplicity in counts.items()
    )
    return numerator / step_denominator**moment_order


def validate_coupled_walk_moment(
    n: int,
    copy_count: int,
    moment_order: int,
) -> CoupledWalkValidationRecord:
    direct, _ = exact_source_averaged_normalized_moment(
        n=n,
        moment_order=moment_order,
        copy_count=copy_count,
    )
    dynamic = exact_coupled_walk_moment(
        n=n,
        copy_count=copy_count,
        moment_order=moment_order,
    )
    return CoupledWalkValidationRecord(
        n=n,
        copy_count=copy_count,
        moment_order=moment_order,
        bridge_sequence_count=math.factorial(n) ** moment_order,
        direct_word_map_moment=str(direct),
        coupled_walk_dynamic_moment=str(dynamic),
        exact_match=direct == dynamic,
    )


def _log2_add(left: float, right: float) -> float:
    high = max(left, right)
    low = min(left, right)
    if high == -math.inf:
        return high
    return high + math.log2(1 + 2 ** (low - high))


def coupled_scaling_record(
    n: int,
    copy_count: int,
    moment_order: int,
    second_moment_eigenvalue_scale: float,
) -> CoupledWalkScalingRecord:
    factorial = math.factorial(n)
    log2_factorial = math.lgamma(n + 1) / math.log(2)
    stationary_log2 = copy_count * (1 - 2 * log2_factorial)
    transient_log2 = (
        moment_order * math.log2(Fraction(3, 4))
        + 0.5 * copy_count * math.log2(1 + Fraction(1, factorial))
    )
    upper_log2 = _log2_add(stationary_log2, transient_log2)
    root_log2 = upper_log2 / moment_order
    second_scale_log2 = (
        math.log2(second_moment_eigenvalue_scale)
        if second_moment_eigenvalue_scale > 0
        else -math.inf
    )
    return CoupledWalkScalingRecord(
        n=n,
        copy_count=copy_count,
        moment_order=moment_order,
        coupled_nonconstant_spectral_radius_upper_bound=0.75,
        coupled_spectral_gap_lower_bound=0.25,
        log2_stationary_kth_moment=stationary_log2,
        log2_transient_error_upper_bound=transient_log2,
        log2_transient_to_stationary_ratio_upper_bound=(
            transient_log2 - stationary_log2
        ),
        log2_coupled_kth_moment_upper_bound=upper_log2,
        log2_normalized_moment_root_upper_bound=root_log2,
        log2_second_moment_eigenvalue_scale=second_scale_log2,
        log2_root_to_second_moment_scale_gap=(
            root_log2 - second_scale_log2
        ),
        stationary_scale_reached_at_certificate_order=(
            transient_log2 <= stationary_log2
        ),
        typical_all_unequal_conditioning_required=True,
        status=(
            "constant-gap-coupled-contraction-"
            "rare-equal-sector-contamination-open"
        ),
    )


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        payload = json.loads(path.read_text())
    except (json.JSONDecodeError, OSError):
        return {}
    return payload if isinstance(payload, dict) else {}


