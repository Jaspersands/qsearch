"""Constant-gap contraction for the shared-generator wreath word walk.

The natural k-copy moment word map can be viewed as a Markov chain on H_n^k,
where H_n is the subgroup generated by the bridge conjugacy class C_n.  At
each step the chain samples c uniformly from C_n and independently either
multiplies or does not multiply each coordinate by c.  Its transition
operator is

    M_k = E_c tensor_i (I + R_c) / 2.

Each bridge is an involution, so every factor P_c=(I+R_c)/2 is an orthogonal
projection.  On any tensor sector with a nonconstant coordinate j,

    tensor_i P_c <= P_c^(j).

The one-coordinate bridge walk has nonconstant spectrum at most 3/4.
Consequently M_k has a k-independent spectral gap of at least 1/4 on the
orthogonal complement of the constants.

For f=1_e+1_C/|C| and a_m the single-label subset word statistic, this gives

    |E[a_m^k] - (2/(n!)^2)^k|
        <= (3/4)^m (1 + 1/n!)^(k/2).

This is a genuine all-order coupled-walk contraction.  It is not yet the
needed typical-source moment theorem: at the certificate order the transient
term still dominates the stationary term, while the stationary term itself
comes from exponentially rare equal one-dimensional source sectors.
"""

