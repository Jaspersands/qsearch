"""Exact maximal-outlier exclusion for affine orientation nodes.

Let ``T`` be a coordinate-aligned affine subcube of the orientation cube with
``d`` varying source pairs.  Lift the target and source slots to regular
representations.  Coordinates with the same membership function on ``T``
move diagonally together.  There are exactly

    r = 2d + 1

distinct nonempty membership functions: the constant function and the two
complementary coordinate functions for every varying pair.  Their incidence
matrix has binary rank ``d+1``.

For ``G=S_n``, ``n>=5``, the subgroup generated by the orientation diagonals
contains an independent ``A_n`` on every membership block.  Its remaining
sign vectors are exactly the row span of the incidence matrix.  Consequently

    |L_T| = |A_n|^(2d+1) 2^(d+1)
           = |S_n|^(2d+1) / 2^d.                         (1)

The normalized subgroup-projection walk has eigenvalue one precisely on the
``L_T``-invariant space, so its regular scalar mass is ``1/|L_T|``.  For the
physical node frame ``A_T=sum_(e in T) E_e``, eigenvalue ``|T|`` is equivalent
to a common vector in every ``Ran(E_e)``.

Every varying source slot is a singleton membership block.  Independent
``A_n`` on that block forces its ``S_n`` irrep to be trivial or sign.  Thus a
``d``-dimensional node can have the maximal eigenvalue only if all ``2d``
varying source irreps are one-dimensional.  Under independent Plancherel law,

    Pr[maximal outlier at a fixed node] <= (2/|S_n|)^(2d). (2)

There are ``2^(K-d)`` coordinate nodes of dimension ``d``.  Under global
source distinctness, (2) is impossible for ``d>=2`` because ``S_n`` has only
two one-dimensional irreps.  At ``d=1`` the varying pair must be the ordered
trivial/sign pair, giving the unconditioned numerator

    2^(K-1) * 2/|S_n|^2 = 2^K/|S_n|^2 < 2/|S_n|.         (3)

After conditioning, divide (3) by the global collision-free mass, which tends
to one.  Exact width-sized outliers therefore disappear simultaneously over
the natural hierarchy with factorially small failure probability.

This is not an upper-edge theorem.  It does not exclude eigenvalues
``(1-epsilon)|T|``, much less prove the required natural edge
``Theta(|T|/|S_n|)``.  Its value is to remove the most severe regular-master
outlier and to identify robust almost-invariance, rather than exact common
invariance, as the next subgroup-walk problem.
"""

