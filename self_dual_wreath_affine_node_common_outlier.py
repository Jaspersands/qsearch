def _compose(left: Permutation, right: Permutation) -> Permutation:
    return tuple(left[right[index]] for index in range(len(left)))


def coordinate_membership_columns(affine_dimension: int) -> tuple[int, ...]:
    """Return membership columns as bitsets over ``F_2^d`` orientations."""

    if affine_dimension < 0:
        raise ValueError("affine dimension must be nonnegative")
    orientation_count = 1 << affine_dimension
    full = (1 << orientation_count) - 1
    columns = [full]
    for coordinate in range(affine_dimension):
        one = sum(
            1 << orientation
            for orientation in range(orientation_count)
            if orientation & (1 << coordinate)
        )
        columns.extend((full ^ one, one))
    if len(set(columns)) != len(columns) or any(column == 0 for column in columns):
        raise ArithmeticError("coordinate membership columns must be distinct")
    return tuple(columns)


def _f2_rank(vectors: tuple[int, ...]) -> int:
    basis: dict[int, int] = {}
    for vector in vectors:
        value = vector
        while value:
            pivot = value.bit_length() - 1
            if pivot not in basis:
                basis[pivot] = value
                break
            value ^= basis[pivot]
    return len(basis)


def coordinate_incidence_rows(affine_dimension: int) -> tuple[int, ...]:
    columns = coordinate_membership_columns(affine_dimension)
    return tuple(
        sum(
            ((column >> orientation) & 1) << index
            for index, column in enumerate(columns)
        )
        for orientation in range(1 << affine_dimension)
    )


def affine_generated_subgroup_order(group_order: int, affine_dimension: int) -> int:
    if group_order < 2 or group_order % 2:
        raise ValueError("an even group order is required")
    pattern_count = 2 * affine_dimension + 1
    return (group_order // 2) ** pattern_count * (1 << (affine_dimension + 1))


def _orientation_embedding(
    element: Permutation,
    affine_dimension: int,
    orientation: int,
) -> ProductElement:
    identity = tuple(range(len(element)))
    output = [element]
    for coordinate in range(affine_dimension):
        selected = int(bool(orientation & (1 << coordinate)))
        output.extend(
            element if slot == selected else identity for slot in (0, 1)
        )
    return tuple(output)


def _product_compose(left: ProductElement, right: ProductElement) -> ProductElement:
    return tuple(_compose(a, b) for a, b in zip(left, right))


def exact_generated_subgroup_order(n: int, affine_dimension: int) -> int:
    """Enumerate the small finite control subgroup by breadth-first closure."""

    if n > 3 or affine_dimension > 2:
        raise ValueError("exact closure is restricted to S3 and d at most two")
    group = tuple(itertools.permutations(range(n)))
    identity_permutation = tuple(range(n))
    identity = (identity_permutation,) * (2 * affine_dimension + 1)
    generators = tuple(
        _orientation_embedding(element, affine_dimension, orientation)
        for orientation in range(1 << affine_dimension)
        for element in group
        if element != identity_permutation
    )
    discovered = {identity}
    frontier = deque((identity,))
    while frontier:
        current = frontier.popleft()
        for generator in generators:
            candidate = _product_compose(generator, current)
            if candidate not in discovered:
                discovered.add(candidate)
                frontier.append(candidate)
    return len(discovered)


def audit_affine_subgroup(
    n: int = 3,
    affine_dimension: int = 1,
) -> AffineSubgroupControl:
    rows = coordinate_incidence_rows(affine_dimension)
    predicted = affine_generated_subgroup_order(
        math.factorial(n),
        affine_dimension,
    )
    exact = exact_generated_subgroup_order(n, affine_dimension)
    pattern_count = len(coordinate_membership_columns(affine_dimension))
    rank = _f2_rank(rows)
    verified = bool(
        pattern_count == 2 * affine_dimension + 1
        and rank == affine_dimension + 1
        and exact == predicted
    )
    return AffineSubgroupControl(
        n=n,
        affine_dimension=affine_dimension,
        orientation_count=1 << affine_dimension,
        distinct_nonempty_membership_pattern_count=pattern_count,
        incidence_rank_over_f2=rank,
        predicted_generated_subgroup_order=predicted,
        exact_generated_subgroup_order=exact,
        generated_subgroup_formula_verified=verified,
        status=(
            "exact-affine-generated-subgroup-formula-verified"
            if verified
            else "affine-generated-subgroup-formula-failure"
        ),
    )


def _common_rank(left: np.ndarray, right: np.ndarray, tolerance: float) -> int:
    eigenvalues = np.linalg.eigvalsh(left + right)
    return int(np.count_nonzero(eigenvalues >= 2 - tolerance))


def audit_physical_singleton_necessity(
    n: int = 3,
    copy_count: int = 2,
    varying_pair_index: int = 0,
    *,
    tolerance: float = 1e-9,
) -> PhysicalCommonOutlierControl:
    if n != 3 or copy_count != 2 or varying_pair_index not in (0, 1):
        raise ValueError("the complete physical control uses S3 and two pairs")
    partitions = tuple(integer_partitions(n))
    one_dimensional = {(n,), (1,) * n}
    block_count = 0
    common_count = 0
    violations = 0
    maximum_residual = 0.0
    fixed_mask = 0
    left_mask = fixed_mask & ~(1 << varying_pair_index)
    right_mask = left_mask | (1 << varying_pair_index)
    for target in partitions:
        for sources in itertools.product(partitions, repeat=2 * copy_count):
            labels = tuple(
                (sources[2 * index], sources[2 * index + 1])
                for index in range(copy_count)
            )
            left = orientation_invariant_projector(target, labels, left_mask)
            right = orientation_invariant_projector(target, labels, right_mask)
            common = _common_rank(left, right, tolerance)
            maximum = float(np.linalg.eigvalsh(left + right)[-1])
            maximum_residual = max(
                maximum_residual,
                abs(maximum - 2.0) if common else max(0.0, maximum - (2 - tolerance)),
            )
            variable_sources = sources[
                2 * varying_pair_index : 2 * varying_pair_index + 2
            ]
            block_count += 1
            common_count += common > 0
            violations += bool(
                common > 0
                and any(source not in one_dimensional for source in variable_sources)
            )
    verified = violations == 0
    return PhysicalCommonOutlierControl(
        n=n,
        copy_count=copy_count,
        varying_pair_index=varying_pair_index,
        physical_block_count=block_count,
        common_outlier_block_count=common_count,
        singleton_one_dimensional_necessity_violation_count=violations,
        maximum_projector_sum_eigenvalue_residual=maximum_residual,
        exact_singleton_necessity_verified=verified,
        status=(
            "exact-singleton-membership-necessity-verified"
            if verified
            else "singleton-membership-necessity-failure"
        ),
    )


def common_outlier_scaling_record(n: int) -> CommonOutlierScalingRecord:
    if n < 2:
        raise ValueError("n must be at least two")
    log2_group = math.lgamma(n + 1) / math.log(2)
    copy_count = math.ceil(log2_group)
    group_order = math.factorial(n)
    independent_terms = [
        (1 << (copy_count - dimension))
        * (2 / group_order) ** (2 * dimension)
        for dimension in range(1, copy_count + 1)
    ]
    independent = math.fsum(independent_terms)
    distinct_numerator_log2 = copy_count - 2 * log2_group
    distinct_numerator = (
        2.0 ** distinct_numerator_log2
        if distinct_numerator_log2 > -1074
        else 0.0
    )
    independent_log2 = math.log2(independent) if independent > 0 else -math.inf
    return CommonOutlierScalingRecord(
        n=n,
        group_order_log2=log2_group,
        information_threshold_copy_count=copy_count,
        independent_all_dimension_union_upper_bound=independent,
        independent_all_dimension_union_upper_bound_log2=independent_log2,
        globally_distinct_event_numerator_upper_bound=distinct_numerator,
        globally_distinct_event_numerator_upper_bound_log2=distinct_numerator_log2,
        conditioned_bound_formula="2^K/(|S_n|^2 P_cf(n,K))",
        dimensions_at_least_two_impossible_under_global_distinctness=True,
        exact_maximal_outlier_excluded_with_high_probability=True,
        near_maximal_outlier_excluded=False,
        natural_edge_proved=False,
        status="exact-common-outlier-rare-near-outlier-open",
    )


