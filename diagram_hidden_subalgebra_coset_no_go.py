def multiply(
    table: MultiplicationTable,
    left: Element,
    right: Element,
) -> Element:
    try:
        return table[(left, right)]
    except KeyError as error:
        raise ValueError("multiplication table is incomplete") from error


def validate_finite_monoid(
    elements: Iterable[Element],
    identity: Element,
    table: MultiplicationTable,
) -> tuple[Element, ...]:
    universe = tuple(elements)
    if not universe or len(set(universe)) != len(universe):
        raise ValueError("elements must be a nonempty duplicate-free collection")
    if identity not in universe:
        raise ValueError("identity is absent")
    element_set = set(universe)
    for left in universe:
        for right in universe:
            product = multiply(table, left, right)
            if product not in element_set:
                raise ValueError("multiplication is not closed")
            if multiply(table, identity, left) != left:
                raise ValueError("left identity law failed")
            if multiply(table, left, identity) != left:
                raise ValueError("right identity law failed")
            for third in universe:
                if multiply(table, product, third) != multiply(
                    table, left, multiply(table, right, third)
                ):
                    raise ValueError("associativity failed")
    return universe


def is_submonoid(
    subset: Iterable[Element],
    identity: Element,
    table: MultiplicationTable,
) -> bool:
    members = set(subset)
    return bool(members) and identity in members and all(
        multiply(table, left, right) in members
        for left in members
        for right in members
    )


def submonoid_is_group(
    subset: Iterable[Element],
    identity: Element,
    table: MultiplicationTable,
) -> bool:
    members = set(subset)
    if not is_submonoid(members, identity, table):
        raise ValueError("subset is not a submonoid")
    return all(
        any(
            multiply(table, element, candidate) == identity
            and multiply(table, candidate, element) == identity
            for candidate in members
        )
        for element in members
    )


def right_translates(
    elements: Iterable[Element],
    subset: Iterable[Element],
    table: MultiplicationTable,
) -> tuple[frozenset[Element], ...]:
    universe = tuple(elements)
    members = tuple(subset)
    return tuple(
        frozenset(multiply(table, element, member) for member in members)
        for element in universe
    )


def translate_partition_statistics(
    elements: Iterable[Element],
    subset: Iterable[Element],
    table: MultiplicationTable,
) -> tuple[int, bool, bool, int]:
    universe = tuple(elements)
    translates = right_translates(universe, subset, table)
    unique = tuple(dict.fromkeys(translates))
    overlapping_unequal = sum(
        bool(left & right) and left != right
        for index, left in enumerate(unique)
        for right in unique[index + 1 :]
    )
    equal_or_disjoint = overlapping_unequal == 0
    cover = set().union(*unique) == set(universe)
    return len(unique), equal_or_disjoint, cover, overlapping_unequal


def audit_monoid_submonoid(
    control_id: str,
    elements: Iterable[Element],
    identity: Element,
    table: MultiplicationTable,
    subset: Iterable[Element],
) -> FiniteMonoidCosetControl:
    universe = validate_finite_monoid(elements, identity, table)
    members = tuple(subset)
    if not is_submonoid(members, identity, table):
        raise ValueError("control subset is not a submonoid")
    group = submonoid_is_group(members, identity, table)
    translate_count, equal_or_disjoint, cover, overlap_count = (
        translate_partition_statistics(universe, members, table)
    )
    verified = equal_or_disjoint == group and cover
    return FiniteMonoidCosetControl(
        control_id=control_id,
        monoid_order=len(universe),
        submonoid_order=len(members),
        submonoid_is_group=group,
        right_translate_count=translate_count,
        right_translates_equal_or_disjoint=equal_or_disjoint,
        right_translates_cover_monoid=cover,
        overlapping_unequal_translate_pair_count=overlap_count,
        theorem_equivalence_verified=verified,
        status=(
            "group-coset-partition-control"
            if verified and group
            else (
                "nonunit-overlapping-translate-control"
                if verified
                else "finite-monoid-coset-control-failure"
            )
        ),
    )


def transformation_monoid(degree: int) -> tuple[tuple[tuple[int, ...], ...], dict]:
    if degree < 1:
        raise ValueError("degree must be positive")
    elements = tuple(itertools.product(range(degree), repeat=degree))
    table = {
        (left, right): tuple(left[right[index]] for index in range(degree))
        for left in elements
        for right in elements
    }
    return elements, table


def enumerate_submonoids(
    elements: tuple[Element, ...],
    identity: Element,
    table: MultiplicationTable,
) -> tuple[frozenset[Element], ...]:
    if len(elements) > 16:
        raise ValueError("exhaustive submonoid enumeration is capped at order 16")
    output = []
    others = tuple(element for element in elements if element != identity)
    for mask in range(1 << len(others)):
        subset = {identity}
        subset.update(
            others[index]
            for index in range(len(others))
            if mask & (1 << index)
        )
        if is_submonoid(subset, identity, table):
            output.append(frozenset(subset))
    return tuple(output)


def odd_double_factorial(value: int) -> int:
    output = 1
    for factor in range(1, value + 1, 2):
        output *= factor
    return output


def bell_number(value: int) -> int:
    if value < 0:
        raise ValueError("value must be nonnegative")
    row = [1]
    for size in range(1, value + 1):
        next_row = [row[-1]]
        for index in range(1, size + 1):
            next_row.append(next_row[-1] + row[index - 1])
        row = next_row
    return row[0]


def diagram_qft_scaling_boundary(
    diagram_order: int,
) -> DiagramQFTScalingBoundary:
    if diagram_order < 1:
        raise ValueError("diagram_order must be positive")
    brauer_dimension = odd_double_factorial(2 * diagram_order - 1)
    partition_dimension = bell_number(2 * diagram_order)
    brauer_log = math.log2(brauer_dimension)
    partition_log = math.log2(partition_dimension)
    return DiagramQFTScalingBoundary(
        diagram_order=diagram_order,
        brauer_basis_dimension_decimal=str(brauer_dimension),
        brauer_basis_dimension_log2=brauer_log,
        partition_basis_dimension_decimal=str(partition_dimension),
        partition_basis_dimension_log2=partition_log,
        necessary_brauer_loop_parameter_log2_from_published_factor=(
            2.0 * brauer_log
        ),
        necessary_partition_loop_parameter_log2_from_published_factor=(
            2.0 * partition_log
        ),
        ordinary_coset_partition_available_for_bridge_generated_subalgebra=False,
        efficient_qft_implies_hidden_problem_solver=False,
        module_spectrum_direction_not_killed_by_coset_no_go=True,
        status="naive-cosets-impossible-module-spectrum-model-open",
    )


