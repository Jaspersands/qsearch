"""Coset-partition no-go for naive hidden subalgebras of diagram algebras.

The hidden subgroup state construction relies on a group fact: right cosets
``gH`` are either equal or disjoint.  There is an exact finite-monoid boundary.
For a submonoid ``B`` of a finite monoid ``M``, the right translates ``aB``
form a partition of ``M`` if and only if every element of ``B`` is a unit, so
``B`` is a group.  Indeed, ``bB`` intersects ``B`` for every ``b in B``.  If
translates are equal-or-disjoint then ``bB=B``, hence ``bc=1`` for some
``c in B``; finiteness upgrades a one-sided inverse to a two-sided inverse.

Consequently, a hidden submonoid generated by a noninvertible bridge or reset
diagram cannot support ordinary HSP coset states.  Projectively rescaled bridge
and point generators are nonidentity idempotents, and therefore nonunits.  A
new oracle/state model based on ideals, Green relations, fixed factorizations,
or modules is required before a diagram-algebra QFT can be algorithmically
connected to a hidden problem.

The viable high-variance replacement is not another coset definition.  It is a
module-spectrum program: use Brauer/partition-algebra Fourier or generalized
Schur transforms to expose multiplicities or invariant subspaces in natural
orthogonal-tensor, permutation-tensor, code, or tensor-isomorphism instances.
That program remains proof-gated by a natural decision reduction, input-state
preparation, the published large-loop-parameter regime, and dequantization.
"""

